function parolaDelGiorno (dataint) {
    var res = "";

    var data = new Date(dataint);
	//data.setDate(data.getDate() + offset)
	var k = data.getDate() + "/" + (data.getMonth() + 1)
	var letture = lettureDelGiorno[k];
    for (var i in letture) {
		var lettura = letture[i];
		res += '<a href="laparola:' + lettura + '">';
        res += LaParola.normalizzaRiferimento(lettura);
		res += '</a> ';
	}

	setSpan('pdg_data', k);
	setSpan('pdg', res);
}
