<h2>Nuova Riveduta (2006)</h2>
<p id="Nuova Riveduta">Il testo &egrave; della quinta edizione del 2023.</p>
<p>La versione Nuova Riveduta 2006 si presenta come una revionse della precedente edizione del 1994.</p>
<p>La Nuova Riveduta &egrave; il frutto di un intenso lavoro di ricerca, di confronto sui testi ebraici e greci e di aggiornamento linguistico sulla base della Riveduta del 1924. Quest'ultima era stata realizzata da un comitato di esperti coordinati da Giovanni Luzzi ed era essa stessa il risultato di progressive revisioni che ebbero il loro impianto di origine nella Bibbia di Giovanni Diodati.</p>
<p>La Nuova Riveduta, dunque, si colloca nella linea della tradizione del testo tradotto da Giovanni Diodati nel 1607 a Ginevra; allo stesso tempo se ne distingue sia per l'aggiornamento linguistico, sia per la revisione operata sulla base di quei manoscritti greci ed ebraici che non erano disponibili all'epoca del Diodati stesso.</p>
<p>Alcune particolarit&agrave; del testo:<br />
1. alcuni brani sono in corsivo. Generalmente si tratta di indicazioni letterarie, ad esempio titoli presenti nel testo ebraico o greco (ad es. Salmo di Davide). Nel Nuovo Testamento i brani in corsivo sono quasi sempre citazioni dell'Antico Testamento.<br />
2. nel testo biblico sono state inserite delle parentesi quadre [ ], che racchiudono un termine o un brano assente in alcuni manoscritti ritenuti importanti.</p>
<p>L'ebraico utilizza tre nomi principali per indicare Dio. Sono state utilizzate le seguenti traduzioni:<br />
- il tetragramma, Yhwh (generalmente pronunciato Yahv&egrave;), il nome di Dio pi&ugrave; ricorrente nell'Antico Testamento, &egrave; stato reso con la veste grafica di "SIGNORE";<br />
- Adonai &egrave; stato tradotto con "Signore" (laddove ricorra Adoni Yhwh, abbiamo reso tale espressione con "il Signore, DIO");<br />
- El, Elohim, Eloha sono stati tradotti con "Dio".</p>

<h2>Nuova Riveduta (1994)</h2>
<p id="Nuova Riveduta 1994">Il testo &egrave; della decima edizione del 2004.</p>
<p>La Nuova Riveduta sui testi originali (1994), a cura della Societ&agrave; Biblica di Ginevra.</p>
<h3>Prefazione</h3>
<p>La Societ&agrave; Biblica di Ginevra &egrave; lieta di presentare questo testo dopo vent'anni d'intenso lavoro di ricerca e di confronto con i testi ebraici e greci.</p>
<p>Da un lato, esso non ha alcuna relazione con il testo della Bibbia tradotta da Giovanni Luzzi ma, dall'altro, risulta in continuit&agrave; con la <a href="#Luzzi">Riveduta</a> del 1924, fra i cui revisori si trovava Giovanni Luzzi come coordinatore. E poich&eacute; la Riveduta del 1924 &egrave; l'ultima revisione proveniente da una serie di revisioni che ebbero il loro impianto di origine nel testo di <a href="#Diodati">Diodati</a>, se ne conclude che la nostro Nuova Riveduta del 1994 si colloca nella linea della tradizione del testo tradotto da Giovanni Diodati nel 1607 a Ginevra. Ma, allo stesso tempo, se ne distingue sia per l'aggiornamento linguistico sia per la revisione fatta sulla base dei manoscritti greci ed ebraici pi&ugrave; antichi e prestigiosi che non erano disponibili settant'anni fa e, ancor meno, all'epoca del Diodati stesso.</p>
<p>Per quanto concerne la traduzione del Tetragramma (YHWH), abbiamo preferito ricorrere alla traduzione orale, quella corrispondente a &laquo;SIGNORE&raquo;. Questo termine risulta scritto in carattere maiuscoletto perch&eacute; il lettore possa distinguerlo facilmente dalla parola Signore che, invece, &egrave; la traduzione del termine ebraico &laquo;'adhonai&raquo;. Laddove ricorre &laquo;'adhonai Yhwh&raquo; abbiamo reso tale espressione con &laquo;il Signore, DIO&raquo; per evitare la ripetizione.</p>
<p>Ci &agrave; sembrato utile rendere la parola &laquo;Gentili&raquo; con termini equivalenti, quali &laquo;stranieri&raquo; e &laquo;pagani&raquo;, a seconda del contesto, affinch&eacute; ci fosse una comprensione immediata da parte di colui che legge.</p>
<p>Uno degli scopi che ci siamo prefissi &egrave; stato quello di non eliminare alcune asperit&agrave; proprie del testo biblico, cos&igrave; utili per conoscere profondamente il pensiero di Dio.</p>
<p>Cogliamo l'occasione per esprimere un vivo ringraziamento ai nostri esperti e studiosi delle sacre Scritture, che hanno dedicato molti anni a un confronto meticoloso con i testi originali, alla revisione del linguaggio e alle continue letture del testo definitivo.</p>
<p>Ringraziamo cordialmente anche gli esperti delegati dalla Societ&agrave; Biblica Italiana (Britannica e Forestiera) che hanno controllato con cura tutto il materiale elaborato.</p>
<p>Ma, soprattutto, ringraziamo Dio per la sua benevolenza e per il suo sostegno che non &egrave; mai venuto meno. Lui ha concesso, nella sua grazia, che giungesse a compimento il sacro dovere di tradurre la sua Parola fedelmente e in maniera comprensibile a ognuno nella nostra bella lingua italiana.
Nella convinzione di aver dato un importante contributo a favore dei lettori desiderosi di fare uno studio attento e rispettoso della Parola del Signore, ne raccomandiamo la lettura a tutti coloro che siano alla ricerca di Dio.</p>

