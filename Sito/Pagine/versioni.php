<h2>Note della Bibbia di Ginevra</h2>
<p id="CommentarioGinevra">Le note marginali della Bibbia di Ginevra sono un tesoro ereditato dalla Riforma Protestante.</p>
<p>Per quasi mezzo secolo, aiutarono il popolo di Inghilterra, Scozia e Irlanda a comprendere le Scritture: spiegavano concetti difficili con chiarezza, offrivano interpretazioni teologiche profonde, e mettevano nelle mani del lettore comune ci&ograve; che prima era riservato ai dotti.</p>
<p>Queste stesse note nutrirono la fede e la resistenza dei Puritani. Furono lette da Shakespeare, Bunyan e Milton, portate in America sulla Mayflower, e distribuite da Cromwell ai suoi soldati. Una legge scozzese del 1579 arriv&ograve; perfino a imporre che ogni capo famiglia con un certo reddito possedesse una Bibbia di Ginevra.</p>
