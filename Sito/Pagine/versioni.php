<h2>Nuova Diodati</h2>
<p id="Nuova Diodati">La Nuova Diodati, Revisione (1991), edizione La Buona Novella - Brindisi.</p>
<h3>Introduzione</h3>
<p>Questa revisione della Bibbia in lingua italiana, &egrave; il risultato di un grande desiderio e determinazione da parti di alcuni fratelli (cristiani evangelici) di offrire ai credenti, e a chiunque &egrave; assetato di verit&agrave;, uno strumento valido e affidabile per la lettura e studio della Parola di Dio. Questa revisione dovrebbe essere ancora pi&ugrave; utile ed importante per coloro che sono impegnati in un ministero.</p>
<p>I criteri che hanno guidato questo lavoro di revisione sono:</p>
<ol>
<li>La maggior fedelt&agrave; possibile ai testi, nell'originale greco per il Nuovo Testamento e nell'ebraico per l'Antico Testamento.</li>
<li>Chiarezza e correttezza nella lingua italiana, nella quale si &egrave; cercato di evitare termini arcaici, difficili, ambigui e oscuri.</li>
</ol>
<p>Per le suddette ragioni sono state messe in corsivo tutte le espressioni, parole, articoli e preposizioni, non contenute nel testo originale greco ed ebraico, ma ritenute utili per rendere pi&ugrave; chiaro ed esplicito il significato del testo.</p>
<p>A questo proposito ci teniamo a precisare che tutti i titoli in grassetto dei capitoli o frazioni di capitolo e dei Salmi stessi, tanto nell'Antico che nel Nuovo Testamento, non sono contenuti nel testo originale ebraico e greco, ma sono aggiunti e hanno lo scopo di indicare il soggetto o il contenuto, sovente in modo selettivo e non esauriente, dei vari capitoli e frazioni di capitolo...</p>
<p>Il testo critico usato &egrave; il &quot;Textus Receptus&quot;, quello sostanzialmente seguito dal Dr.&nbsp;Giovanni <a href="#Diodati">Diodati</a> e in seguito pure dai traduttori della &quot;King James Version&quot;, la versione della Bibbia che ha avuto maggior uso e diffusione nel mondo inglese.</p>
<p>I nomi di &quot;Dio&quot; e &quot;Iddio&quot; nella Diodati sono usati alternativamente pi&ugrave; per ragioni di assonanza che per ragioni inerenti al testo originale. Abbiamo perci&ograve; ritenuto opportuno adottare un criterio di maggiore chiarezza tanto per l'Antico che per il Nuovo Testamento. In questo modo, ogni volta che in italiano viene usato un nome di Dio, &egrave; perch&eacute; vi &egrave; una corrispondenza di un particolare nome di Dio tanto nel testo ebraico che greco.</p>
<p>Cos&igrave; per l'Antico Testamento abbiamo usato i seguenti nomi:</p>
<ul>
<li><em>DIO</em>, che rende il termine ebraico <em>Eloh&icirc;m</em>.</li>
<li><em>Dio</em> rende invece i termini ebraici <em>El&ocirc;ah</em>, <em>&Ecirc;l</em> e <em>&Ecirc;lahh</em> (aramaico, in Esdra e in Daniele).</li>
<li><em>Eterno</em> rende i termini ebraici <em>Jeh&ocirc;v&acirc;h</em> e <em>Yah</em>.</li>
<li><em>Signore</em> rende il termine ebraico <em>Ad&ocirc;n&acirc;i</em>, che letteralmente significa <em>mio Signore</em>.</li>
</ul>
<p>Per il Nuovo Testamento, i nomi pi&ugrave; importanti di Dio sono tre:</p>
<ul>
<li><em>Dio</em> che rende il termine greco <em>Theos</em>.</li>
<li><em>Signore</em> rende il termine greco <em>Kurios</em>.</li>
<li><em>Ges&ugrave;</em> rende il termine greco <em>Iesous</em>, che letteralmente significa <em>Jeh&ocirc;v&acirc;h</em> o <em>Dio salva</em>.</li>
</ul>

