<h2>Commento di Frederick Brotherton Meyer</h2>
<p id="CommentoMeyer">Frederick Brotherton Meyer era un pastore battista ed evangelista inglese impegnato nel ministero e nel lavoro di missione nei centri urbani su entrambe le sponde dell'Atlantico.
Questo commentario, pubblicato dal 1914 al 1918 in sette volumi, &egrave; di natura devozionale, con commenti concisi. Mancano 1Cronache e una parte di Numeri, su cui non ha scritto.
</p>
<p>Il testo italiano &egrave; stato tradotto dall'intelligenza artificiale.</p>

