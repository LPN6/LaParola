<a name="20260320"></a>
<h2>20 marzo 2026</h2>
<p>Alcuni nuovi testi sono stati aggiunti. Sul sito e nelle app ci sono i commentari di Calvino (attualmente Genesi e il Nuovo Testamento) e le <i>Note della Bibbia di Ginevra</i>.
Solo nelle app ci sono <i>Commentario sul testo greco delle epistole di Paolo</i> di John Eadie e <i>Istituzione della religione cristiana</i> di Giovanni Calvino.  
</p>

<a name="20260220"></a>
<h2>20 febbraio 2026</h2>
<p>Una traduzione interlineare contiene, nel caso del Nuovo Testamento, tutte le parole greche e poi le parole italiane che le traducono. C'&egrave; una traduzione interlineare in LaParola da molti anni, ma &egrave; stata completamente riscritta per correggere errori, aggiungere nuove caratteristiche, e utilizzare nuove tecnologie.
Fra altro, ci sono ora tre traduzioni interlineari, con le traduzioni alla Riveduta 2020, alla Nuova Riveduta, e alla Nuova Riveduta (1994).<p>
<p>La versione pi&ugrave; completa &egrave; sul sito a <a href="/interlineare/">https://www.laparola.net/interlineare/</a>. Pu&ograve; anche essere letta come testo continuo a <a href="/app/">https://www.laparola.net/app/</a> , scaricata e utilizzata in tutte le app di LaParola, o in un libro cartaceo (vedi "Altri formati" sulla pagina dell'interlineare sul sito).
</p>

<a name="20251110"></a>
<h2>10 novembre 2025</h2>
<p>Quattro nuovi commentari sono stati aggiunti al sito e alle app: il <i>Commentario completo di Matthew Henry</i>, le <i>Note di Albert Barnes sulla Bibbia</i>, il <i>Commento di Frederick Brotherton Meyer</i> (un commentario devozionale), e il <i>Tesoro di Davide</i>, un commentario sui Salmi di C.&nbsp;H.&nbsp;Spurgeon.</p>

<a name="20250901"></a>
<h2>01 settembre 2025</h2>
<p>Il testo della Nuova Riveduta, che in precedenza era un miscuglio di diverse edizioni, &egrave; stato sistemato per creare il testo di due versione.
La "Nuova Riveduta" &egrave; quella del 2006 (in modo particolare, la quinta edizione del 2023),
mentre la "Nuova Riveduta (1994)" &egrave; quella del 1994 (la decima edizione del 2004).</p>
<p>Un nuovo commentario, l'<i>Esposizione della Bibbia di Gill</i>, una traduzione di John Gill's Exposition of the Bible, un commentario espositivo del 1763 di 12.000 pagine.</p>

<a name="20250809"></a>
<h2>09 agosto 2025</h2>
<p>Un nuovo commentario, l'<i>Illustratore biblico</i>, una traduzione del Biblical Illustrator, un commentario del 1900 di 34.000 pagine.</p>

<a name="20250606"></a>
<h2>06 giugno 2025</h2>
<p>Un nuovo commentario, il <i>Commentario del pulpito</i>, una traduzione del Pulpit Commentary, un commentario del 1909 di 26.000 pagine.</p>

<a name="20250117"></a>
<h2>17 gennaio 2025</h2>
<p>Ci sono <a href="/riassunti/">riassunti</a> di ogni capitolo della Bibbia, generati da un'intelligenza articiale. I riassunti includono alcuni spunti per mettere in pratica il testo e alcune domande per la riflessione.
I riassunti possono essere letti su <a href="/riassunti/">questo sito</a>, oppure scaricati e installati nelle <a href="/programma/">app di LaParola</a>.</p>
<p>Per trovare in modo pi&ugrave; facile delle risorse per studiare un capitolo, ho creato un indice degli strumenti che si possono utilizzare sul sito. Basta iniziare dall'<a href="/bibbia/">elenco di libri della Bibbia</a> e scegliere il libro e poi il capitolo.</p>
<p>L'aspetto del sito &egrave; stato semplificato e modernizzato. Adesso si pu&ograve; trovare tutto nel menu superiore, o con uno schermo piccolo toccando l'icona in alto a sinistra.</p>

