<h1>Stare fermi insieme in Cristo (Filippesi 1:27-2:11)</h1>

<h2>Ripasso</h2>
<p><i>Quali cose che vedi nella vita di Paolo ti aiutano a capire la frase "vivere &egrave; Cristo"? (Fili 1:12 14,18,25)</i></p>
<p>Proclamava sempre il vangelo a tutti, rallegrandosi quando altri lo proclamavano, e aiutava altri a crescere nella fede in Cristo (cio&egrave;, vivere per lui).</p>

<p><i>Cosa pensano della morte quelli che possono dire "vivere &egrave; Cristo"?</i></p>
<p>Desiderano essere con Cristo, vedono la morte come un guadagno e meglio per loro (ma non per gli altri).</p>

<h2>Studio</h2>
<p><i>In questi versetti c'&egrave; il desiderio da parte di Paolo per i Filippesi di "stare fermi in uno stesso spirito" in Cristo. Non era scontato, nonostante il fatto che era una comunit&agrave; di cristiani di cui Paolo aveva buoni ricordi. Qual &egrave; il motivo di stare fermi in uno stesso spirito, e quali ne sono i benefici? (Fili 1:27-28)</i></p>
<p>Perch&eacute; &egrave; il comportamento degno del vangelo, di quelli per cui vivere &egrave; Cristo (cio&egrave;, sono missionali), che mettono il Vangelo e Ges&ugrave; il primo posto nella propria vita.</p>
<p>Aiuta ad essere uniti, sostenendosi nella fede, rafforzandosi per vivere e proclamare il vangelo del Signore Ges&ugrave; Cristo - nonostante la persecuzione e l'opposizione.</p>

<p><i>Che cosa vuol dire "stare fermi in uno stesso spirito" in pratica? (Fili 1:27, 2:2)</i></p>
<p>Come corpo di Cristo, non siamo divisi, n&eacute; combattiamo l'uno contro l'altro. Invece, siamo uno: in spirito, in mente, in amore, in proposito. E quello spirito &egrave; di vivere per Cristo. (Vedi anche Ef 4:4-6)</p>
<p>Il modo per fare questo &egrave; stato spiegato nello <a href="filippesi05.php">studio 5</a>.</p>

<p><i>Quali due cose ti sono state concesse? (Fili 1:29-30)</i></p>
<p>Credere in Cristo, e soffrire per lui. Cio&egrave;, la nostra fede in Cristo &egrave; un dono o privilegio, ma cos&igrave; anche la nostra sofferenza per Cristo. Dobbiamo considerare la sofferenza come una benedizione. Non solo &egrave; un onore soffrire per il suo nome (Col 1:24), ma dimostra che apparteniamo veramente a lui.</p>
<p>I soldati del passato aveva divise colorate, per essere riconsciuto dai compagni nonostante la confusione e la polvere creata da una battaglia. Oggi, le squadre sportive portano colori diversi, affinch&egrave; ogni giocatore pu&ograve; essere facilmente e velocemente identificato dai compagni.
La divisa per un Cristiano non &egrave; un vestito particolare, ma la sofferenza per Cristo. Non la sofferenza in generale, ma se qualcuno soffre perch&eacute; ha fatto dei sacrifici per promuovere l'opera di Ges&ugrave; Cristo in s&eacute; stesso o in altri, &egrave; un seguace di Cristo.</p> 
<p>C'&egrave; un approfondimento sulla sofferenza nello <a href="filippesi07.php">studio 7</a>.</p>

<p><i>Perch&eacute; non dobbiamo combattere l'uno contro l'altro? (Fili 2:1-2)</i></p>
<p>Siccome sei benedetto di essere in Cristo, non devi lottare ma essere unito. Altri si opporranno a te e ti faranno soffrire, ma in Cristo devi stare fermo insieme con gli altri in Cristo.</p>
<p>I milionari non si combattono per un euro; cos&igrave; noi che abbiamo il tesoro del vangelo non dobbiamo lottare per aver gli spiccioli come il potere, il nostro punto di vista accettato dagli altri, l'approvazione degli altri, eccetera.</p>

<p><i>Qual &egrave; il pericolo principale all'unit&agrave;, nonostante la benedizione in Cristo? (Fili 2:3)</i></p>
<p>Orgoglio ed egoismo (cio&egrave;, vivere per te stesso e non per Cristo). Agostino ha detto: "L'orgoglio &egrave; la madre di tutti i peccati". Orgoglio verso Dio ("Dio vuole che io faccio cos&igrave;, ma non lo voglio fare perch&eacute; penso che sia meglio un'altra cosa") e verso gli altri (che sar&agrave; approfondito nei prossimi versetti).</p>

<p><i>Per combattere contro l'orgoglio, che cosa ti insegna Paolo a fare? (Fili 2:3-4)</i></p>
<p>Non essere egoista, rivendicando i tuoi diritti, ma umile e un servo degli altri. Devi considerare gli altri pi&ugrave; importanti di te stesso, e considerare i loro interessi pi&ugrave; importanti dei tuoi.</p>
<p>Pensa ad un'altra persona della tua comunit&agrave;. Qual &egrave; il suo interesse / bisogno in questo momento? Come puoi pensare ad esso, magari rinunciando ad uno tuo?</p>
<p>C'&egrave; un approfondimento sulla grazia invece dell'orgoglio verso gli altri nello <a href="filippesi05.php">studio 5</a>.</p>
<p>C'&egrave; un approfondimento sul servizio nello <a href="filippesi08.php">studio 8</a>.</p>

<p><i>Quale esempio perfetto hai per vivere in questo modo? (Fili 2:5-8)</i></p>
<p>Paolo d&agrave; il Signore Ges&ugrave; come il perfetto esempio di umilt&agrave;. Ti esorta ad avere l'atteggiamento che aveva Cristo quando &egrave; venuto sulla terra e ha vissuto fra l'umanit&agrave;.</p>

<p><i>Che cosa ti colpisce dell'umilt&agrave; di Cristo?</i></p>
<p>Bench&eacute; sia Dio, non ha fatto valere la sua uguaglianza con il Padre.<br />
Bench&eacute; sia Dio, ha rinunciato a tutti i suoi diritti per diventare umano, e inoltre un servo.<br />
Bench&eacute; sia Dio, ha ubbidito al Padre ed &egrave; andato alla croce, morendo per noi.</p>

<p><i>Qual era il risultato dell'umilt&agrave; di Ges&ugrave;? (Fili 2:9-11)</i></p>
<p>Dio l'ha innalzato al posto superiore, e un giorno tutti riconosceranno che &egrave; il Signore - anche quelli che ti oppongono e ti fanno soffrire.</p>

<p><i>Che cosa vuol dire, "comportatevi in modo degno del vangelo di Cristo"? (Fili 1:27)</i></p>
<p>Essere come Cristo, altruistico e umile, un servo ad altri, ubbidiente a Dio. Sempre una vita missionale. Che cosa impari anche da Efes 4:1-3?</p>

<p><i>Qual &egrave; il risultato di vivere in questo "modo degno"? (Fili 1:27)</i></p>
<p>Non combatti pi&ugrave; contro gli altri per il tuo orgoglio ed egoismo, ma invece combatterai per il vangelo con gli altri in un mondo che &egrave; ostile, sostenendovi in questo grande compito.</p>

<p><i>Quale sar&agrave; la fine della nostra vita se viviamo in modo degno del vangelo?</i></p>
<p>Siamo sicuri della nostra salvezza (Fili 1:28), e un giorno saremo innalzati per essere con Cristo (1P 5:5-6).</p>

<h2>Riassunto</h2>
<p>Il segreto per stare fermi insieme &egrave; l'umilt&agrave; - mettere gli altri prima di te stesso, e soprattutto mettere Ges&ugrave; prima di te stesso. Il tuo esempio perfetto &egrave; Cristo; il tuo nemico principale non &egrave; quelli che ti si oppongono ma il tuo orgoglio ed egoismo.</p>

<h2>Versetto a memoria</h2>
<p>Filippesi 2:5: Abbiate in voi lo stesso sentimento che &egrave; stato anche in Cristo Ges&ugrave;.</p>


