<h1>Una vita di ubbidienza</h1>

<p>In Filippesi 2:12, l'ubbidienza era fondamentale per la santificazione, cio&egrave; per la vita del discepolo missionale. In questo studio rifletterai sulla tua ubbidienza a Cristo.</p>
<h2>Esempi di ubbidienza</h2>
<p><i>1. Noi che siamo diventati i figli di Dio, gli dobbiamo ubbidire sempre e in ogni cosa. Perch&eacute;? (Gv 10:27)</i></p>
<p>Perch&eacute; siamo le sue pecore.</p>
<p>Il testo non dice che le pecore devono ascoltarlo, ma semplicemente che le pecore ascoltano la voce di Ges&ugrave; e lo seguono. Ubbidire a Ges&ugrave; non &egrave; un dovere da aggiungere, ma una caratteristica di un cristiano che ascolta e ubbidisce di istinto.</p>
<p>Alcune caratteristiche del comportamento delle pecore possono aiutare a approfondire questa affermazione. Per esempio, le pecore seguono solo il proprio pastore sempre. Nella Palestina, le pecore appartenenti a diversi pastori sono messe nello stesso ovile di notte. La mattina, ogni pastore chiama le sue pecore per nome e conosce quelle che sono le sue. Anche se un altro pastore le chiama per nome, le pecore sanno distinguere la voce del proprio pastore e seguono solo lui. Vedi anche Gv 10:3-5. Puoi cercare altri esempi in Internet.</p>

<p><i>2. Ascoltare e seguire la voce di Ges&ugrave; vuole dire non soltanto ubbidire alle sue parole ma anche imitare la sua ubbidienza. Quale esempio di ubbidienza Ges&ugrave; ti d&agrave; in Gv 4:34; 8:29; Fili 2:8?</i></p>
<p>Il cibo di Ges&ugrave; era la sua ubbidienza, cio&egrave;, era quello che gli dava forza.</p>
<p>Ges&ugrave; pensava sempre di quello che avrebbe fatto piacere al Padre.</p>
<p>Ubbidienza totale, costi quello che costi.</p>

<p><i>3. Che cosa hai imparato quando hai seguito l'esempio di Ges&ugrave; e ubbidito a lui?</i></p>
<p>Forse conviene prima pensare di alcuni esempi concreti.</p>
<p>Poi, l'ubbidienza potrebbe sembrare un sacrificio e una perdita, ma in realt&agrave; ne traiamo un beneficio.</p>
<p>Se sei pronto ad ubbidire, Dio ti d&agrave; la saggezza e la forza necessarie per ubbidire.</p>
<p>La fede cresce attraverso l'ubbidienza.</p>

<h2>Le motivazioni dell'ubbidienza</h2>

<p><i>4. Anche se l'ubbidienza dovrebbe essere naturale, c'&egrave; anche una motivazione. Qual &egrave;? (Gv 14:15) L'ubbidienza potr&agrave; essere un peso? Qual &egrave; la differenza con l'ubbidienza per obbligo (come un militare) o per paura della punizione (come verso il codice stradale)?</i></p>
<p>L'ubbidienza viene dall'amore per Ges&ugrave;, come il frutto di questo rapporto. Cos&igrave; non &egrave; un peso, ma qualcosa che facciamo volentieri.</p>
<p>Di solito non superiamo il limite della velocit&agrave; perch&eacute; non vogliamo prendere la multa, non perch&eacute; amiamo gli altri autisti e pedoni e non vogliamo fare male a loro. Invece, in ogni azione e pensiero devi riflettere su quanto bene vuoi a Ges&ugrave; Cristo e vuoi il suo bene e onore.</p>
<p>Nello stesso modo, facciamo quello che il nostro coniuge vuole quando lo amiamo e vogliamo il suo bene, non solo quando lui/lei ama noi e quello che vuole &egrave; giusto secondo noi. Ci d&agrave; piacere rendere felice il coniuge, anche se ci costa, e non &egrave; un peso a causa dell'amore che abbiamo.</p>

<p><i>5. Alcuni non capiscono bene il rapporto fra l'ubbidienza e la fede. Sottovalutano l'importanza dell'ubbidienza perch&eacute; la salvezza &egrave; per fede, e pensano che sottolineare l'ubbidienza (opere) riduca l'importanza della fede. Qual &egrave; il rapporto fra l'ubbidienza e la fede in Giac 2:14-19?</i></p>
<p>La fede precede l'ubbidienza. L'ubbidienza &egrave; un risultato naturale della fede, anzi un componente naturale della fede, senza di cui la fede &egrave; morta (cio&egrave;, non &egrave; vera fede).</p>

<p><i>6. Qual &egrave; la differenza fra il legalismo e l'ubbidienza?</i></p>
<p>Il legalismo &egrave; il tentativo di soddisfare tutto le richieste divine (che sono spesso ma non necessariamente regole umane) per essere a posto con Dio, anche da parte di Cristiani che sono gi&agrave; salvati per fede. L'ubbidienza &egrave; fare quello che Dio vuole per amore di lui e per fede che &egrave; giusto vivere giusto perch&eacute; Dio &egrave; supremo.</p>

<p><i>7. Quale benedizione &egrave; promessa a quelli che ubbidiscono a causa del loro amore per il Signore (Gv 14:21)?</i></p>
<p>Sar&agrave; amato, e Ges&ugrave; si manifester&agrave; a lui. "Mi manifester&ograve; a lui" potrebbe essere non solo un'apparizione visibile, ma "lo benedir&ograve;" oppure "avr&ograve; un rapporto pi&ugrave; profondo con lui", eccetera.</p>

<h2>Una verifica personale dell'ubbidienza</h2>
<p><i>8. Come Ges&ugrave; insegna l'importanza dell'ubbidienza in Mt 7:24-27?</i></p>
<p>Nonostante le situazioni critiche nella vita (le difficolt&agrave;, la tentazione di fare il contrario), ubbidiamo. La caratteristica principale della vita cristiana non &egrave; la fede professata verbalmente ma l'ubbidienza (cio&egrave;, la fede praticata Giac 2:26)! &egrave; importante anche perch&eacute; ti fa sta in piedi e non cadere.</p>
<p>A volte, sembra che l'ubbidienza sia un sacrificio pi&ugrave; grande della disubbidienza. Ma alla fine, la disubbidienza ti costa molto di pi&ugrave;.</p>

<p><i>9. Scrivi una preghiera di ravvedimento per aver vissuto una vita disubbidiente anche quando hai confessato il tuo amore per il Signore con le labbra.</i></p>
<p>Chi guida lo studio dovrebbe pregare per uno spirito di ravvedimento per il gruppo, e dovrebbe essere un esempio nel suo ravvedimento.</p>

<h2>Riassunto</h2>
<p>L'ubbidienza &egrave; la risposta normale dei credenti, e un discepolo di Ges&ugrave; ubbidisce come Ges&ugrave; ha ubbidito. Falliamo sempre nella nostra ubbidienza, ma per questo motivo abbiamo Ges&ugrave; che porta il perdono!</p>

