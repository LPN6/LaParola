<h1>Guerra spirituale</h1>

<p><i>1. Leggete Gv 15:18-19 e descrivete il motivo che Ges&ugrave; d&agrave; per cui non possiamo evitare la guerra spirituale.</i></p>
<p>Il mondo &egrave; usato in diversi sensi nella Bibbia: qui &egrave; tutto il creato che si oppone a Dio.</p>
<p>Siccome apparteniamo a Ges&ugrave; e non al sistema del mondo, il mondo &egrave; antagonistico a noi nello stesso modo in cui si oppone a Dio.</p>

<p><i>2. Quali formi di opposizione dal mondo hai sperimentato?</i></p>
<p>Non sempre persecuzione, ma anche per esempio tentazione a conformarsi alla tendenza materialistica di comprare tante cose.</p>

<h2>Le strategie di Satana</h2>
<p><i>3. Quale avvertimento ci d&agrave; 1P 5:8-9 delle attivit&agrave; del diavolo?</i></p>
<p>Di vegliare perch&eacute; il diavolo &egrave; in giro, e di resistergli.</p>
<p>Domanda supplementare: Perch&eacute; il diavolo &egrave; paragonato ad un leone? &Egrave; forte e veloce, il re degli animali, attacca gli uomini, terrorizza la preda con il ruggito</p>
<p>Domanda supplementare: Quali sono alcuni esempi della strategia del diavolo che sono simili ad un leone ruggente? Opprime e perseguita la fede; fa che siamo oppressi da sentimenti di colpa, fallimento, disperazione e ferite; ci fa soffrire attaccando il corpo; ci rende amari attaccando famiglia e finanze.</p>

<p><i>4. Quali altre strategie (pi&ugrave; come una volpe che come un leone) usa Satana secondo 2Cor 11:14; Ap 20:10?</i></p>
<p>Si traveste da angelo di luce, e seduce come un falso profeta - cio&egrave;, imita Dio e i suoi servi.</p>
<p>Domanda supplementare: Quali sono alcuni esempi della strategia del diavolo che sono simili ad una volpe? Ci seduce a cercare piaceri materiali oppure esperienze mistiche invece della vita trasformata; ci rende critici verso altri credenti e la chiesa. Ci d&agrave; successo spirituale affinch&eacute; diventiamo orgogliosi.</p>

<p><i>5. In genere, il diavolo &egrave; come un leone per causare sofferenza e persecuzione, e come una volpe per creare la tentazione. Quale aspetto &egrave; pi&ugrave; comune oggi nella nostra societ&agrave;? A quale aspetto sei pi&ugrave; vulnerabile?</i></p>
<p>Per la maggior parte di noi, &egrave; la volpe.</p>

<h2>L'armatura cristiana</h2>
<p><i>6. Spiegate brevemente perch&eacute; le seguenti persone sono state sconfitte in una battaglia spirituale: Pietro (Mt 26:40-41), Imeneo (1Tim 1:19-20), Dema (2Tim 4:10).</i></p>
<p><b>Pietro:</b> non ha vegliato n&eacute; pregato per non cadere nella tentazione</p>
<p><b>Imeneo:</b> ha rinunciato alla fede e alla buona coscienza</p>
<p><b>Dema:</b> ha amato il mondo, e cos&igrave; non ha potuto resistere alla tentazione</p>
<p>Cio&egrave;, anche i responsabili possono essere sconfitti da Satana se trascurano l'armatura cristiana.</p>

<p><i>7. Leggete Efes 6:10-18. Quali sono i motivi per cui dobbiamo indossare tutta l'armatura nei versetti 10 e 11?</i></p>
<p>Per essere forti (con il potere per difenderci) e per resistere al diavolo.</p>

<p><i>8. Quali parti dell'armatura sono per l'autodifesa, per la protezione, per l'attacco, e per la guardia?</i></p>
<p><b>Autodifesa:</b> verit&agrave; (cintura), giustizia (corazza), zelo dal vangelo (calzatura), salvezza (elmo) - questi sono le cose essenziali che il credente deve ricercare, aggrappandosi alla verit&agrave; del vangelo e vivendo una vita degna della verit&agrave;</p>
<p><b>Protezione:</b> fede (scudo) - convinzione nella bont&agrave; di Dio e nell'adempimento delle sue promesse che ci protegge dalle bugie di Satana</p>
<p><b>Attacco:</b> parola di Dio (spada) - spada dello Spirito, non la nostra; dobbiamo meditare e approfondire le Scritture, affinch&eacute; lo Spirito possa usarla nella nostra vita</p>
<p><b>Guardia:</b> preghiera - per stare attenti e vegliare, sempre. Se non preghiamo, non siamo concentrati spiritualmente ed &egrave; pi&ugrave; facile per il diavolo attaccarci. Non dimenticare l'importanza della preghiera anche per combattere la preoccupazione nello <a href="filippesi17.php">studio precedente</a>.</p>

<p><i>9. Potete pensare di esempi nella tua vita dell'uso della fede per sconfiggere le bugie, dell'uso da parte dello Spirito della Parola di Dio nella nostra vita, e dell'uso della preghiera come guardia?</i></p>

<p><i>10. Ci sono dei buchi nella tua armatura? Quale aspetto trascuri di pi&ugrave; o &egrave; il pi&ugrave; debole?</i></p>

<h2>Certezza della vittoria spirituale</h2>
<p><i>11. Dobbiamo avere la certezza che prevarremo quando affrontiamo la guerra spirituale. Spiegate i motivi per la nostra fiducia da 1Cor 15:57; 1Gv 5:4-5.</i></p>
<p><b>1Cor 15:57</b>: Ges&ugrave; ha gi&agrave; vinto la morte (nel contesto di 1Cor 15) e Satana, e noi abbiamo la vittoria per mezzo di lui. Come gli Israeliti che sono avanzati dopo che Davide aveva ucciso Golia, combattiamo in una battaglia gi&agrave; vinta. Non significa che non cederemo mai alla tentazione o alla persecuzione, ma che nonostante le nostre cadute ritorneremo sempre alla grazia e saremo con Dio per sempre.</p>
<p><b>1Gv 5:4-5</b>: Tutti i figli di Dio vincono il mondo per fede: una fede che Ges&ugrave; ha gi&agrave; trionfato e vinto per noi sulla croce (Col 2:13-15); una fede che siamo gi&agrave; stati liberati dal dominio del male (Col 1:13); una fede che Dio ci protegge e ci guida nella giustizia; una fede che Dio ci d&agrave; saggezza e potenza quando gli chiediamo (Giac 1:5).</p>
<p>In altre parole, la vittoria pu&ograve; essere descritta in tre modi: la vittoria definitiva che godiamo in Ges&ugrave;, la vittoria che supera la tentazione, e la vittoria che si ravvede e ritorna alla fede e alla grazia quando cadiamo nel peccato. Satana &egrave; anche sconfitta dal nostro perdono dopo aver peccato.</p>

<h2>Riassunto</h2>
<p>La guerra spirituale &egrave; inevitabile nella vita cristiana.</p>
<p>Se la nostra vita spirituale si indebolisce, non potremo resistere nella battaglia.</p>
<p>&Egrave; importante continuare nell'abitudine del trionfo nella guerra spirituale.</p>

