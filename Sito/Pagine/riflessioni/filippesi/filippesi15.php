<h1>Crescita spirituale e maturit&agrave;</h1>

<p>Nello <a href="filippesi14.php">studio precedente</a> abbiamo visto l'importanza di protenderci verso le cose che stanno davanti, di correre verso la m&egrave;ta, di non pensare di essere arrivati alla perfezione ma di cercarla (Fili 3:12-14). Una parte di questa corsa &egrave; la crescita spirituale, che approfonderemo in questo studio.</p>

<h2>Che cosa &egrave; l'immaturit&agrave;?</h2>
<p><i>Per capire il significato della maturit&agrave; e come possiamo crescere spiritualmente, dobbiamo prima capire che cosa &egrave; l'immaturit&agrave;. Secondo 1Cor 3:1-4, quali sono alcune caratteristiche del credente immaturo (carnale)? Spiegale.</i></p>
<p>Carnali (ancora controllati dalla natura peccaminosa e non da Cristo), bambini in Cristo (non hanno molto conoscenza e non si comportano come adulti), prendono solo latte perch&eacute; non sopportano cibo solido (solo le verit&agrave; pi&ugrave; semplici della Parola e discernimento solo delle pi&ugrave; semplici manifestazioni del bene e del male Ebr 5:12-14), gelosi, litigiosi, divisi (in diversi partiti).</p>

<p><i>Quali di queste caratteristiche dell'immaturit&agrave; &egrave; pi&ugrave; sorprendente per te?</i></p>
<p>Dipende dall'individuo, ma forse per molti saranno la gelosia e le contese. Pensiamo che sia importante conoscere di pi&ugrave; le cose giuste, ma &egrave; anche il nostro comportamento che conta.</p>
<p>Formare dei gruppetti nella chiesa (e fra chiese simili) &egrave; naturale e utile. Quello che &egrave; sbagliato &egrave; quando escludiamo o critichiamo o competiamo con altri gruppi.</p>

<p><i>La chiesa a Corinto ha ricevuto molto doni spirituali (1Cor 1:7), eppure spiritualmente erano bambini. Cosa significa?</i></p>
<p>Doni ed esperienze spirituali non sono n&eacute; conseguenze n&eacute; cause della maturit&agrave;.</p>
<p>La maturit&agrave; &egrave; pi&ugrave; importante dei doni. Doni diversi sono dati a persone diverse, ma tutti devono cercare lo stesso tipo di maturit&agrave;.</p>
<p>Comunque, i doni sono necessari e vanno ricercati, ma insieme con (o dopo) la ricerca della maturit&agrave;.</p>

<h2>Che cosa &egrave; la maturit&agrave;?</h2>
<p><i>Come sono descritte la maturit&agrave; e la crescita spirituale in Efes 4:13-16?</i></p>
<p>L'obiettivo &egrave; la perfezione (Efes 4:12): unit&agrave; della fede, piena conoscenza del Figlio di Dio, uomini fatti, all'altezza della statura perfetta di Cristo; non come bambini sballottati, non portati da ogni vento di dottrina dagli uomini astuti.</p>
<p>La crescita: seguire la verit&agrave; in amore, crescere in ogni cosa verso Cristo il capo, sviluppo e edificazione da Cristo (il capo) mediante l'aiuto degli altri (le giunture; cos&igrave; il credente maturo sviluppa e edifica anche gli altri).</p>

<p><i>Alla fine, maturare spiritualmente vuol dire diventare come Ges&ugrave;. Perch&eacute;?</i></p>
<p>Ripristiniamo l'immagine di Dio, e Ges&ugrave; &egrave; la perfetta immagine di Dio.</p>

<p><i>In modo specifico, quali trasformazioni ci sono quando si diventa come Cristo?</i></p>
<p>In quello che pensiamo, come agiamo, lo scopo della vita.</p>
</p>Poi, puoi approfondire con questi versetti: pensieri Mt 4:4,19; azioni Lu 9:58, Gv 13:1; scopo Mt 20:28; Gv 10:10.</p>

<p>Efesini 4:15 dice che dobbiamo crescere in ogni cosa, cio&egrave; la crescita deve coinvolgere l'intera persona, altrimenti diventiamo fisicamente come un adulto con la mentalit&agrave; di un bambino oppure il contrario. Per esempio, alcuni hanno tanta conoscenza della Parola, ma non possono edificare altri perch&eacute; non possono mantenere buoni rapporti con loro. Inoltre, la crescita ha a che fare non solo con come pensiamo e agiamo in chiesa, ma anche a lavoro e in famiglia.</p>
<p><i>In quali sfere della tua personalit&agrave; e della tua vita quotidiana la tua crescita &egrave; indietro in confronto con le altre sfere?</i></p>

<h2>Gli strumenti della maturit&agrave;</h2>
<p><i>Secondo 1Tess 2:7; 2P 3:18; Ef 4:16; Fili 3:12, quali sono alcune delle cose di cui abbiamo bisogno per crescere spiritualmente? Ci sono altre cose necessarie o utili?</i></p>
<p>1Tess 2:7 - responsabili che prendono cura di noi<br />
2P 3:18 - la grazia e la conoscenza di Ges&ugrave;<br />
Ef 4:16 - da Ges&ugrave; il capo, mediate gli altri (quindi dobbiamo frequentare altri credenti sia per crescere sia per far crescere gli altri)<br />
Fili 3:12 - uno sforzo da parte nostra</p>

<h2>Riassunto</h2>
<p>Dio vuole che cresciamo spiritualmente.<br />
Non ci sono metodi istantanei per arrivare alla maturit&agrave;.<br />
Molti non hanno il desiderio o lo sforzo per crescere spiritualmente.<br />
Dobbiamo aiutare altri a crescere.</p>

