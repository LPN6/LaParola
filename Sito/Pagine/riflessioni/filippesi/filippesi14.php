<h1>Conoscere Cristo</h1>

<h2>Ripasso</h2>
<p><i>Paolo aveva un ottimo curriculum vitae per quanto riguardo la sua vita morale e religiosa. Che cosa ne dice in Fili 3:7-8? Perch&eacute;?</i></p>
<p>Lo considerava una perdita e spazzatura, perch&eacute; quello che noi si fa non pu&ograve; mai rendere giusto davanti a Dio. Solo per la fede in Cristo puoi essere contato come giusto.</p>

<p><i>Perch&eacute; devi stare attento? (Fili 3:2)</i></p>
<p>Perch&eacute; alcuni vogliono sostituire o aggiungere all'opera di Cristo e alla fede in lui per ottenere la giustizia.</p>

<p><i>Come descrive Paolo il vero credente in Fili 3:3? &Egrave; una descrizione di te?</i></p>
<p>Adorare Dio nello Spirito (cio&egrave; tutta la vita &egrave; diretta dello Spirito Santo); glorificarsi in Cristo Ges&ugrave; (cio&egrave; rallegrarsi in Ges&ugrave; e tutto quello che ha fatto per lui); non confidarsi nella carne (cio&egrave; non dipende da quello che si fa per diventare giusto per Dio).</p>

<p><i>Paolo voleva che i Filippesi si fidassero di Ges&ugrave; e di nient'altro. Perch&eacute; i credenti sono a volte tentati a porre la propria fiducia in cose addizionali?</i></p>
<p>A volte sembra pi&ugrave; facile affidarci delle proprie azioni come misura di quanto piacere a Dio. &Egrave; pi&ugrave; facile vivere per vista che per fede.</p>
<p>Esempi? Quanto spesso leggiamo la Bibbia, quanto zelo nella preghiera, a quante persone parliamo di Ges&ugrave;, eccetera.</p>

<p><i>Di che cosa ti devi ricordare quando sei tentato a mettere la tua fiducia in queste altre cose?</i></p>
<p>Filippesi 3:9.</p>

<h2>Studio</h2>
<p><i>Leggi Filippesi 3:10-4:1. Rifletti sulla proposizione: &egrave; una cosa credere in Cristo; &egrave; un'altra cosa conoscere Cristo. (Fili 3:8-10; 2Tim 1:12)</i></p>
<p>Molti credono in Cristo nel senso che credono nei fatti che riguardano Ges&ugrave; (chi &egrave; e quello che ha fatto). Per&ograve;, bisogna non solo credere in Cristo ma conoscere Cristo (vedi Mt 7:21-23) e volerlo conoscere sempre di pi&ugrave; (Fili 3:12-14).</p>

<p><i>Perch&eacute; dovremmo volere conoscere Cristo di pi&ugrave;?</i></p>
<p>A causa del suo amore per noi, per quello che ha fatto per noi, e perch&eacute; &egrave; tutto per noi - &egrave; la nostra giustizia. Lo Spirito di Ges&ugrave; ci fa conoscere Cristo di pi&ugrave;.</p>

<p><i>Secondo Fili 3:10, che cosa vuol dire "conoscere Cristo"?</i></p>
<p>Conoscere la potenza della sua risurrezione (sperimentare la potenza trasformatrice di una nuova vita diventando come lui Rom 8:9-11), e soffrire per lui (rinnegare noi stessi e la nostra natura peccaminosa, essere maltrattati da altri perch&eacute; portiamo il suo nome, essere attaccati dal diavolo, eccetera Fili 1:29-30).</p>

<p><i>Cosa pensi dell'affermazione, "Se non siamo nel processo di essere trasformati da Cristo e a Cristo e se non soffriamo per lui, non lo conosciamo".</i></p>
<p>Molti fanno del tutto per togliere la sofferenza nella vita, ma soffrire per Cristo (non la sofferenza in generale) non &egrave; una cosa da evitare. Per esempio, devi parlare di lui anche se altri non ti accetterebbero.</p>

<p><i>Qual &egrave; lo scopo della vita di Paolo? Che cosa vuol dire? (Fili 3:12-14)</i></p>
<p>La perfezione. Afferrare il premio per cui Dio l'ha chiamato in Cristo, cio&egrave; essere risuscitato mediate Cristo (Fili 3:11) ed essere con lui per tutta l'eternit&agrave;. Voleva cos&igrave; tanto conoscere Cristo ed essere con lui, non al 50%, non al 90% n&eacute; 99%, ma perfettamente - il discepolo missionale. Non si paragonava con altri, ma con la perfezione di Ges&ugrave; Cristo. Si impegnava per questo scopo. &Egrave; questo lo scopo della tua vita? Si vede?</p>
<p>Molti pensano che la salvezza sia il punto di arrivo nella vita spirituale, ma in realt&agrave; &egrave; solo il punto di partenza per una vita (fisica) di impegno e sforzi.</p>
<p>Questo ha molte implicazioni per ogni sfera della nostra vita. Le implicazioni per il nostro tempo saranno approfondite nello <a href="filippesi16.php">studio 16</a>.</p>

<p><i>Che cosa ti pu&ograve; impedire di "protenderti" verso il premio? (Fili 3:12-19)</i></p>
<p>Puoi: dimenticarti del traguardo che hai in Cristo; pensare di essere arrivati (Fili 3:12 - la soddisfazione &egrave; un gran nemico della crescita; o meglio, devi essere soddisfatti con Cristo ma mai del tuo stato); pensare solo al passato cio&egrave; essere soddisfatto di quello che hai fatto o essere bloccato da sbagli passati (Fili 3:13); pensare solo delle cose terrene (Fili 3:19).</p>
<p>Questo "protendersi" verso il premio &egrave; in realt&agrave; una descrizione della crescita spirituale, un tema che sar&agrave; approfondito nello <a href="filippesi15.php">studio 15</a>.</p>

<p><i>Quale aiuto propone Paolo ai Filippesi? (Fili 3:17)</i></p>
<p>Offre la sua vita come esempio da seguire, ed anche la vita di altri che hanno questa vita missionale (come Timoteo ed Epafrodito nel capitolo precedente). Non solo Paolo ha insegnato la vita missionale, l'ha vissuta.</p>

<p><i>Dovresti essere un esempio ad altri (vedi 1Tim 4:12). Lo sei? Vale la pena seguire il tuo esempio? Puoi dire, "Seguite me come io seguo Cristo"?</i></p>
<p>La realt&agrave; &egrave; che sei sempre un esempio agli altri, perch&eacute; ti vedono e possono imitarti. La domanda &egrave;, quale esempio sei per gli altri, positivo o negativo?</p>

<p><i>Chi sono i "nemici della croce di Cristo", e perch&eacute;? (Fili 3:18) Qual era il suo atteggiamento verso di loro?</i></p>
<p>Quelli che non hanno la croce al centro, cio&egrave; non sono missionali. Pensano invece ai propri bisogni e desideri (le cose della terra Fili 3:19). Non vogliono conoscere Cristo di pi&ugrave;.</p>
<p>Anche se erano nemici della croce, non erano i suoi nemici, e in una lettera piena di gioia (vedi lo <a href="filippesi17.php">studio 17</a>), &egrave; strano leggere che Paolo piangeva per loro. Ma essere missionali vuol anche dire essere dispiaciuti quando la croce non &egrave; al centro, dispiaciuti per Cristo e per gli altri.</p>

<p><i>Quale effetto dovrebbero avere sulla tua vita le grandi verit&agrave; di Fili 3:20-21?</i></p>
<p>La cittadinanza in cielo, verr&agrave; un Salvatore che ti preparer&agrave; per la gloria.</p>
<p>Quindi non devi vivere per questo mondo, perch&eacute; la tua casa &egrave; in cielo, e devi guardare Cristo, conoscendolo e vivendo per lui.</p>
<p>Quando io sapevo che sarei venuto in Italia fra qualche mese, non ho pi&ugrave; comprato cose che non avrei potuto portare con me, anzi vendevo e regalavo le mie cose. Ho trascorso il mio tempo preparandomi per vivere nel nuovo paese, imparando la lingua, la cultura, la storia, pensando e parlando di come sar&agrave;. Cos&igrave; devi fare tu per il tuo nuovo paese di cui hai gi&agrave; la cittadinanza.</p>

<h2>Riassunto</h2>
<p>La tua vita &egrave; conoscere Cristo e desiderare di essere con lui.</p>

