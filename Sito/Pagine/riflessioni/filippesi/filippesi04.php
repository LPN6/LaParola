<h1>Vivere in Cristo (Filippesi 1:12-26)</h1>

<h2>Ripasso</h2>
<p><i>Perch&eacute; Paolo era fiducioso che i Filippesi erano credenti genuini (Fili 1:5)? Cosa vuole dire?</i></p>
<p>I Filippesi non solo hanno creduto, ma erano partecipi al vangelo, cio&egrave; erano missionali, vivendo il vangelo seguendo Cristo e vivendo per lui (per esempio amando altri).</p>

<p><i>Quale sicurezza possiamo avere se siamo seguaci veri di Cristo (Fili 1:6)?</i></p>
<p>Che Dio completer&agrave; la buona opera che ha iniziato in noi.</p>

<h2>Studio</h2>
<p><i>1. Come completerebbe il tuo amico migliore questa frase: "per te, vivere &egrave; per..."? Come lo deciderebbe il tuo amico?</i></p>
<p>Considererebbe come trascorri il tuo tempo, quello di cui ti piace parlare, quello che ti rende contento.</p>

<p><i>2. Alla luce di ci&ograve;, come ti piace trascorrere il tuo tempo, di che cosa parli, cosa metti sui social, qual &egrave; la tua pi&ugrave; grande gioia? &Egrave; Cristo?</i></p>
<p>Rifletti sulle cose per cui anche i Cristiani possono vivere: famiglia, coniuge, lavoro, ministero cristiano, casa, squadra di cuore. Forse sono cose buone, ma possiamo vivere per queste cose pi&ugrave; che per Cristo.</p>

<p><i>3. Leggi Fili 1:12-26, e considera come la vita di Paolo mostrava che viveva per Cristo, cio&egrave;, era missionale. In Fili 1:12-13, che cosa osservarono le guardie di Paolo?</i></p>
<p>Paolo non valut&ograve; la sua esperienza attuale (essere in prigione) in base alla sua comodit&agrave; personale, ma in base a quanto aiuta il progresso del vangelo.</p>
<p>Le guardie sapevano che Paolo era in prigione per Cristo. Sapevano anche che a Paolo piaceva parlare di Cristo, anche in catene.</p>

<p><i>4. Bench&eacute; fosse in prigione, di cui cosa Paolo poteva rallegrarsi? (Fili 1:12-18)</i></p>
<p>Il progresso del vangelo: poteva predicare ai soldati e ai governanti, i Cristiani pi&ugrave; timidi avevano preso coraggio (Fili 1:14), i rivali di Paolo predicavano di pi&ugrave; (Fili 1:15-17). Questo &egrave; vivere in modo missionale: considerare le circostanze non in base a quello che mi fanno, ma l'effetto delle circostanze sul vangelo. Notate anche la grazia che Paolo mostrava verso quelli che lo invidiavano: non c'era rancore, solo gioia che hanno pi&ugrave; ardire nella proclamazione del vangelo. Per un approfondimento di questo tipo di rapporto, vedi lo <a href="filippesi05.php">studio 5</a>.</p>

<p><i>5. Paolo era in prigione, con un futuro di incertezza e forse la morte. Che cosa potresti considerare importante se tu fossi in una tale situazione?</i></p>
<p>Essere rilasciati, stare bene, la tua reputazione.</p>

<p><i>6. Quale era la cosa pi&ugrave; importante per Paolo? (Fili 1:18) Secondo te, perch&eacute; era cos&igrave;? (Rom 1:16)</i></p>
<p>Che Cristo era predicato. Perch&eacute; il vangelo glorifica Cristo, ed era l'unico modo per salvare le persone. Questa &egrave; la vita missionale. La sua fama e reputazione, e addirittura la sua vita, erano sotto attacco, ma non era importante perch&eacute; Cristo era glorificato. Paolo era in pericolo, ma non era importante perch&eacute; Cristo era glorificato.</p>
<p>Se qualcuno ti critica o ti disprezza per le tue scelte per Cristo, riesci a dire, "Che importa?" (Fili 1:18)</p>

<p><i>7. Nonostante le circostanze difficili della prigionia, perch&eacute; Paolo era fiducioso che avrebbe continuato ad esaltare Cristo nella sua vita? (Fili 1:19-20)</i></p>
<p>Sapeva che gli altri pregavano per lui, e che aveva l'aiuto dello Spirito per continuare ad esaltare Cristo tramite la proclamazione del vangelo.</p>
<p>Questo punto &egrave; importante: la vita missionale non &egrave; forzarti di vivere in un modo diverso, ma sottometterti allo Spirito che ti trasforma (con l'aiuto della preghiera, di noi e di altri).</p>

<p><i>8. Cosa pensava Paolo della morte, sapendo che sarebbe potuto morire per Cristo? (Fili 1:21-24)</i></p>
<p>La morte non &egrave; una cosa positiva in s&eacute;, ma ha un guadagno come conseguenza di essere con Cristo che era meglio per Paolo (ma la sua morte non era meglio per i Filippesi).</p>
<p>Il suo punto di vista missionale cre&ograve; un dilemma: che cosa era meglio per Cristo e per il Vangelo? Per lui, sarebbe morire; per gli altri, sarebbe vivere ancora.</p>

<p><i>9. Come pensi tu della morte? La desideri? Sei pronto a morire adesso? Perch&eacute; o perch&eacute; no?</i></p>
<p>Se vivi per le cose intorno a te, non desideri partire e essere con Cristo. Il tuo atteggiamento verso la morte dimostra per chi o per cosa vivi.</p>

<p><i>10. Come pensava Paolo della sua vita su questa terra? (Fili 1:22,26)</i></p>
<p>La vita va dedicata alla proclamazione del vangelo ad altri, e edificare altri in questo vangelo. Non alla carriera, sposarsi, creare una famiglia, eccetera. Di nuovo, questa &egrave; la vita missionale. Se vivi per Cristo, questo tesoro non ti sar&agrave; mai tolto; se vivi per altre cose, prima o poi perderai quello per cui vivi.</p>

<p><i>11. Che cosa caratterizza la vita di qualcuno che pu&ograve; dire, "per me vivere &egrave; Cristo"?</i></p>
<p>Cristo &egrave; tutto. La persona desidera di essere con Cristo, e mentre &egrave; sulla terra, vuole condividere il vangelo del Signore Ges&ugrave;, vivere in un modo che lo onora, e aiutare altri a vivere per Cristo. Questo caratterizza la tua vita?</p>

<h2>Riassunto</h2>
<p>Vivere in Cristo vuol dire proclamare il vangelo di Cristo e edificare altri credenti.</p>

<h2>Versetto a memoria</h2>
<p>Filippesi 1:21: Per me il vivere &egrave; Cristo e il morire guadagno.</p>

