Questo &egrave; un raccolto dagli studi delle piccole descrizioni e caratteristiche del discepolo missionale.
</p><p>
Un discepolo missionale:</p>
<h2>1. Fiduciosi in Cristo</h2>
<p>&egrave; servo di Cristo Ges&ugrave; - esiste per fare la volont&agrave; di Ges&ugrave; non la propria<br />
&egrave; partecipe al vangelo - collabora per l'avanzamento della buona notizia<br />
usa il vangelo come misura di valutazione - le circostanze sono buone o cattive in base all'effetto sul vangelo non su di s&eacute;<br />
prega motivi missionali - il progresso del vangelo negli altri</p>
<h2>2. Un nuovo comandamento: Amare l'uno l'altro</h2>
<p>ama - come Dio ci ama, anche (soprattutto) i nemici<br />
ama in modo missionale - cercando il bene degli altri che &egrave; la crescita del vangelo in loro</p>
<h2>3. Ospitalit&agrave; missionale</h2>
<p>sa di essere perdonato molto, e vuole mostrare la stessa grazia agli altri<br />
usa tutto quello che Dio ha dato per il regno non per s&eacute; stesso</p>
<h2>4. Vivere in Cristo</h2>
<p>vive per Cristo - quello che &egrave; importante &egrave; l'effetto sul vangelo, non quello che altri pensano di lui<br />
cerca l'assistenza dello Spirito Santo e la preghiera per il futuro - non dipende da s&eacute; stesso<br />
desidera essere con Cristo</p>
<h2>5. Rapporti di grazia</h2>
<p>ha una passione per la grazia di Dio, che lo rende amorevole e umile<br />
vede le differenze e le difficolt&agrave; come opportunit&agrave; di manifestare la grazia di Dio</p>
<h2>6. Stare fermi insieme in Cristo</h2>
<p>non combatte con gli altri - perch&eacute; sono sempre motivi meno importanti del vangelo<br />
si comporta in modo degno di Cristo - altruistico, umile, servo, ubbidiente</p>
<h2>7. Prove e carattere spirituale</h2>
<p>crede che le difficolt&agrave; sono per il bene del vangelo, e possono fare del bene a lui<br />
si prepara per le difficolt&agrave; future conoscendo meglio Dio</p>
<h2>8. Una responsabilit&agrave; per servire</h2>
<p>serve - pensa ai bisogni e agli interessi degli altri prima dei suoi</p>
<h2>9. Trasformati da Cristo</h2>
<p>pensa prima di tutto al vangelo, sia in quello che dice sia in quello che fa<br />
si adopera per la propria santificazione - vuole che il vangelo (la sua salvezza) sia sempre di pi&ugrave; in s&eacute; stesso</p>
<h2>10. Una vita di ubbidienza</h2>
<p>ascolta Ges&ugrave; e ubbidisce a Ges&ugrave; di istinto - perch&eacute; lo ama e lo vuole imitare</p>
<h2>11. Una vita che testimonia di Cristo</h2>
<p>&egrave; consapevole del gran valore del messaggio del vangelo - e vuole condividerlo<br />
ama altri come li ama Ges&ugrave; - che significa condividere il vangelo con loro</p>
<h2>12. Giusti in Cristo</h2>
<p>considera tutto quello che fa un danno in confronto con Cristo e quello che Cristo ha fatto (cio&egrave;, il vangelo)</p>
<h2>13. La giustizia di Cristo</h2>
<p>sottomette tutta la vita alla sovranit&agrave; di Cristo</p>
<h2>14. Conoscere Cristo</h2>
<p>si impegna a conoscere Cristo sempre di pi&ugrave;<br />
desidera fortemente essere con Cristo</p>
<h2>15. Crescita spirituale e maturit&agrave;</h2>
<p>non &egrave; perfetto, ma desidera crescere spiritualmente sia in conoscenza sia in comportamento</p>
<h2>16. Tempo</h2>
<p>&egrave; in missione il 100% del tempo</p>
<h2>17. Rallegrarsi in Cristo</h2>
<p>pensa sempre al Vangelo, al Signore, e al buono, per rallegrarsi invece di preoccuparsi</p>
<h2>18. Guerra spirituale</h2>
<p>sa di aver vinto, non perch&eacute; &egrave; pi&ugrave; forte di Satana e la morte ma perch&eacute; lo &egrave; Ges&ugrave;<br />
esercita la fede, la Parola e la preghiera nella tentazione e la persecuzione</p>
<h2>19. Contenti in Cristo</h2>
<p>&egrave; contento perch&eacute; &egrave; in Cristo, non per le circostanze o per quello che ha</p>
<h2>20. Denaro; amministrazione</h2>
<p>valuta i soldi confrontandoli con il valore del Vangelo<br />
usa i suoi soldi per avanzare il Vangelo<br />
si ricorda che secondo il Vangelo Ges&ugrave; si &egrave; dato per noi, e d&agrave; nello stesso modo</p>

