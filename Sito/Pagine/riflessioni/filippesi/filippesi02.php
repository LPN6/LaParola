<h1>Un nuovo comandamento: Amare l'uno l'altro</h1>

<p>Nello <a href="filippesi01.php">studio precedente</a>, abbiamo parlato dell'amore di Paolo per i Filippesi (Fili 1:7-8) e come Paolo ha pregato per la crescita dell'amore dei Filippesi (Fili 1:9-11). In questo studio, approfondiamo alcuni aspetti dell'importanza dell'amore; in altri studi approfondiremo in quali modi possiamo amare. Perch&eacute; l'amore &egrave; il comandamento primario, e quello che dovrebbe distinguere sia il Cristiano sia i Cristiani (Gv 13:35). Essere discepoli vuol dire soprattutto amare; essere missionali vuol dire amare nel modo giusto, cio&egrave; per il vangelo.</p> 

<h2>La necessit&agrave; dell'amore</h2>
<p>Esaminiamo come la chiesa ad Efeso non ha amato in Apoc 2:1-6.</p>

<p><i>1. Per quali cose &egrave; stata approvata la chiesa ad Efeso? (Apoc 2:2-3,6)</i></p>
<p>Opere, fatica, costanza, non sopportazione dei malvagi, messa alla prova. Tutte queste cose non bastano per essere una chiesa sana.</p>

<p><i>2. Perch&eacute; la chiesa &egrave; stata rimproverata? (Apoc 2:4)</i></p>
<p>Ha abbandonato il suo primo amore, cio&egrave; l'amore (per gli altri) che aveva all'inizio.</p>

<p><i>3. Secondo te, perch&eacute; la chiesa ad Efeso ha abbandonato il suo primo amore? Nel rispondere, pensa alle cose positive della chiesa, che sottolineavano la lotta contro la false dottina.</i></p>
<p>Forse la forza della chiesa &egrave; stata la causa - &egrave; facile (pi&ugrave; facile?) difendere la verit&agrave; e purezza in un modo freddo e senza compassione.</p>

<p><i>4. Quale avvertimento ha dato il Signore alla chiesa se non avrebbe ricuperato il suo primo amore? (Apoc 2:5)</i></p>
<p>La chiesa sarebbe stata tolta, non sarebbe pi&ugrave; esistita.</p>

<p><i>5. Come ti senti mentre contempli le parole del Signore, in cui una chiesa perde il valore della sua esistenza se abbandona l'amore, anche se sostiene la verit&agrave; e mantiene la santit&agrave; e purezza?</i></p>
<p>Sembra duro? Ma l'amore &egrave; la caratteristica principale della chiesa (Gv 13:35). Che cosa pensa Ges&ugrave; di te?</p>

<h2>La totalit&agrave; dell'amore</h2>
<p>Leggi Mt 22:37-40 e studia il tipo di amore che si deve avere per Dio e per il prossimo.</p>
<p><i>6. Come devi amare Dio? Cosa significa amare con il cuore, amare con l'anima, amare con la mente?</i></p>
<p>Con tutte il nostro essere. Anche in diversi modi: con le emozioni, con lo spirito, con l'intelletto. Mc 12:30 aggiunge la forza, cio&egrave; anche fisicamente.</p>
<p>Un libro "I cinque linguaggi dell'amore" descrive diversi modi in cui amiamo, e che tutti amano in alcuni modi pi&ugrave; che in altri: dire, fare, regalare, dedicare tempo, toccare.
Le difficolt&agrave; in una coppia accadono spesso quando esprimono amore e vogliono ricevere amore in modi diversi. Ad uno sembra che l'altro non lo ami, e sicuramente non lo soddisfa; mentre in real&agrave; mostra il suo amore in un modo diverso.</p>

<p><i>7. "Con tutto il cuore, tutta l'anima e tutta la mente" vuol dire offrire a Dio tutto il nostro essere. Siamo servi di Cristo (Fili 1:1). Con quale parte del tuo essere trovi pi&ugrave; difficile e pi&ugrave; facile amare Dio?</i></p>
<p>L'amore verso Dio non &egrave; come l'amore verso il prossimo, in cui possiamo usare uno o due "linguaggi" dell'amore (preferabilmente quelli preferiti dall'altro). Verso Dio, dobbiamo usare tutti i linguaggi, il cuore, l'anima, la mente, e la forza.
Per&ograve;, nota che dice "con tutto..." non "con tanto..." Nello stesso modo che qualcuno con una QI di 80 pu&ograve; amare Dio con la mente meno di qualcuno con una QI di 120 ma non pecca, cos&igrave; anche qualcuno che non riesce a esprimere o sentire le emozioni pu&ograve; amare con tutto il cuore ma meno cuore di altri, eppure non pecca.</p> 

<p><i>8. Cosa ti impedisce di amare Dio con tutto il tuo essere?</i></p>
<p>Per esempio, non conoscere Dio abbastanza bene, n&eacute; quanto ti ama. Oppure non lo voler amare perch&eacute; ti costa troppo, cio&egrave;, c'&egrave; qualcosa che ami di pi&ugrave;
(di solito la propria indipendenza, cio&egrave; s&eacute; stessa; oppure qualcosa del mondo fisico, che &egrave; in realt&agrave; un amore per quello che si riceve da quella cosa (benessere, felicit&agrave;, ...) che &egrave; sempre un amore per s&eacute; stesso).</p>

<p><i>9. Che tipo di amore devi mostrare al tuo prossimo? (Vedi anche 1G 3:16)</i></p>
<p>Come te stesso.</p>

<p><i>10. Cosa vuol dire amare il prossimo come te stesso?</i></p>
<p>Di istinto amiamo noi stessi - cerchiamo sempre il nostro bene, quello che ci rende contenti e realizzati, e lo facciamo senza pensare. Cos&igrave; istintivamente dobbiamo amare gli altri.</p>

<p><i>11. Spiega il rapporto fra amare Dio e amare il prossimo. Perch&eacute; sono considerati come se fossero due lati della stessa medaglia? Perch&eacute; amare Dio &egrave; prima di amare il prossimo?</i></p>
<p>Quando amiamo Dio, naturalmente amiamo gli altri perch&eacute; Dio li ama. Se non amiamo gli altri, non amiamo Dio. Ma l'amore di Dio &egrave; il fondamento.</p>

<p><i>12. Secondo te, la mancanza dell'amore giusto verso il Dio invisibile &egrave; un fattore che ti impedisce di amare il tuo prossimo che vedi? (1G 4:20)</i></p>

<h2>L'eccellenza dell'amore</h2>
<p><i>13. Secondo 1Cor 13, l'amore ha tre tipi di eccellenza. Esamina i primi tre versetti e spiega come l'amore sorpassa gli altri doni:<br />
a) l'amore &egrave; migliore del dono delle lingue;<br />
b) l'amore &egrave; migliore del dono della profezia;<br />
c) l'amore &egrave; migliore del dare tutto per aiutare i bisognosi.</i></p>
<p>a) senza una visione missionale delle lingue, per edificare gli altri, le lingue sono solo uno squillante cembalo per far vedere la mia spiritualit&agrave;<br />
b) la verit&agrave; senza amore non &egrave; niente - vedi Apocalisse 2:1-6<br />
c) aiutare i bisognosi senza amore &egrave; un aiuto per i bisognosi, ma un danno per me perch&eacute; &egrave; per farmi sentire meglio.</p>

<p>Nelle 15 qualit&agrave; dell'amore in 1Cor 13:4-7, vediamo che l'amore non vuol dire semplicemente il sentimento di passione dell'innamoramento.
Queste 15 caratteristiche invece iniziano e concludono con la sopportazione paziente. Se il nostro cuore &egrave; mosso o no, dobbiamo mettere in pratica l'amore.
Bench&eacute; qualcuno possa obiettare, "Come posso amare se non sento l'amore nel mio cuore?", non &egrave; un ragionamento convincente.
Il Signore ci dice di mettere in pratica l'amore nonostante come ci sentiamo nel nostro cuore. Leggi e rifletti su Rom 12:20.</p>
<p><i>14. 1Cor 13:4-7 &egrave; prima di tutto una descrizione dell'amore di Dio verso di noi. Quali caratteristiche mancano maggiormente nel tuo amore.</i></p>
<p>Dobbiamo aiutare (fare) anche se i sentimenti non ci sono. Anzi, soprattutto quando i sentimenti non ci sono, solo questo &egrave; amore, quando non c'&egrave; qualcosa per noi.</p>

<h2>Riassunto</h2>
<p>L'amore &egrave; importante, anche primario, per il credente e per la Chiesa.</p>
<p>Dobbiamo amare Dio e gli altri con tutto il nostro essere, anche (anzi soprattutto) quando i sentimenti favorevoli non ci sono.</p>
<p>In questo studio, abbiamo parlato soprattutto dell'amore del discepolo, e poco dell'amore missionale. L'amore missionale sar&agrave; considerato ulteriormente nello <a href="filippesi08.php">studio 8</a>.</p>

