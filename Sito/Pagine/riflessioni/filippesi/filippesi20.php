<h1>L'amministrazione missionale del denaro</h1>

<h2>Il principio del dare</h2>
<p>Il principio missionale del denaro si trova in Mt 13:44; 6:19-21. I soldi sono buoni, ma hanno un valore piccolissimo davanti alle ricchezze celesti. Un atteggiamento missionale pensa ai soldi alla luce del Vangelo per dare ad essi il loro giusto valore.</p>

<p>Se dovessimo fare una scelta fra un regalo di &euro;10 oggi oppure &euro;1000 ogni giorno della nostra vita, la decisione sarebbe facile. Eppure, scegliamo spesso i &euro;10 (Mt 19:29).</p>

<p><i>1. Quali sono le limitazioni dei soldi secondo Ec 5:10-15?</i></p>
<p>v. 10: Pi&ugrave; hai, pi&ugrave; vuoi avere; non siamo mai contenti con quello che abbiamo.<br />
v. 11: Pi&ugrave; hai, pi&ugrave; viene consumato dagli altri.<br />
v. 12: Pi&ugrave; hai, pi&ugrave; preoccupazioni hai per tenerli e avere ancora per il futuro.<br />
v. 13: Pi&ugrave; hai, pi&ugrave; sei soggetto alla sventura, cio&egrave; puoi perdere di pi&ugrave;.<br />
v. 14: Pi&ugrave; hai, pi&ugrave; hai da perdere.<br />
v. 15: Pi&ugrave; hai, pi&ugrave; dovrai lasciare.</p>

<h2>La pratica del dare</h2>
<p><i>2. In quali modi il mondo raccoglie i fondi? Secondo 1Cor 16:1-4 e 2Cor 8:1-5, in che modo dovrebbero dare i cristiani?</i></p>
<p>Dobbiamo dare con regolarit&agrave;, secondo la propria ricchezza ricevuta da Dio (chi ha di pi&ugrave; d&agrave; di pi&ugrave;), con trasparenza.</p>
<p>Dobbiamo dare (almeno qualcosa) anche se siamo poveri, con generosit&agrave;, volentieri (anche 2Cor 9:6-7), secondo (o oltre) i propri mezzi (anche 2Cor 8:11-12), con un forte desiderio (Mc 12:41-44), come un privilegio che non vediamo l'ora di fare (e non la ricerca di qualche banconota all'ultimo minuto quando il cestino viene passato a noi durante il culto; At 20:35), dopo aver dato se stesso a Dio.</p>

<p>Nell'AT c'&egrave; il comando della decima, che non c'&egrave; nel NT. Invece c'&egrave; il principio di essere come Cristo, generosi come lui nel dare tutto per grazia (2Cor 8:9).</p>

<p><i>3. A chi dobbiamo dare, secondo Rom 15:26; 1Tim 5:17-18; Fili 4:15?</i></p>
<p>Ai cristiani poveri, ai responsabili e insegnanti della chiesa.</p>

<h2>Alcune domande di valutazione personale</h2>
<p><i>4. Se dono dei soldi, quando lo faccio: dopo aver pagato tutte le spese mensili (dando quello che rimane), o prima?</i></p>
<p>La legge delle primizie ci insegna che dobbiamo credere che Dio provveder&agrave; e cos&igrave; dobbiamo dare tutto a lui (Lev 23:9-14; Dt 18:1-5).</p>
<p>Ges&ugrave; dice di cercare prima il regno Dio, e Dio provveder&agrave; il resto (Mt 6:33; anche Fili 4:19 nello studio precedente).</p>
<p>Dio non chiede pi&ugrave; (cio&egrave; dopo la venuta di Ges&ugrave;) di dargli solo le nostre primizie: egli desidera tutto.</p>
<p>Dio ha dato la sua primizia (Ges&ugrave; il suo primogenito) per noi.</p>

<p><i>5. Il mio dare dimostra che credo che Dio avr&agrave; cura di me, ma anche che lo far&agrave; generosamente?</i></p>
<p>Dare &egrave; un obbligo o un privilegio; do di malavoglia o gioiosamente?</p>
<p>Quando do, dono quello che penso di dover dare, o pi&ugrave; di quello che penso di dover dare?</p>
<p>Dio &egrave; un Dio della grazia, che dona gioiosamente pi&ugrave; di quello che meritiamo.</p>

<p><i>6. Il mio dare dimostra che credo nel vangelo?</i></p>
<p>Credo che quello che io possiedo mi appartenga, o che tutto quello che possiedo appartenga a Dio?</p>
<p>Abbiamo ricevuto un favore immeritato e non guadagnato da Dio. Anche noi dobbiamo fare nello stesso modo.</p>
<p>Il vangelo ci dice che siamo completamente al sicuro nelle mani di Dio, a prescindere da quanto denaro abbiamo o non abbiamo.</p>

<p><i>7. In che modo mi sono avvicinato al concetto della decima: legalisticamente, licenziosamente, o fondato e guidato dal vangelo?</i></p>
<p>Legalisticamente: L'AT dice di dare il 10% al tempio, perci&ograve; anch'io do il 10%.</p>
<p>Licenziosamente: La decima era dell'AT e non &egrave; pi&ugrave; necessario per essere dichiarati giusti, per cui do quello che mi sento di dare, tanto non ha importanza.</p>
<p>Il vangelo: La mia giustizia viene da Ges&ugrave;, non dall'ubbidienza alla legge. Perci&ograve; sono libero dalla legge, per&ograve; non per appartenere a me stesso ed ai miei desideri. Devo dare tutto me stesso a Ges&ugrave; che mi ha acquisito, e la decima non &egrave; certo sufficiente.</p>

<p><i>8. Quando dono i miei soldi, li do liberamente o cerco di controllarli? Mi fido delle guide spirituali della chiesa perch&eacute; decidano dove meglio impiegarli, o voglio deciderlo io?</i></p>

<p><i>9. Se le persone che guido seguissero il mio esempio nel dare, dove saremmo come chiesa, come comunit&agrave; missionale, o come futura chiesa in via di fondazione?</i></p>
<p>Ogni discepolo ben preparato sar&agrave; come il suo maestro (Lu 6:40). Discepoliamo le persone non solo con le nostre parole ma anche con quello che facciamo.</p>

