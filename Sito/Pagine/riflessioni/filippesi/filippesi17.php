<h1>Rallegrarsi in Cristo (Filippesi 4:2-9)</h1>

<h2>Ripasso</h2>
<i>1. Quale desiderio dovrebbe avere ogni credente? (Fili 3:8,10)</i>
<p>Conoscere Cristo di pi&ugrave;.</p>

<i>2. Qual &egrave; il traguardo della vita cristiana? (Fili 3:12-14,20)</i>
<p>Essere con Cristo per tutta l'eternit&agrave;. Noi siamo cittadini del cielo mediante Cristo, non di qua.</p>

<i>3. In quali modi possiamo essere "nemici della croce di Cristo"? (Fili 3:18-19)</i>
<p>Perdere di vista il traguardo ed essere consumati dalle cose che ci circondano.</p>

<p><i>Nota:</i> I versetti Fili 4:2-3 sono gi&agrave; stati considerati nello studio 5. Ma concentrarsi sul tema della gioia, studieremo in questa riflessione dal versetto 4 in avanti.</p>

<h2>Studio</h2>

<i>4. In un mondo stressante e confusionario, che cosa dobbiamo fare secondo Fili 4:6?</i>
<p>Non preoccuparci n&eacute; essere ansiosi. Leggete Mt 6:25-33.</p>

<i>5. Molti si preoccupano. Si preoccupano addirittura di preoccuparsi. Come invece dovrebbero fare i credenti? (Fili 4:4)</i>
<p>Rallegrarsi sempre. Non ci rallegriamo per le circostanze, ma nel (e per il) Signore. Ci rallegriamo per chi lui &egrave;, per tutte le sue promesse e la sua fedelt&agrave; per adempierle, per quello che ha fatto e sta facendo e far&agrave; per noi.</p>
<p>C'&egrave; sempre un motivo per preoccuparci, ma ci sono sempre 10 motivi maggiori per rallegrarci nel Signore.</p>

<i>6. Discutete l'affermazione: Se ci preoccupiamo o ci rallegriamo dipende da quello su cui ci concentriamo.</i>
<p>Se ci concentriamo sulle circostanze, possiamo essere ansiosi.</p>
<p>Se ci concentriamo sul Signore, sulla sua sovranit&agrave; e bont&agrave;, ci rallegriamo.</p>

<i>7. La prima frase in Fili 4:5 pu&ograve; sempre fuori posto fra queste esortazioni alla gioia. Ma &egrave; anche nel contesto dei contrasti interpersonali fra Evodia e Sintiche (Fili 4:2-3). Nei momenti dei conflitti, perch&eacute; la mansuetudine pu&ograve; essere il risultato della gioia, e la gioia il risultato della mansuetudine?</i>
<p>Se siamo gioiosi nel Signore, la nostra gioia non viene dal "vincere" la discussione ma vedere vincere il Vangelo di Cristo. Cos&igrave; possiamo essere mansueti verso gli altri, sacrificando qualche nostro diritto per essere concordi nel Signore.</p>
<p>Se siamo mansueti verso gli altri, cerchiamo i loro interessi e non dobbiamo preoccuparci n&eacute; agitarci per le discussioni e differenze di opinione, e cos&igrave; non perdiamo la nostra gioia.</p>

<i>8. In ogni circostanza, "il Signore &egrave; vicino" (Fili 4:5). Quali sono le implicazioni?</i>
<p>Il Signore &egrave; vicino, dimorando in noi mediante il suo Spirito. Quindi non ci lascer&agrave; mai (Ebr 13:5 6) e si curer&agrave; di noi. Cos&igrave; dobbiamo essere tranquilli. In quel modo saremo gentili con gli altri. L'ansiet&agrave;, dall'altra parte, porta all'agitazione e scatti d'ira verso gli altri.</p>
<p>Possibilmente il senso &egrave; anche che il ritorno del Signore &egrave; vicino, e quindi (con il pensiero collegato al prossimo versetto) non dobbiamo angustiarci del futuro.</p>

<i>9. Capita a tutti che a volte sperimentiamo ansiet&agrave; nel cuore e nella mente. Cosa dobbiamo fare? (Fili 4:6)</i>
<p>Oltre a rallegrarci nel Signore e ricordarci che &egrave; vicino, dobbiamo pregare. Dobbiamo pregare riguardo a tutto, incluse le cose che ci preoccupano. Dobbiamo affidare a Dio le nostre preoccupazioni (1P 5:6-7; Sal 55:22). Considerate: "Il modo per essere ansioso per niente &egrave; di essere in preghiera per tutto".</p>

<i>10. Notate quello che Paolo dice della preghiera in Fili 4:6. Che cosa dobbiamo includere nelle nostre preghiere?</i>
<p>Dobbiamo chiedere insieme con il ringraziamento, cio&egrave; essere riconoscenti per chi &egrave; Dio e tutto quello che fa per noi. Quando lo facciamo, scopriamo che ci stiamo rallegrando nel Signore piuttosto di preoccuparci.</p>

<i>11. Discutete l'affermazione: Quanto ci preoccupiamo &egrave; collegato a quanto poco preghiamo.</i>

<i>12. Qual &egrave; il risultato di rallegrarci nel Signore e pregare con il ringraziamento? (Fili 4:7)</i>
<p>Invece di avere un cuore ansioso, la pace di Dio riempie il nostro cuore. Non &egrave; una pace ordinaria (Gv 14:27). Non dipende dalle circostanze. &Egrave; oltre la comprensione.</p>

<i>13. Cosa fa la pace di Dio, e dove si trova? (Fili 4:7)</i>
<p>La pace di Dio protegge il nostro cuore e la nostra mente da sentimenti e pensieri negativi, come l'ansiet&agrave;. La chiave &egrave; che si trova in Cristo. Tutte le benedizioni di Dio si trovano in lui (Ef 1:3).</p>

<i>14. Cosa ci esorta Paolo a fare in Fili 4:8, e come &egrave; collegato con l'insegnamento precedente?</i>
<p>Dobbiamo meditare sulle cose buone. Naturalmente, ci&ograve; succede quando ci concentriamo sul Signore invece di concentrarci sulle circostanze, e porta alla gioia, alla pace, e al ringraziamento.</p>

<i>15. Qual &egrave; il punto principale di Fili 4:9?</i>
<p>Dobbiamo mettere in pratica quello che impariamo dalla Parola di Dio. Poi il Dio della pace sar&agrave; con noi e ci dar&agrave; la sua pace.</p>

<i>16. Quali cose vogliamo mettere in pratica da questo studio, affinch&eacute; non ci preoccupiamo?</i>
<p>Alcuni esempi: Rallegrarsi nel Signore, pregare sempre con ringraziamento, concentrarsi sulle cose buone.</p>

<h2>Riassunto</h2>
<p>Rallegrarsi sempre nel Signore, pregare, pensare giusto - cos&igrave; non preoccuparsi ma aver pace.</p>

<h2>Versetto a memoria</h2>
<p>Filippesi 4:6 : Non angustiatevi di nulla, ma in ogni cosa fate conoscere le vostre richieste a Dio in preghiere e suppliche, accompagnate da ringraziamenti.</p>

