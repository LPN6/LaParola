<h1>Fiduciosi in Cristo (Filippesi 1:1-11)</h1>
<p><i>1. In quale modo Paolo descrive s&eacute; stesso e Timoteo? Cosa vuol dire? (Fili 1:1)</i></p>
<p>Servi di Cristo Ges&ugrave;, cio&egrave; era il loro signore e padrone, e hanno rinunciato ai propri diritti per vivere per lui. Cio&egrave;, sono in missione per conto di Dio, tutto il resto &egrave; secondario.</p>

<p><i>2. Chi sono i "santi"? Cosa vuol dire questo termine? (Fili 1:1)</i></p>
<p>Ogni Cristiano vero &egrave; un santo, non solo alcuni speciali. I vescovi e i diaconi erano gruppi di persone separati, ma tutti erano santi. Vuol dire messo da parte (da e per Dio).</p>

<p><i>3. Considera la benedizione per i Cristiani a Filippi. Cosa significano queste parole? (Fili 1:2)</i></p>

<p><i>4. Quale atteggiamento vedi nel cuore di Paolo verso i Cristiani filippesi? (Fili 1:3-4,7-8)</i></p>
<p>Paolo li ama: ringrazia Dio (con gioia) per loro, li ricorda (in modo particolare il loro aiuto), e desidera il loro bene (che &egrave; Cristo).</p>

<p><i>5. Quale atteggiamento hai verso altri credenti? Li ami con affetto profondo in Cristo Ges&ugrave;? Leggi e rifletti su 1Pietro 1:22; 1Giovanni 4:20-21.</i></p>
<p>L'amore del discepolo sar&agrave; approfondito nello <a href="filippesi02.php">studio 2</a>.</p>

<p><i>6. Perch&eacute; poteva Paolo avere questa fiducia che erano veri Cristiani? (Fili 1:5-6)</i></p>
<p>(a) Erano partecipi con Paolo del vangelo; cio&egrave; non solo erano d'accordo con l'insegnamento del vangelo ma hanno vissuto il vangelo, manifestando il Vangelo e di essere discepoli di Cristo. "Partecipare al vangelo" &egrave; un'ottima definizione della vita missionale.<br />
["Partecipazione" in Fili 1:5 &egrave; la parola greca koinonia (e "partecipi" in Fili 1:7 &egrave; una parola simile), che vuol dire 'essere socio' e, nell'ambito religioso, 'comunione'.]</p>
<p>(b) Siccome Dio li ha resi partecipi al Vangelo, completer&agrave; la sua opera in loro.</p>

<p><i>7. Considera Lidia e il carceriere in Atti 16:13-15,32-34. Come hanno mostrato la loro partecipazione al vangelo "dal primo giorno"?</i></p>
<p>Lidia ha mostrato ospitalit&agrave;, il carceriere ha preso cura di Paolo e Sila. Hanno dato quello che avevano per l'opera di Dio e dei suoi servi. Questa domanda e la risposta saranno approfondite nello <a href="filippesi03.php">studio 3</a> sull'ospitalit&agrave;.</p>
<p>La partecipazione in Fili 1:7 si riferisce probabilmente ad un dono dato a Paolo (Fili 4:10-14), che sar&agrave; approfondito negli ultimi <a href="filippesi19.php">due</a> <a href="filippesi20.php">studi</a>.</p>

<p><i>8. In base al fatto che Paolo sapeva che erano Cristiani genuini, quale promessa d&agrave; in Fili 1:6?</i></p>
<p>L'opera di Dio continuer&agrave; in loro fino alla fine, e sar&agrave; completa. (Vedi anche Efes 2:10.)</p>

<p><i>9. Che cosa impariamo da Fili 1:6 dell'opera di Dio?</i></p>
<p>Dio ha iniziato la buona opera in noi portandoci a Cristo (Gv 6:44); Dio continua ad operare in noi fino alla fine (Fili 2:13); l'opera &egrave; buona rendendoci giusti (Fili 1:10-11) come Cristo (Rom 8:29); l'opera sar&agrave; completata quando vedremo Ges&ugrave; (1Gv 3:2).</p>

<p><i>10. A volte possiamo pensare che i nostri peccati e fallimenti fanno s&igrave; che Dio ci abbandoner&agrave;. &Egrave; vero?</i></p>
<p>No - Dio persevera nonostante i nostri fallimenti (Gv 10:27-29; 6:37-40). Un discepolo &egrave; (fra altro) uno studente, qualcuno che impara sempre e non &egrave; gi&agrave; arrivato. Essere sensibili ai propri fallimenti &egrave; un segno positivo che lo Spirito Santo sta operando in noi. Riesci a pensare a qualche esempio personale?</p>

<p><i>11. Rifletti sulle affermazioni: "Non siamo noi che teniamo Dio, ma lui che tiene noi." "Quello che Dio inizia, lui conclude".</i></p>

<p><i>12. Considera Fili 1:7. Come vede Paolo il suo imprigionamento?</i></p>
<p>Come ogni cosa, va valutato dal vangelo, non da quello che ha perso (libert&agrave;, amici, cibo, ecc.). Infatti era un'opportunit&agrave; per i Filippesi mostrare la loro partecipazione nella grazia. (Era anche un'opportunit&agrave; per la testimonianza Fili 1:12-13.) Cos&igrave; dobbiamo valutare la nostra situazione attuale, che sia buona o cattiva, che sia il lavoro o la famiglia o altro - la vita missionale chiede prima di tutto come la mia situazione, qualunque sia, possa essere usata per il progresso del vangelo.</p>

<p><i>13. Quali sono i motivi principali per cui Paolo prega per i Filippesi in Fili 1:9-11?</i></p>
<p>Che l'amore abbondi, che possano apprezzare le cose migliori (cio&egrave; spirituali), che saranno perfetti al ritorno di Cristo, che avranno fatto molte opere di giustizia in Cristo per glorificare Dio.</p>
<p>Nota che sono motivi molto diversi da quelli che noi solitamente chiedere, per noi stessi e per altri. Sono diversi, perch&eacute; sono motivi missionali! Usa questi motivi per pregare per i tuoi parenti e amici prima di finire questo studio.</p>

<p>Ci sono due risposte sbagliate possibili a questo studio, e infatti a tutti questi studi. La prima vede la grandissima distanza fra i discepoli che siamo e i discepoli che dovremmo essere, e risponde disperando o arrendendosi.
La seconda invece si impegna e fa del tutto per essere un discepolo perfetto o almeno migliore con i propri sforzi.
Ma Fili 1:6 non dice, "Dio ha cominciato in voi un'opera buona, e voi la condurrete a compimento". Dobbiamo fidarci della sovranit&agrave; di Dio e la potenza dello Spirito in noi.
Cos&igrave; non ci arrendiamo e non pensiamo di farcela da soli. Invece ci adoperiamo di pi&ugrave; sapendo che Dio sta operando in noi (Fili 2:12-13).</p>

<h2>Riassunto</h2>
<p>Dio conclude quello che inizia. Se siete in Cristo, siate fiduciosi che Dio continuer&agrave; ad operare in voi fino a quando andrete ad essere con il Signore.</p>

<h2>Versetto a memoria</h2>
<p>Filippesi 1:6: Ho questa fiducia: che colui che ha cominciato in voi un'opera buona, la condurr&agrave; a compimento fino al giorno di Cristo Ges&ugrave;.</p>


