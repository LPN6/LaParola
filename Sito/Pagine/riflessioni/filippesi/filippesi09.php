<h1>Trasformati da Cristo (Filippesi 2:12-30)</h1>

<h2>Ripasso</h2>
<p><i>Perch&eacute; Paolo esorta i credenti a stare fermi insieme? (Fili 1:27-28)</i></p>
<p>Aiuta a sostenersi e rafforzarsi mentre combattono per il vangelo in un mondo ostile al cristianesimo.</p>

<p><i>Qual &egrave; il nemico principale allo stare fermi insieme?</i></p>
<p>Orgoglio ed egoismo, non quelli che si oppongono a te mentre cerchi di condividere il vangelo.</p>

<p><i>Come devi superare l'orgoglio e l'egoismo? (Fili 2:3-8)</i></p>
<p>Essere come Cristo. Devi riflettere su di lui e imitarlo (vedi anche Ebrei 12:2-3).</p>

<h2>Studio</h2>
<p><i>&Egrave; importante parlare del vangelo ed anche vivere la vita cristiana. Che cosa potrebbe succedere se tu facessi l'uno e non l'altro?</i></p>
<p>Una buona vita non glorifica Cristo agli altri e non porta le persone a Cristo (qualcuno potrebbe per esempio voler imitare la tua buona vita e diventare buddista). Parlare di Cristo senza una vita pia ti fa apparire ipocriti e nessuno vorrebbe diventare come te.</p>

<p><i>Cosa pensa Dio della societ&agrave; in cui viviamo, e come dovresti essere tu? (Fili 2:14-15)</i></p>
<p>Siamo in una societ&agrave; "storta e perversa", cio&egrave; nelle tenebre spirituali, facendo male. Tu devi essere diverso, irreprensibile e integro, risplendente come le stelle.</p>

<p><i>Secondo Fili 2:14-15, cosa vuole dire "risplendere come stelle"? Vedi anche Matteo 5:14-16.</i></p>
<p>Condurre una vita pia - non mormorare n&eacute; disputare, ma cercare di essere irreprensibile.</p>
<p>Tenere alta la parola di vita, cio&egrave;, parliamo del vangelo.</p>
<p>Un discepolo missionale pensa sempre prima di tutto al vangelo, in quello che fa e in quello che dice.</p>
<p>Questa forma di testimonianza &egrave; approfondita nello <a href="filippesi11.php">studio 11</a>.</p>
<p>[Una frase citata spesso e attribuita a Francisco di Assisi &egrave;, "Predicate sempre il vangelo, e se necessario usate anche le parole". Oltre al fatto che non l'ha mai detto (non appare in tutti i suoi scritti) e non l'avrebbe mai detto (predicava spesso, fino a cinque volte a giorno, era bravo, e insegnava ai suoi seguaci a predicare), non ha senso. Non si pu&ograve; predicare, e nessuno pu&ograve; conoscere il vangelo, senza le parole (Rom 10:14,17). Si potrebbe dire invece, "Predicate sempre il vangelo, e usate sempre le azioni".]</p>

<p><i>Pensa al non credente pi&ugrave; bravo e ammirabile che conosci. In che modo sei diverso? Cristo fa qualche differenza in te?</i></p>

<p><i>Per "risplendere come stelle", devi "adoperarti al compimento della tua salvezza" (Fili 2:12). Cosa vuol dire?</i></p>
<p>Non devi adoperarti per essere salvato, perch&eacute; la salvezza dipende dall'opera di Cristo alla croce. Invece, devi attuare la salvezza gi&agrave; ottenuta facendo scelte giuste con la disciplina affinch&eacute; tu possa essere libero dal peccato.</p>
<p>Ci&ograve; vuol dire l'ubbidienza, un tema che sar&agrave; approfondito nello <a href="filippesi10.php">studio 10</a>.</p>

<p><i>Sei esortato ad adoperarti al compimento della salvezza, ma quale grande verit&agrave; troviamo in Fili 2:13?</i></p>
<p>Bench&eacute; tu debba fare la tua parte per la tua santificazione, &egrave; Dio che opera in te (Fili 1:6). Opera in te affinch&eacute; tu desideri la santit&agrave;, e ti aiuta nelle tue azioni. La volont&agrave; e l'opera di Dio hanno come scopo che siamo santi (1Te 4:3) e trasformati in Cristo (2Cor 3:18).</p>

<p><i>Quale atteggiamento devi avere adoperandoti al compimento della salvezza? Perch&eacute;?</i></p>
<p>Con timore (riverenza) e tremore. Dio ti ha salvato mediante Cristo, e dimori sempre nella sua santa presenza. Come puoi continuare a peccare e rimanere come eri, oppure lavorare contro la sua opera trasformatrice nella tua vita?</p>

<p><i>Molti cosiddetti Cristiani conducono una doppia vita. Come sono nella presenza di altri Cristiani &egrave; diverso di come sono con altri. Cosa ne pensiamo alla luce di Fili 2:12-16?</i></p>
<p>Non deve essere cos&igrave;. Mentre ti adoperi al compimento della salvezza, con Dio che opera in te, tutta la tua vita (personalit&agrave;, rapporti, pensieri, parole, azioni) va trasformata, affinch&eacute; tu risplenda sempre e dappertutto di Cristo. Questo &egrave; vero per te sia quando altri Cristiani sono presenti sia quando sono assenti (Fili 2:12)?</p>

<p><i>Paolo parla di due persone che sono esempi di "risplendere come stelle" (Fili 2:15) e "stimare gli altri superiori cercando non il proprio interesse ma anche quello degli altri" (Fili 2:3-4). Chi sono, e in quali modi troviamo questi due atteggiamenti in loro?</i></p>
<p><b>Timoteo:</b> non serviva s&eacute; stesso ma Cristo e gli altri, era impegnato per l'opera del vangelo (Fili 2:22).</p>
<p><b>Epafrodito:</b> altruistico, umile, pensava ad altri prima di s&eacute; stesso, impegnato per l'opera di Cristo (Fili 2:30). Quando era ammalato e vicino alla morte, era preoccupato - non per la malattia ma perch&eacute; i Filippesi avevano sentito della sua malattia (e ne erano sconvolti).</p>
<p>Sono due discepoli missionali!</p>

<h2>Riassunto</h2>
<p>Lascia che Cristo ti trasformi affinch&eacute; tu possa risplendere come una stella in questo mondo.</p>

<h2>Versetto a memoria</h2>
<p>Filippesi 2:12b-13: Adoperatevi al compimento della vostra salvezza con timore e tremore; infatti &egrave; Dio che produce in voi il volere e l'agire, secondo il suo disegno benevolo.</p>

