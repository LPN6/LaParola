<h1>Prove e carattere spirituale</h1>

<p>Lo scopo di questa lezione pu&ograve; essere diviso in tre parti:<br />
<b>Passato:</b> guardare indietro e riflettere sui benefici ottenuti da sofferenze subite nel passato.<br />
<b>Presente:</b> Avere il giusto atteggiamento verso sofferenze e prove attuali.<br />
<b>Futuro:</b> Prepararsi per reagire bene a sofferenze e prove che verranno.</p>

<p>Dio non condusse gli Israeliti per il deserto portandoli su un comodo lettino. Dio spiega il motivo per le sfide che affrontarono in Deuteronomio 8.</p>
<p><i>1. Quale era il primo obiettivo della prova degli Israeliti nel deserto? (Deuteronomio 8:2)</i></p>
<p>Umiliarli, e per rivelare quello che era nel cuore. Dovevano capire che non volevano n&eacute; potevano ubbidire a Dio, e cos&igrave; essere umiliati davanti a Dio.</p>

<p><i>2. Perch&eacute; gli esseri umani non sono umiliati se non soffrono?</i></p>
<p>La sofferenza rivela i nostri limiti. Capiamo quello che non possiamo fare. Solo quando sperimentiamo i nostri limiti riconosciamo il nostro bisogno del sostegno di Dio.</p>

<p><i>3. Qual era il secondo obiettivo delle prove? (Deuteronomio 8:3)</i></p>
<p>Imparare di non vivere di pane (cio&egrave;, tutto quello che soddisfa i nostri bisogni materiali) solo, ma dal Signore. Viviamo non solo per pane (famiglia, carriera, eccetera), ma per Cristo. L'obiettivo non era solo di umiliare, ma umiliare per avere la vita abbondante che viene da Dio.</p>

<p><i>4. &Egrave; difficile comprendere la verit&agrave; che l'uomo non vive di pane solo, se non abbiamo sperimentato quello che vuol dire perdere tutto. Quando e in che modo hai capito questa verit&agrave;?</i></p>

<p><i>5. Quale era il terzo obiettivo della prova nel deserto? (Deuteronomio 8:16)</i></p>
<p>Benedirli. La sofferenza &egrave; la preparazione per la benedizione. Dio prima ci rende idonei per ricevere la benedizione, e poi ci benedice. La sofferenza &egrave; una 'licenza per la benedizione', e cos&igrave; in realt&agrave; una benedizione travestita. [La benedizione dopo la sofferenza potr&agrave; essere in paradiso.]</p>

<p><i>6. Come ti senti riguardo al fatto che Dio usa le prove per prepararti a ricevere le sue benedizioni?</i></p>

<p><i>7. Quali pericoli ci potrebbero essere, se non ci fossero delle prove? (Deuteronomio 8:12-14)</i></p>
<p>Orgoglio, dimenticare Dio. Siamo vulnerabili a tali pericoli perch&eacute; possiamo illuderci che abbiamo guadagnato le benedizioni per i nostri meriti o perch&eacute; abbiamo fatto bene.</p>

<p><i>8. Sei mai caduto in una tale trappola? Come eri quando eri fiducioso di te, e ottenevi quello che volevi?</i></p>

<p><i>9. Puoi pensare a degli esempi di come il tuo carattere spirituale &egrave; stato formato da Dio attraverso la sofferenza? Sei grato per l'esperienza?</i></p>

<p>Dio non lascia quelli che ama a rimanere in sofferenza senza scopo. Se Dio &egrave; sovrano su ogni cosa, la sofferenza &egrave; uno strumento della provvidenza divina. E la provvidenza divina &egrave; sempre buona. Quindi, il risultato della sofferenza deve essere per forza buono. Solo quelli che credono in questa verit&agrave; per fede possono ringraziare Dio per la sofferenza.</p>

<p>C'&egrave; una verit&agrave; in comune fra Giobbe e Geremia: la loro fede era gi&agrave; stata preparata per resistere alla sofferenza.</p>
<p><i>10. Leggi Giobbe 1 per imparare l'atteggiamento che devi avere in mezzo alla sofferenza. Prima di tutto, fai un riassunto del carattere di Giobbe. (Giobbe 1:1-5)</i></p>
<p>Integro e giusto, temeva Dio, fuggiva il male. Molta fede nell'impegno per i figli. Molto ricco.</p>

<p><i>11. Fai un riassunto della sofferenza di Giobbe. (Giobbe 1:13-20)</i></p>
<p>Perse tutto improvvisamente, anche i figli e la salute.</p>

<p><i>12. Come si comport&ograve; Giobbe quando inizi&ograve; a soffrire? (Giobbe 1:20-22)</i></p>
<p>Non diede la colpa a Dio, n&eacute; era in preda alla disperazione. Riconobbe la sovranit&agrave; di Dio.</p>

<p><i>13. Descrivi un periodo in cui ti sentivi risentimento verso Dio perch&eacute; non riuscivi a capire quello che succedeva.</i></p>

<p><i>14. Qual era il motivo per cui Giobbe poteva adorare Dio e non peccare, nonostante la forte sofferenza? (Giobbe 1:21)</i></p>
<p>Riconobbe la sovranit&agrave; di Dio confessando che Dio d&agrave; e toglie. Non diede la colpa a Dio, perch&eacute; aveva una fede ferma nella sovranit&agrave; di Dio.</p>

<p><i>15. &Egrave; molto importante che continui a nutrire la nostra fede e crescere nella conoscenza della sovranit&agrave; di Dio per non peccare. Spiega perch&eacute; &egrave; cos&igrave;.</i></p>
<p>Il carattere di Giobbe non era formato nella sofferenza. Era gi&agrave; pronto per soffrire, la sofferenza solo rivel&ograve; il suo carattere (a Satana e ad altri).</p>

<p>Vediamo quello che fece Geremia quando soffriva. Leggi Lamentazioni 3:19-23.</p>
<p><i>16. Di che cosa si ricord&ograve; Geremia quando era sconsolato? (Lamentazioni 3:21-22)</i></p>
<p>Dell'amore e della compassione di Dio. Nella sua afflizione, medit&ograve; sul carattere di Dio.</p>

<p><i>17. Quale benedizione speciale diede Dio a Geremia quando era sconsolato?</i></p>
<p>Di gustare l'amore e la compassione di Dio nuovamente ogni mattina. Probabilmente Geremia pregava e rifletteva sul carattere di Dio ogni mattina in mezzo all'afflizione, il segreto della sua vittoria sulla sofferenza.</p>

<p><i>18. Riflettere tranquillamente sul carattere di Dio ti ha aiutato nei periodi di prova?</i></p>

<p><i>19. Secondo Salmo 119:67,71; Romani 8:28; 2Corinzi 1:3-4, quali sono alcuni benefici della sofferenza?</i></p>
<p>Ti insegna a ubbidire alla Parola di Dio, e capirla.<br />
Sperimenti la provvidenza di Dio, che porta bene dall'afflizione.<br />
Ti d&agrave; saggezza e forza per consolare altri nelle loro afflizioni.</p>

<p><i>20. Quali benedizioni spirituali hai ottenuto in periodi di prova nel passato? Puoi affermare con il salmista, "&egrave; stata un bene per me l'afflizione subita"? Puoi incoraggiare altri che stanno soffrendo con quello che hai imparato?</i></p>

<h2>Riassunto</h2>
<p>I Cristiani non sono liberati dalla sofferenza subito quando credono in Ges&ugrave; Cristo.<br />
La profonda provvidenza di Dio sta operando nella sofferenza e nell'afflizione dei credenti.<br />
Dio forma il nostro carattere spirituale tramite la sofferenza.
</p>

