<h1>Contenti in Cristo (Filippesi 4:10-23)</h1>

<h2>Ripasso</h2>
<p><i>Che cosa dovrebbe caratterizzare la vita del credente? Perch&eacute;? (Fili 4:4)</i></p>
<p>Rallegrarsi nel Signore sempre, perch&eacute; &egrave; buono e in controllo.</p>

<p><i>Che cosa non dovrebbe caratterizzare la vita del credente, e come lo dovremmo togliere? (Fili 4:6)</i></p>
<p>L'ansiet&agrave;. Dobbiamo invece pregare con ringraziamento, affidare le preoccupazioni al Signore, rallegrarci in lui, e riflettere sulle cose buone.</p>

<p><i>Quando mettiamo in pratica quello che Dio ci insegna, cosa ci promette Dio?</i></p>
<p>Il Dio della pace promette di essere con noi e di darci la sua pace, che supera la comprensione.</p>

<h2>Studio</h2>
<p><i>Molti nella societ&agrave; cercano la contentezza. Dove pensano di trovarla?</i></p>
<p>In circostanze migliori, denaro e possessi materiali, potere, prestigio, fama, salute, famiglia, buona figura, rapporti, fare cose piacevoli.</p>

<p><i>In generale, perch&eacute; le persone non trovano la contentezza in queste cose?</i></p>
<p>Alla fine, non soddisfanno completamente, o ci abituiamo e ne vogliamo di pi&ugrave;, o sono temporanee. Considerate Ecclesiaste 2:9-11.</p>

<p><i>Paolo era genuinamente contento. Cosa impariamo della contentezza di Paolo? (Fili 4:11-12)</i></p>
<p>Non dipendeva da quello che aveva o non aveva, n&eacute; dalle sue circostanze.</p>

<p><i>Qual era il segreto della sua contentezza? (Fili 4:13)</i></p>
<p>Attraverso Cristo, Paolo era convinto che Dio l'avrebbe rafforzato e aiutato in ogni situazione della vita. A prescindere della situazione, Paolo si fidava di Dio per soddisfare ogni suo bisogno. (Il versetto &egrave; spesso citato male nel senso "Io posso fare ogni cosa", ma dal contesto &egrave; "Io posso vivere in ogni cosa/situazione".) Cos&igrave;, il Signore l'ha soddisfatto (Gv 6:35).</p>

<p><i>Una delle chiavi per essere contenti in Cristo &egrave; di fidarsi delle promesse di Dio. Ne abbiamo viste diverse in Filippesi. Condividete brevemente alcune che abbiamo visto - alcune sono nei versetti a memoria.</i></p>
<p>Fili 1:6 - Dio completer&agrave; la sua buona opera in noi<br />
Fili 2:13 - Dio opera in noi<br />
Fili 3:9 - Dio d&agrave; la giustizia tramite la fede<br />
Fili 3:20 - la nostra cittadinanza &egrave; in cielo, e aspettiamo un Salvatore<br />
Fili 4:13 - Dio ci d&agrave; la forza per fare tutto</p>

<p><i>Cosa dice 2Cor 1:20 delle promesse di Dio?</i></p>
<p>Sono adempiute in Cristo. Cio&egrave;, ricevere le promesse di Dio essendo in Cristo. In Cristo siamo benedetti e troviamo la vera contentezza eterna.</p>

<p><i>Quando siamo contenti, come i credenti filippesi, qual &egrave; il risultato? (Fili 4:14-16)</i></p>
<p>Doniamo e sosteniamo altri, piuttosto di essere avari (perch&eacute; troviamo la contentezza non nel denaro per noi stessi, ma nel denaro usato per aiutare gli altri e per promuovere il Vangelo).</p>
<p>Questo uso missionale del denaro, pensando al suo uso per il Vangelo, sar&agrave; approfondito nello <a href="filippesi20.php">studio 20</a>.</p>
<p>Possiamo dire la stessa cosa delle altre cose in cui si cerca di essere contenti elencate all'inizio dello studio: possiamo servire invece di cercare potere, prestigio, fama, buona figura; possiamo investire il nostro tempo in quello che promuove il Vangelo invece di cose che piacciono a noi; eccetera.</p> 

<p><i>Come considera Dio il nostro dare agli altri, soprattutto a quelli nel ministero cristiano? (Fili 4:18)</i></p>
<p>A Dio, &egrave; come un sacrificio gradevole. Produce anche frutto per i Filippesi (Fili 4:17), che potrebbe essere la provvisione da parte di Dio (Fili 4:19) ma anche la crescita e la maturit&agrave; del carattere dei Filippesi. Considerate le parole di Ges&ugrave; in Marco 9:41. Paolo, essendo un discepolo missionale di Cristo, era pi&ugrave; interessato nella crescita del Vangelo nella vita dei Filippesi a causa del dono che nel denaro del dono che ha ricevuto.</p>

<p><i>Di quale grande verit&agrave; Paolo ci ricorda in Fili 4:19-20?</i></p>
<p>Dio provveder&agrave; a tutti i nostri bisogni in Cristo. &Egrave; il debitore di nessuno. Pu&ograve; provvedere abbondantemente. Quindi in Cristo siamo contenti, e glorifichiamo il nostro Dio e Padre per sempre.</p>

<p><i>Quali sono le ultime parole di Paolo ai Filippesi? Cosa ne impariamo? (Fili 4:23)</i></p>
<p>Che la grazia di Cristo sar&agrave; con loro. La cosa pi&ugrave; preziosa &egrave; la grazia di Dio per noi in Cristo. &Egrave; per grazia che siamo salvati e riconciliati a Dio, e abbiamo ogni benedizione in Cristo.</p>

<h2>Riassunto</h2>
<p><i>Essere contenti in Cristo, e meditare sulle promesse di Dio che sono tutte adempiute in Cristo.</i></p>

<h2>Versetto a memoria</h2>
<p><i>Filippesi 4:13 - Io posso ogni cosa in colui che mi fortifica.</i></p>


