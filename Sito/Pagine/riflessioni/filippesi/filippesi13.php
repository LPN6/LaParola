<h1>La giustizia di Cristo</h1>

<p>Paolo afferma in Filippesi 3:8-9 che tutto quello che &egrave; e che aveva fatto era un danno e spazzatura al fine di essere trovato in Cristo con la giustizia che si ha mediate la fede in Cristo, che viene da Dio. Ma qual &egrave; questa giustizia?
<h2>Sintesi</h2>
<p>La giustizia perfetta di Ges&ugrave; Cristo &egrave; accreditata alle persone affinch&eacute; Dio li veda come se fossero giuste. &Egrave; diversa dal perdono (che non d&agrave; la giustizia) e dalla santificazione (che &egrave; la trasformazione del carattere affinch&eacute; la persona sia pi&ugrave; santa o giusta). La giustizia di Cristo viene ricevuta per fede e non &egrave; prodotta interiormente come merito; &egrave; fondata invece sull'ubbidienza perfetta di Cristo.</p>
<p>Questa sintesi sar&agrave; spiegata e approfondita nei seguenti brani biblici.</p>

<h2>Il grande scambio</h2>
<p><i>1. Secondo 2Corinzi 5:21, che cosa riceviamo noi e che cosa riceve Ges&ugrave; Cristo?</i></p>
<p>Ges&ugrave; &egrave; diventato peccato pur non avendo conosciuto peccato. Ci&ograve; non vuol dire che &egrave; diventato un peccatore, ma che il suo stato &egrave; diventato quello del peccato.</p>
<p>Nello stesso modo, noi diventiamo giustizia - non che diventiamo giusti, ma che il nostro stato cambia in giustizia di Dio.</p>
<p>Ci sono due collegamenti fra i due lati: lo scopo per cui Cristo diventa peccato &egrave; affinch&eacute; noi diventiamo giustizia, e il modo in cui diventiamo giustizia &egrave; "in lui", cio&egrave; Cristo. In questa unione con Cristo il nostro peccato passa a Ges&ugrave; e la giustizia di Ges&ugrave; passa a noi.</p>

<h2>La giustizia accreditata</h2>
<p>In Romani 4, la parola chiave &egrave; &#955;&#959;&#947;&#943;&#950;&#959;&#956;&#945;&#953; (logizomai), che viene utilizzata 11 parole, soprattutto riflettendo su Genesi 15:6 che parla di Abraamo. &Egrave; un termine finanziario, con il senso di accreditare al conto, come di una banca, e viene tradotta "mettere in conto", "calcolare", "contare" o, rimuovendo l'immagine economica, "imputare", "considerare", "dichiarare".</p>

<p><i>2. Secondo Romani 4:1-2, come non &egrave; stato giustificato (cio&egrave; ricevere giustizia, in un senso che sar&agrave; considerato dopo) Abraamo, e che cosa ne era la conseguenza?</i></p>
<p>Non secondo la carne (cio&egrave;, per le sue proprie caratteristiche) n&eacute; per opere (quello che ha fatto), cos&igrave; non poteva vantarsi davanti a Dio, perch&eacute;, nelle parole di Paolo, era tutto un danno e spazzatura (Fili 3:7-8).</p>

<p><i>3. Secondo Romani 4:3, come &egrave; stato giustificato Abraamo?</i></p>
<p>La sua fede &egrave; stata calcolata (logizomai) come se fosse giustizia. Non &egrave; che sia diventato pi&ugrave; giusto, ma che Dio ha fatto un bonifico al conto di Abraamo che misurava non la sua ricchezza ma la sua giustizia. Per cui Abraamo era considerato giusto, anche se non lo era.</p>
<p>Se continuiamo con l'analogia, se c'&egrave; un bonifico al nostro conto, la giustizia deve essere trasferita da un altro conto. Vedremo quale conto nel prossimo brano.</p>
<p>Collegando con 2Cor 5:21, diventiamo giustizia non nel senso che siamo giusti nelle nostre azioni, ma riceviamo la grazia di essere considerati giusti.</p>

<p><i>4. Spiega il contrasto in Romani 4:4-5.</i></p>
<p>Invece di guadagnare o meritare la giustizia (e cos&igrave; essere in grado di vantarsi), chi crede vede la sua fede calcolata come giustizia. &Egrave; per grazia (Romani 4:4), perch&eacute; Dio non &egrave; obbligato a considerare la tua fede in quel modo.</p>

<p>Questa giustificazione &egrave; una benedizione (Romani 4:6-8), e include un altro "messo in conto". Non solo Dio accredita la fede come giustizia, ma neanche accredita (sempre logizomai, ma qui nel senso di addebitare) il peccato come iniquit&agrave;. Ogni fattura per il tuo peccato ti arriva con "PAGATO" gi&agrave; timbrato sopra (2Cor 5:19).</p>

<p>Questa benedizione non &egrave; solo per Abraamo ma anche per tutti quelli che credono (Romani 4:9-12).</p>
<h2>L'ubbidienza di uno solo</h2>
<p>Romani 5:17-19 contrasta gli effetti delle vite di Adamo e di Ges&ugrave;.</p>

<p><i>5. Che cosa succede a tutti a causa di quello che Adamo fece?</i></p>
<p>La sua sola trasgressione &egrave; risultata nella morte e nella condanna di tutti, perch&eacute; per la sua disubbidienza sono costituiti [la Nuova Riveduta erroneamente traduce "resi" invece di costituiti come la seconda met&agrave; del versetto e come le altre versioni italiane] peccatori, cio&egrave; dichiarati peccatori anche prima di aver commesso un peccato, perch&eacute; ereditiamo la sua natura corrotta. Questa &egrave; la dottrina del peccato originale.</p>

<p><i>6. Che cosa succede a causa di quello che Ges&ugrave; fece? A chi?</i></p>
<p>Per mezzo di lui, regneranno nella vita quelli che ricevono la sua grazia e il suo dono.</p>
<p>La sua ubbidienza era per la giustificazione di tutti. (Anche se in Romani 5:18, tutti e due erano per ogni persona, nel senso di "in vista di", da Romani 5:17 &egrave; chiaro che solo alcuni ricevono il dono mentre tutti ereditano la condanna.)</p>
<p>Per la sua ubbidienza, molti sono costituiti (dichiarati, che &egrave; come imputati o calcolati ma usando un linguaggio legale piuttosto di commerciale) giusti. ["Molti" due volte in 5:18 &egrave; in confronto con "uno", non in confronto con "tutti" cio&egrave; tanti ma non tutti. Infatti, dal contesto, molti sono stati costituiti peccatori nel senso di tutti, ma molti saranno costituiti giusti nel senso di quelli che ricevono la sua grazia.]</p>

<p>Quindi:<br />
<i>Adamo:</i> disubbidienza &rarr; colpa imputata &rarr; condanna<br />
<i>Ges&ugrave;:</i> ubbidienza &rarr; giustizia imputata &rarr; giustificazione</p>

<p>L'ubbidienza di Ges&ugrave; che viene imputata &egrave; di solito considerata come sia la sua giustizia inerente che ha dall'eternit&agrave; (chiamata anche "ubbidienza passiva"), sia la sua "ubbidienza attiva", cio&egrave; l'ubbidienza nella sua vita come uomo (Ebrei 5:8), in modo particolare sottomettersi alla sua morte sulla croce (che forse &egrave; il "solo atto di giustizia" Rom 5:18).</p>

<p>La nostra giustizia deriva non dalla nostra ubbidienza, ma dall'ubbidienza di Cristo che riceviamo nel grande scambio; i meriti di Cristo che sono trasferiti dal conto di Ges&ugrave; (che ha infiniti meriti) e accreditati al nostro, e diventano contati come i nostri meriti davanti a Dio.</p>
 
<h2>La giustizia non tua</h2>
<p>Ritornando al punto di partenza in Filippesi 3:8-9, possiamo capire meglio il ragionamento di Paolo.</p>

<p><i>7. Come &egrave; descritta la giustizia sua (e tua)?</i></p>
<p>Derivante dalla legge<br />
Un danno e spazzatura in confronto con Cristo</p>

<p><i>8. Come &egrave; descritta la giustizia da Dio?</i></p>
<p>Si ha mediante la fede in Cristo<br />
Viene da Dio<br />
Basata sulla fede</p>

<p>Non c'&egrave; nessuno merito nostro, perch&eacute; quello che facciamo non &egrave; niente, ma semplicemente riceviamo la giustizia che ci &egrave; donata.</p>

<h2>Implicazioni</h2>
<h3>Certezza della salvezza</h3>
<p>Fondata su Cristo, non sulla tua spiritualit&agrave; o piet&agrave;.<br />
Cos&igrave; la pace della coscienza deriva da un fondamento oggettivo (Cristo), non interiore che pu&ograve; cambiare con il tuo comportamento e i tuoi sentimenti.</p>

<h3>Umilt&agrave;</h3>
<p>Nessun vanto umano. La gloria va solo a Dio perch&eacute; i meriti sono di Ges&ugrave; Cristo.</p>

<h3>Libert&agrave;</h3>
<p>Ubbidienza come risposta, non come condizione di un rapporto con Dio.</p>

<h3>Adorazione</h3>
<p>Perch&eacute; la salvezza &egrave; interamente opera di Dio.</p>

