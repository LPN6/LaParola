<h2>Introduzione al libro di Filippesi</h2>
<p><i>1. Leggi Atti 16:11-40 e 1Tessalonicesi 2:1-2. Che cosa scopri di Filippi e della sua chiesa?</i></p>
<p>Filippi era una citt&agrave; importante, una colonia romana, e aveva un buon commercio.</p>
<p>La chiesa all'inizio era composta da Lidia e un carceriere, con le loro famiglie, e forse una serva. I Cristiani erano forse emozionati per le tante meraviglie ma anche preoccupati per la persecuzione.</p>

<p><i>2. Leggi tutta la lettera ai Filippesi. Che cosa scopri della chiesa a Filippi e della situazione attuale, e quali temi generali osservi?</i></p>
<p>Epafrodito &egrave; stato mandato da Filippi a Paolo con un dono, e ha aiutato Paolo in prigione; Paolo poi ha mandato Epafrodito a Filippi perch&eacute; era malato.</p>
<p>Alcuni temi: ringraziamento per la partecipazione nel vangelo, la situazione di Paolo e di Epafrodito, come stare fermi nella fede soprattutto nell'opposizione, seguire l'esempio dell'umilt&agrave; di Ges&ugrave;, avvertimento contro l'insegnamento falso.</p>

