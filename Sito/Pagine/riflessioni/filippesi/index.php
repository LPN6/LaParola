<h1>Filippesi</h1>
<p class="primalettera">
Questa &egrave; una serie di studi sul discepolato, in modo particolare il discepolato missionale - un termine inventato per esprimere l'idea di qualcuno che impara da e segue Cristo (un discepolo) pensando sempre a come trasformare verso Cristo s&eacute; stesso, gli altri, e il posto in cui si trova (missionale).
