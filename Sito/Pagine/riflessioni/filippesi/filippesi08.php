<h1>Una responsabilit&agrave; per servire</h1>

<h2>Il fondamento del servizio</h2>
<p>Vediamo in Luca 22:24-27 quello che Ges&ugrave; dice dell'atteggiamento nel servizio.</p>

<i>1. Qual era la causa della contesa fra i 12 discepoli? (Luca 22:24)</i>
<p>Chi doveva essere considerato il pi&ugrave; grande.</p>
<p>Nota che avevano fatto un "corso" di discepolato a tempo pieno per tre anni a questo punto. Vediamo che il cuore del servo non &egrave; una cosa che si ha facilmente, n&eacute; solo con l'insegnamento.</p>

<i>2. Qual confronto fa Ges&ugrave; fra il regno di Dio e i regni della terra per insegnare le loro nature opposte?</i>
<p>I re e i responsabili del mondo vogliono signoreggiare, ottenere il rispetto, e stabilire l'autorit&agrave;. I responsabili del regno di Dio ottengono autorit&agrave; e onore in base a quanto servono con umilt&agrave;.</p>

<i>3. In che modo Ges&ugrave; descrive s&eacute; stesso? (Luca 22:27)</i>
<p>Come uno che serve (anche se doveva essere quello che andava servito).</p>

<i>4. Quali sono i due punti che Ges&ugrave; voleva insegnare ai suoi discepoli? (Luca 22:26-27)</i>
<p>I responsabili nel regno di Dio dovrebbero essere diversi dai leader del mondo, servendo invece di essere serviti.</p>
<p>Se Ges&ugrave;, il loro maestro, li serviva, anche loro dovevano seguire questo esempio e servire gli altri.</p>

<i>5. Quale sono alcuni esempi del servizio di Ges&ugrave;?</i>
<p>L'incarnazione (Fili 2:7), lavare i piedi dei discepoli (Fili 2:8a), la sua morte (Fili 2:8b).</p>

<i>6. Quali sono alcuni dei motivi per cui &egrave; difficile servire nello stesso modo di Ges&ugrave;?</i>
<p>&Egrave; difficile abbassarsi; sembra mettersi in vista; essere gi&agrave; troppo impegnato; altri potrebbero continuare a chiedermi di servire; fisicamente difficile; mi hanno fatto male o approfittato di me quando ho servito.</p>

<h2>L'atteggiamento del servizio</h2>
<p>Leggi 1Pietro 4:9-11.</p>

<i>7. Perch&eacute; l'ospitalit&agrave; e il mormorio sono collegati?</i>
<p>Perch&eacute; alcuni mormoravano mentre mostravano ospitalit&agrave; - sapevano che lo dovevano fare, e lo facevano nonostante il costo, ma non lo facevano volentieri.</p>

<i>8. Perch&eacute; a volte mormoriamo mentre serviamo?</i>
<p>Serviamo senza aver sperimentato (o capito o ricordato) la grazia di Dio; &egrave; solo un lavoro.</p>
<p>Quando altri non fanno niente mentre noi serviamo (Lu 10:40).</p>
<p>Quando non c'&egrave; riconoscimento, sostegno, incoraggiamento.</p>
<p>Quando costretti a fare cose che non ci piacciono o per cui non abbiamo un dono.</p>
<p>Continuando a servire nello stesso modo, diventa un'abitudine invece di un atto di servizio</p>

<i>9. Hai mai mormorato mentre servivi?</i>

<i>10. Quali aiuti abbiamo per servire con l'atteggiamento giusto? (1Pietro 4:10-11)</i>
<p>I doni della grazia di Dio e la forza che Dio fornisce. Cos&igrave; la gloria va a Dio e non a noi.</p>

<h2>Due modelli di servizio</h2>
<p>In 3Giovanni, leggiamo di due individui. Uno &egrave; lodato da Giovanni, l'altro rimproverato, anche se tutti e due servivano nella chiesa.</p>
<p>Nota che ci sono due altri ottimi esempi in Fili 2:19-30, ma parleremo di loro nel prossimo studio.</p>

<i>11. Cosa sappiamo del servizio di Gaio? (3G 1-6)</i>
<p>Aveva la verit&agrave; (come gli Efesini in Apocalisse (Ef 2:1-7), ma Gaio aveva anche l'amore), camminava nella verit&agrave;, cio&egrave; era fedele, in favore dei fratelli, soprattutto gli stranieri (probabilmente sconosciuti, evangelisti itineranti), con amore e con ospitalit&agrave;.</p>

<i>12. Cosa sappiamo del servizio di Diotrefe? (3G 9-10)</i>
<p>Voleva il primato nella chiesa, quindi non riceve altri e li critica, rifiuta ospitalit&agrave; (perch&eacute; potevano essere un pericolo alla sua leadership).</p>

<h2>Le benedizioni del servizio</h2>
<p>Il servizio prima di tutto &egrave; una benedizione per gli altri, ma anche una benedizione per chi serve.</p>

<i>13. Quale benedizione promette Ges&ugrave; ai veri servi in Matteo 23:12?</i>
<p>Saranno innalzati, a volte in questa vita e a volte nella prossima. Quindi nell'abbassamento, nella critica, nelle offese che riceveremo, possiamo ricordarci di questa promessa.</p>

<i>14. Quale benedizione promette Ges&ugrave; ai veri servi in Matteo 10:42?</i>
<p>Non perder&agrave; il suo premio, anche per un atto cos&igrave; semplice (un bicchiere d'acqua fresca) a qualcuno di poca importanza.</p>

<i>15. Quale benedizione promette Ges&ugrave; ai veri servi in Luca 6:38?</i>
<p>Riceveremo nello stesso modo in cui diamo. Quello che il servizio ci costa, Dio provveder&agrave;.</p>

<i>16. Quale benedizione promette Ges&ugrave; ai veri servi in Apocalisse 2:10?</i>
<p>La corona della vita.</p>

