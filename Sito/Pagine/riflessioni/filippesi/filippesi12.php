<h1>Giusti in Cristo (Filippesi 3:1-9)</h1>

<h2>Ripasso</h2>
<p><i>Come dovresti essere mentre vivi in una societ&agrave; "storta e perversa"? (Filippesi 2:15)</i></p>
<p>Risplendente come stelle, cio&egrave;, risplendere in un mondo spiritualmente nelle tenebre (Mt 5:14-16).</p>

<p><i>Come si splende come una stella?</i></p>
<p>Vivere come Cristo (essere pio) e condividere il vangelo con altri (tenere alta la parola di vita).</p>

<p><i>Cosa devi fare, e che cosa ti deve incoraggiare? (Filippesi 2:12-13)</i></p>
<p>Adoperarti al compimento della propria salvezza, liberandoti dal peccato, ma sapendo che &egrave; Dio in noi che opera.</p>

<h2>Studio</h2>
<p><i>1. Che cosa diresti se Dio ti chiedesse, "Perch&eacute; ti devo accettare e lasciarti entrare in paradiso?"</i></p>
<p>Molti direbbero che si sono comportati bene, o moralmente o spiritualmente. Dio deve loro qualcosa perch&eacute; hanno provato a fare la cosa giusta.</p>

<p><i>2. Cosa pensiamo dei brani Romani 3:9-10; Isaia 64:6?</i></p>
<p>La Bibbia dichiara che nessuno &egrave; giusto (accettato da Dio) a causa del peccato. Anche i nostri atti giusti sono come un abito sporco, cio&egrave;, mancano allo standard della giustizia. Questo &egrave; perch&eacute; spesso non facciamo le nostre buone opere per fede (Rom 14:23) o per la gloria di Dio (1Cor 10:31), ma secondo il nostro standard.

<p><i>3. Il nostro bisogno pi&ugrave; grande &egrave; la giustizia, non la felicit&agrave; o la contentezza o la realizzazione o la salute o qualsiasi altra cosa. Perch&eacute; &egrave; cos&igrave;?</i></p>
<p>Senza la giustizia non siamo giusti con Dio, e quindi non saremo accettati da Dio nel giorno di giudizio. Invece, saremo respinti e andremo in inferno.</p>

<p><i>4. Paolo riteneva di avere pi&ugrave; motivi di vantarsi di quello che era e di quello che aveva fatto di altre persone (Filippesi 3:4-6). Quali erano questi motivi?</i></p>
<p>Era un giudeo autentico, di una trib&ugrave; importante, circonciso quando si doveva.<br />
Era puro e irreprensibile secondo la legge mosaica.<br />
Era zelante per (quello che considerava) la verit&agrave;, perseguitando che pensava diversamente.</p>

<p><i>5. Se dovessi fare una lista simile, che cosa scriveresti? Che cosa di buono hai fatto per Dio? Quale sono le tue buone caratteristiche? Che cosa sei bravo a fare (azioni spirituali, impegni lavorativi o famigliari, eccetera)?</i></p>

<p><i>6. Invece di vantarsi, come si considerava il suo passato e perch&eacute;? (Filippesi 3:7-9)</i></p>
<p>Considerava tutta la sua "vita giusta" come danno, come spazzatura, perch&eacute; sapeva che niente poteva renderlo giusto (accettabile) a Dio, tranne la fede in Ges&ugrave; Cristo. Anzi, non era che non valesse niente, era un danno, cio&egrave; negativo invece di zero. Perch&eacute; ogni cosa che sei o che hai fatto pu&ograve; essere un motivo di vantarti, a pensare che hai fatto qualcosa che ti rende pi&ugrave; accettevole a Dio.</p>

<p><i>7. Il vangelo dichiara che possiamo essere dichiarati giusti. Come? (Filippesi 3:9; vedi anche Romani 3:20-26)</i></p>
<p>Non con la propria giustizia, ma con una che Dio ci d&agrave;, che otteniamo mediante la fede in Cristo ma &egrave; provveduta mediante la redenzione che &egrave; in Ges&ugrave; Cristo, ottenuta con la sua morte.</p>

<p><i>8. A causa di questa gloriosa verit&agrave;, cosa pensa di Cristo in Filippesi 3:7-9?</i></p>
<p>Considerava tutto un danno a causa di Cristo (7).<br />
Considerava tutto un danno di fronte all'eccellenza della conoscenza di Cristo Ges&ugrave; (8).<br />
Considerava tutto spazzatura al fine di guadagnare Cristo ed essere trovato in lui (8-9).<br />
Paolo voleva solo Cristo. Possiamo dire altrettanto?</p>
<p>Questa completa dipendenza da Cristo sar&agrave; approfondita nello <a href="filippesi13.php">studio 13</a>.</p>

<p><i>9. Come puoi incoraggiare questo atteggiamento in te stesso, senza disprezzare l'importanza di servire in chiesa, leggere la Bibbia e pregare ogni giorno, testimoniare, eccetera, che sono tutte cose giuste?</i></p>
<p>Bisogna fare queste cose perch&eacute; sono giuste e utili, non per renderti giusto. Ma la tentazione, a causa del proprio orgoglio, &egrave; sempre di pensare alle cose giuste che fai come elementi nella tua giustizia. Soprattutto se ti paragoni agli altri - se sei pi&ugrave; bravo degli altri (che pu&ograve; essere vero), pensi che Dio ti trover&agrave; pi&ugrave; accettevole o pi&ugrave; giusto (che &egrave; falso). La parabola del fariseo e del pubblicano insegna questo (Luca 18:9-14) - chi &egrave; stato dichiarato giusto alla fine?<br />
<p>Un altro atteggiamento da evitare &egrave; di pensare che Dio ti deve qualcosa a causa di quello che hai fatto. "Se ho pregato 1000 volte, perch&eacute; Dio mi ha dato quello che ho voluto?" "Se Dio mi guarisce, promette di andare in chiesa ogni settimana." E cos&igrave; via. Non c'&egrave; niente che puoi fare che ti rende migliore o pi&ugrave; gradito a Dio, in confronto con l'eccellenza della giustia di Cristo.</p>

<p>Il primo versetto del capitolo (Filippesi 3:1) comanda di rallegrarsi, che sar&agrave; approfondito nello <a href="filippesi17.php">studio 17</a>.</p>

<p><i>10. Alla luce di queste verit&agrave;, Paolo ci dice in Filippesi 3:2 di guardarci da chi?</i></p>
<p>Da quelli che ci vogliono togliere la verit&agrave; che la fede sola in Ges&ugrave; Cristo ci dona la giustizia di Dio. Alcuni aggiungono altre cose a Ges&ugrave;, altri sottolineano ancora le buone opere per essere giusti, altri pensano di essere migliori agli occhi di Dio. Tolgono dalla gloria di Cristo, solo lui pu&ograve; farci apparire giusti davanti ad un Dio santo, quando mettiamo la nostra fiducia in lui.</p>

<p><i>11. Come descrive Paolo quelli che sono giusti davanti a Dio? (Filippesi 3:3)</i></p>
<p>Adorano Dio per mezzo del suo Spirito (sono nati dello Spirito), si vantano in Cristo, non mettono la fiducia nella carne, cio&egrave; non si fidano della propria giustizia n&eacute; di atti giusti.</p>

<p><i>12. Una delle pi&ugrave; grandi profezie dell'Antico Testamento riguardo Cristo &egrave; Geremia 23:5-6. Che cosa dichiara, e perch&eacute; dobbiamo rallegrarci?</i></p>
<p>Dichiara che non soltanto il Cristo verr&agrave; dalla stirpe di Davide, ma che lui stesso sar&agrave; il SIGNORE (=Yahweh) e la nostra giustizia (cio&egrave;, non soltanto &egrave; giusto lui, ma sar&agrave; la nostra giustizia). Secondo Romani 4:23-25, questo era tramite la sua morte per il perdono delle nostre offese (perch&eacute; sulla croce ha presso la punizione delle offese) e la sua risurrezione (perch&eacute; abbiamo una nuova vita insieme a lui, una vita giusta Rom 6:4-5; 2Cor 5:15; Col 3:1-3).</p>

<p><i>13. In quali momenti ti senti fiducioso che sei un Cristiano? Quando dovresti?</i></p>
<p>Molti si sentono fiduciosi di essere un Cristiano quando fanno la volont&agrave; di Dio. &Egrave; giusto cercare di piacere al Signore, ma dobbiamo essere sempre fiduciosi del nostro stato davanti a Dio, perch&eacute; la nostra posizione davanti a Dio non si basa sulle nostre opere, ma sull'opera di Cristo per noi.</p>

<h2>Riassunto</h2>
<p>Siamo accettati da Dio tramite la fede in Cristo, perch&eacute; Cristo &egrave; la nostra giustizia.</p>

<h2>Versetto a memoria</h2>
<p>Filippesi 3:8: Ritengo che ogni cosa sia un danno di fronte all'eccellenza della conoscenza di Cristo Ges&ugrave;, mio Signore.</p>

