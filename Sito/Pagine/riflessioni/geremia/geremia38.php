<h1>Geremia 38</h1>
<p><b>Ger 26</b> (vedi <a href="geremia26.php">2 riflessioni fa</a>) All'inizio del regno di Ioiachim [609 a.C.], Dio ha detto a Geremia di profetizzare la distruzione di Gerusalemme se non si sarebbero ravveduti. I capi religiosi volevano ucciderlo, i capi politici lo hanno protetto.</p>
<p><b>Ger 36:1-8</b> 4&deg; anno di Ioiachim [605 a.C.], Geremia detta tutte le profezie a Baruc</p>
<p><b>Ger 36:9-19</b> 5&deg; anno di Ioiachim [604 a.C.], Baruc legge le profezie al popolo e poi ai capi</p>
<p><b>Ger 36:20-26</b> Vengono lette al re, che brucia il rotolo; vuole arrestare Geremia e Baruc ma Dio li nasconde</p>
<p><b>Ger 36:27-32</b> Dio dice di scrivere le profezie di nuovo e che punir&agrave; il re</p>
<p>[597 Gerusalemme sconfitta, Ioiachim deportato]</p>
<p><b>Ger 37:1-3</b> Sedechia [588 a.C.] chiede che Geremia preghi per loro, ma non ascolta Dio</p>
<p><b>Ger 37:4-10</b> Geremia &egrave; libero, e c'&egrave; una pausa dell'assedio perch&eacute; gli Egizi sono venuti</p>
<p><b>Ger 37:11-15</b> Geremia esce da Gerusalemme per andare al suo paese, ma &egrave; arrestato come disertore</p>
<p><b>Ger 37:16-21</b> Il re ascolta Geremia di segreto, e lo trasferisce da una prigione sotterranea al cortile della prigione</p>
<p><b>Ger 32:1-5</b> 10&deg; anno di Sedechia [inizio 587 a.C.], Geremia profetizza la distruzione di Gerusalemme</p>
<p><b>Ger 32:6-15</b> Dio comanda a Geremia di comprare un campo, perch&eacute; ci sar&agrave; il ritorno al paese</p>
<p><b>Ger 32:16-25</b> Geremia &egrave; perplesso per questo ordine</p>
<p><b>Ger 32:26-35</b> Dio ribadisce che Gerusalemme sar&agrave; distrutto</p>
<p><b>Ger 32:36-44</b> &hellip;ma tuttavia raccoglier&agrave; Israele che ritorner&agrave;, e si venderanno i campi</p>

<p>Gli eventi del capitolo 38 si svolgono pochi mesi pi&ugrave; tardi, subito prima della distruzione di Gerusalemme nella seconda met&agrave; del 587 a.C. (Ger 39:1-2).</p>
<p>&nbsp;</p>
<p><b>1</b> Sefatia, Ghedalia, Iucal [Ger 37:3] e Pascur [Ger 21:1], dei capi di Giuda, udirono Geremia che diceva al popolo</p>
<p><b>2-3</b> di arrendersi ai Babilonesi per vivere, altrimenti sarebbero morti nell'assedio e nella cattura della citt&agrave; [detto anche a Ger 21:9].</p>
<p><b>4</b> I capi dissero al re di fare uccidere Geremia, perch&eacute; scoraggiava i soldati e il popolo, cos&igrave; faceva loro del male.</p>
<p><b>5</b> Il re permise ai capi di fare quello che volevano, perch&eacute; non aveva potere su di loro.</p>
<p><b>6</b> Quindi i capi gettarono Geremia in una cisterna [c'erano spesso nelle case, con la forma di una pera] della prigione, dove non c'era acqua e Geremia affond&ograve; nel fango [volevano uccidere Geremia, ma non sporcarsi le mani] [i notabili furono poi uccisi Ger 39:6].</p>
<p>&nbsp;</p>
<p><b>7</b> Ebed-Melec, un eunuco [forse solo un termine per indicare un ufficiale della corte] etiope al servizio del re, ud&igrave; quello che era successo a Geremia [Dio promise di salvarlo in Ger 39:15-18].</p>
<p><b>8</b> And&ograve; dal re alla porta di Beniamino per dirgli</p>
<p><b>9</b> che i capi si erano comportati male, gettando Geremia nella cisterna dove sarebbe morto di fame, in quanto non c'era pi&ugrave; pane nella citt&agrave;.</p>
<p><b>10</b> Cos&igrave; il re ordin&ograve; ad Ebed-Melec di prendere 30 uomini e tirare su Geremia prima che morisse.</p>
<p><b>11-13</b> Cos&igrave; Ebed-Melec salv&ograve; Geremia, tirandolo su. Geremia poi rimase nel cortile della prigione.</p>
<p>&nbsp;</p>
<p><b>14</b> Il re fece condurre Geremia al tempio, dove gli chiese una cosa.</p>
<p><b>15</b> Geremia non voleva rispondere, perch&eacute; il re l'avrebbe fatto morire, e comunque non l'avrebbe ascoltato.</p>
<p><b>16</b> Il re promise di non farlo morire (ma non di ascoltarlo).</p>
<p><b>17</b> Cos&igrave; Geremia gli disse che Dio disse di arrendersi ai Babilonesi, cos&igrave; avrebbe salva la vita e la citt&agrave; non sarebbe distrutta.</p>
<p><b>18</b> Ma se non si fosse arreso, la citt&agrave; sarebbe stata distrutta e il re catturato.</p>
<p><b>19</b> Il re per&ograve; aveva paura dei Giudei che si erano gi&agrave; arresi ai Babilonesi, che loro l'avrebbero maltrattato.</p>
<p><b>20</b> Geremia lo assicur&ograve; che non sarebbe dato nelle loro mani; anzi, sarebbe andato tutto bene.</p>
<p><b>21</b> Ma se non si sarebbe arreso,</p>
<p><b>22-23</b> le donne della sua casa l'avrebbero insultato (ricordandolo che quelli che l'avevano incitato a resistere sono spariti), le mogli e i figli sarebbero catturati, il re preso e la citt&agrave; incendiata.</p>
<p><b>24</b> Il re non voleva che qualcuno sapesse quello che avevano detto, e assicur&ograve; Geremia che non sarebbe morto.</p>
<p><b>25-26</b> Se i capi gli avrebbe chiesto quello che avevano detto, Geremia doveva rispondere che aveva supplicato il re di non farlo tornare nella casa di Gionatan [che era diventata una prigione Ger 37:15].</p>
<p><b>27</b> Cos&igrave; fece Geremia.</p>
<p><b>28</b> Geremia rimase nel cortile della prigione fino alla cattura di Gerusalemme.</p>

<h2>Domande per la riflessione</h2>
<p>Introduzione storica (capitoli 26, 36-37, 32).</p>
<p>Che cosa diceva Geremia? Quale sarebbe stato l'effetto sul popolo?</p>
<p>Perch&eacute; i capi erano contro Geremia? Cosa hanno fatto e perch&eacute;? Come ha reagito il re?</p>
<p>Cosa ha fatto Ebed-Melec? Cosa ha fatto Dio? (Ger 39:15-18; noti il contrasto con Ger 39:6)</p>
<p>Re Sedechia: Cosa ha fatto? Quali erano le 2 obbiezioni di Geremia? A quale ha risposto il re? Quali erano le possibilit&agrave; che Geremia ha dato?</p>
<p>Perch&eacute; il re non ha ubbidito (vedi anche Ger 38:5)? Qual era la sua fine in Ger 39:6-7?</p>
<p>Geremia ha parlato da Dio nonostante le conseguenze, e sapendo che non sarebbe stato ascoltato. Che cosa gli &egrave; successo secondo Ger 39:11-14?</p>
