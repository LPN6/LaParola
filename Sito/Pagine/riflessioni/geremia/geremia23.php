<h2>Domande per la riflessione</h2>
<p>Geremia ha parole da Dio da dire ai (falsi) profeti, ma prima parla di s&eacute;. Come si sentiva (9)? Perch&eacute;? [(10), anche alcuni motivi nello studio precedente]</p>
<p>Le caratteristiche di un falso profeta (e quindi anche del vero): [Mt 7:20]</p>
<p><i>Comportamento:</i> segue l'empiet&agrave; (10-11); malvagio e travia gli altri (13-14). Quindi giudizio (12,15)</p>
<p><i>Autorit&agrave;:</i> proprio cuore (16); non nel consiglio di Dio (18,22); non da Dio (21,32); propri sogni (27); rubato (30); propria lingua (31)</p>
<p><i>Messaggio:</i> cose vane (16); pace ai giudicati (17); menzogne e inganno (26,32); paglia invece di frumento, fuoco e martello (28-29); sogni falsi che traviano (32)</p>
<p>Qual era la risposta di Geremia ai falsi profeti? (9)</p>
<p>&nbsp;</p>
<p>Il comportamento dei profeti era conforme a quello che dicevano, non erano ipocriti. [Alcune versioni in Ger 23:14 hanno "agiscono con ipocrisia" ma &egrave; meglio "vivono una menzogna", che non &egrave; ipocrisia.] Il comportamento va confrontato con la volont&agrave; di Dio. Come decidi quello che puoi o non puoi fare?</p>
<p>Quello che dici, lo sai soltanto o l'hai sperimentato incontrando Dio nella Bibbia e in preghiera? Come cambia il modo in cui testimoni? [Non per forza citando versetti, fra altro abbiamo lo Spirito Santo, ma i nostri pensieri e le nostre parole devono essere basate su quello che Dio ha rivelato.]</p>
