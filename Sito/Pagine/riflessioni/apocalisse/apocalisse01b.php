<h2>Come rispondere alla visione (17-20)</h2>
<h3>Risposta di Giovanni</h3>
<p>&Egrave; caduto come morto, perch&eacute; la visione era di un Ges&ugrave; troppo gloriosa e potente affinch&eacute; potesse rimanere in piedi davanti a lui. (Gios 5:14; Ez 1:28; <u>Dan 8:17</u>; Dan 10:15; <u>Mt 17:1-6</u>; At 26:14)</p>
<h3>Risposta di Ges&ugrave;</h3>
<p>Non doveva temere. Una ragione per non temere non &egrave; data, ma la mano su Giovanni &egrave; un segno della sua benedizione.</p>
<p>Ges&ugrave; sottolinea che &egrave; la causa e il fine della creazione (Is 44:6), che era morto ma allora viveva per sempre, che ha autorit&agrave; sulla morte.<br />
Giovanni doveva scrivere tutte queste visioni (come Ap 1:11), partendo dal mistero (cio&egrave; segreto rivelato - dopo la spiegazione non &egrave; pi&ugrave; misterioso) delle stelle e dai candelabri.</p>

<h2 id="colori">I colori dell'Apocalisse</h2>
<p>Come i numeri, anche i colori hanno spesso un senso figurativo, in greco come in italiano.
Ma non sempre i sensi figurativi sono uguali in diverse culture e lingue!</p>
<p><i>Bianco:</i> vittoria (Ap 19:11,14), a volte purit&agrave; (Ap 7:14)<br />
<i>Rosso:</i> violenza (Ap 6:4)<br />
<i>Giallastro:</i> malattia mortale (Ap 6:8)<br />
<i>Porpora, scarlatto:</i> ricchezza, opulenza (Ap 17:4)<br />
<i>Oro:</i> gloria, di valore (positivo Ap 4:4; 21:21 e negativo Ap 17:4)<br />
<i>Nero:</i> niente di particolare (Ap 6:5,12)<br />
</p>
<p>Nota che non tutti i colori sono simboli. A volte descrivono veramente una cosa.</p>

