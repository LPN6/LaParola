<b>18</b> [perch&eacute;] lui &egrave; il primo e l'ultimo (Is 44:6; 48:12), il risorto, l'eterno, e ha le chiavi della [l'autorit&agrave; sulla] morte.<br />
<b>19</b> Di nuovo, Giovanni &egrave; stato comandato di scrivere tutto ci&ograve; che aveva visto, ma anche le cose che sono e che succederanno dopo.<br />
<b>20</b> I "misteri" [cio&egrave;, le cose nascoste nel passato ma ora rivelate, conosciute]: le sette stelle sono gli angeli delle sette chiese [forse le chiese stesse, come Ap 2:1 ecc], che sono i sette candelabri.<p>
