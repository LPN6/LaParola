<h2>Introduzione alla visione (9-11)</h2>
<p><i>Chi ha ricevuto la visione, e come si descrive?</i></p>
<p>Giovanni - probabilmente l'apostolo, scrittore del Vangelo ed epistole, ma afferma di essere un fratello degli altri credenti, e che con loro soffre la tribolazione ma anche il regno e la perseveranza. [umilt&agrave;]</p>

<p>Era a Patmos (un'isola nel mare vicino alle sette chiese) (si soppone in prigione o in esilio) per la testimonianza di Ges&ugrave; (forse la testimonianza di Giovanni riguardo a Ges&ugrave;, ma se come Ap 1:2, sempre collegato alla Parola di Dio, &egrave; la testimonianza da Ges&ugrave;).</p>
<p><i>Cosa gli &egrave; successo?</i></p>
<p>Fu rapito [in realt&agrave;, non nel testo ma un'interpretazione; sarebbe "fui nello Spirito" o "diventai nello Spirito"; uno stato estatico spirituale] di domenica, e una voce potente gli disse di scrivere il contenuto delle visioni alle sette chiese. [Messaggio prima di tutto per loro, non per noi.]</p>

<h2>La visione di Ges&ugrave; Cristo (12-16)</h2>
<p>La cosa pi&ugrave; importante &egrave; l'impressione generale, e solo dopo considerare i dettagli.
Prova a disegnare quello che &egrave; descritto - aiuter&agrave; anche a ricordare l'immagine e farne tesoro.
Qual &egrave; la tua impressione del personaggio nella visione?</p>

<p>Giovanni usa il linguaggio della letteratura apocalittica, dall'Antico Testament, e di Ges&ugrave; per descrivere la sua visione.
Per ogni elemento, chiediti:<br />
1. Cosa cosa significa il simbolo? [non sempre c'&egrave; significato preciso, a volte &egrave; l'impressione che d&agrave;]<br />
2. Come ha aiutato le 7 chiese?<br />
3. Come aiuta te? (se ne fai tesoro Ap 1:3)</p>

