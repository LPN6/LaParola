<h3>L'angelo della chiesa:</h3>
<p>Gli studiosi non sono d'accordo sull'identit&agrave; dell'angelo della chiesa. Le possibili interpretazioni sono: un angelo custode della chiesa, la realt&agrave; spirituale in cielo della chiesa, il responsabile della chiesa, la chiesa stessa. Le prime due si basano sull'analogia di angeli assegnati alle nazioni in Daniele, ma il parallelo &egrave; debole. La terza considera anche il senso letterale di angelo che &egrave; "messaggero" e non sempre un essere spirituale, ma probabilmente non c'era uno responsabile per ogni chiesa e non era un messaggero (se non era semplicemente il segretario / messaggio - "al messaggero scrive questo messaggio per l'intera chiesa". La quarta corrisponde a Ap 1:7, che &egrave; quello che lo Spirito dice alle chiese, ma in Ap 1:20 le chiese e gli angeli delle chiese sono diversi.</p>
<p>In ogni caso, le lettere sono chiaramente indirizzate ai membri della chiesa, che ricevono incoraggiamenti, avvertimenti, e promesse, anche se non possiamo essere sicuri perch&eacute; usa la parola "angelo".</p>


