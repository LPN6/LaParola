<h3>Tre osservazioni:</h3>
<p>1. I falsi insegnamenti possono essere in qualsiasi tipo di chiesa, forte o debole. La cosa importante &egrave; stare vigilante, e rispondere con constanza, verit&agrave;, e amore.<br />
2. Chi si &egrave; dimostrato fedele (Smirne, Filadelfia) ha ricevuto la promessa di poca o nessuna tribolazione. Le altre chiese avevano bisogno di essere rafforzate con le prove. Anche oggi spesso sono quelli con la fede pi&ugrave; debole che subiscono pi&ugrave; prove.<br />
3. Le chiese con difficolt&agrave; esterne (Smirne, Pergamo, Filadelfia) erano quelle forte; quelle che stavano bene dal punto di vista umano (Sardi, Laodicea) erano pi&ugrave; deboli. Non possiamo scegliere le nostre circostanze, ma possiamo decidere come usarle per rafforzare la chiesa. Possiamo usare la ricchezza materiale per servire o la persecuzione per pregare di pi&ugrave;.
