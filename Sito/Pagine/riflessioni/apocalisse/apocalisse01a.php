<h1>Introduzione (Apocalisse 1:1-8)</h1>
<p>Il libro &egrave; stato scritto dall'apostolo Giovanni (Ap 1:1,4,9; 22:8) negli ultimi 20 anni del primo secolo dopo Cristo, probabilmente fra il 90 e il 95 d.C.
&Egrave; stato scritto a Patmos, dove Giovanni era prigioniero a causa della sua testimonianza (Ap 1:9), e spedito alle "sette chiese di Asia", cio&egrave; della Turchia sud-occidentale.</p>

<p>I Cristiani di queste chiese erano sotto pressione, sia dall'esterno (la persecuzione) sia dell'interno (falsa dottrina nella chiesa).
Lo scopo di <i>Apocalisse</i> &egrave; di rivelare la verit&agrave; (non nasconderla con un codice segreto) con una versione della verit&agrave; che era diversa da quello che vedevano con gli occhi.
La realt&agrave; era (ed &egrave;) che Ges&ugrave; vince, quindi i Cristiani dovevano (e devono) rimanere fedele a lui e adorarlo.</p>

<h2>Che cosa &egrave; l'Apocalisse?</h2>
<p><i>una rivelazione</i> (Ap 1:1). Nel greco, la prima parola del libro &egrave; "apocalisse". Nel linguaggio comune in italiano, "apocalisse" vuol dire "catastrofe" o "disastro", e forse pensiamo che il libro &egrave; un libro di catastrofi e non un libro di rivelazioni.
In inglese e tedesco, il nome del libro vuol dire "rivelazione". Il libro &egrave; la rivelazione di Ges&ugrave; (pu&ograve; essere quello che Ges&ugrave; rivela oppure la rivelazione che riguarda Ges&ugrave;; sono vere tutti e due).</p>
<p><i>la Parola di Dio e testimonianza di Ges&ugrave; Cristo</i> (Ap 1:2). Di nuovo, quello che Ges&ugrave; testimonia e/o la testimonianza che riguarda Ges&ugrave;.</p>
<p><i>una profezia</i> (Ap 1:3). Non (solo) nel senso di predizioni per il futuro, ma verit&agrave; da custodire nel proprio cuore nella vita attuale (Ap 19:10; 22:7).</p>
<p><i>una lettera</i> (Ap 1:4-5,11) (circolare) a sette chiese specifiche. Sicuramente c'erano altre chiese in Asia (Colosse, Troas, Ierapoli), forse le 7 rappresentano tutte. Vedi <a href="#numeri">I numeri dell'Apocalisse</a>.</p>

<h2>Origine e destinazione</h2>
<p>Dio a Ges&ugrave; attraverso un angelo a Giovanni ai servi (le sette chiese).</p>

<h2>Come ricevere il libro</h2>
<p>(Ap 1:1) le cose devono avvenire tra breve (cio&egrave;, sono certe, imminenti nel tempo di Dio)<br />
(Ap 1:3) come beatitudine<br />
(Ap 1:3) fare tesoro, cio&egrave; ricordare sempre</p>
<p>Dobbiamo aspettarci di essere benedetti mentre leggiamo il libro, se ne facciamo tesoro.</p>

<h2>Le immagini</h2>
<h3>Presente (Ap 1:4-6)</h3>
<p><i>Dio:</i> &egrave;, era, e viene (invece di sar&agrave;): sottolinea una conclusione della storia<br />
<i>Spirito Santo:</i> spirito completo (sette) di Dio<br />
<i>Ges&ugrave; Cristo:</i> fedele testimone (per esempio, giudica e combatte con giustizia Ap 19:11), primo (ma non ultimo!) risorto, che ci ama e ci ha salvati, e ci ha resi sudditi e sacerdoti.</p>
<h3>Futura (Ap 1:7-8)</h3>
<p><i>Ges&ugrave;:</i> ritorner&agrave;, sar&agrave; visibile a tutti (che non &egrave; vero ora)<br />
<i>Dio:</i> &egrave; per sempre.</p>

<p>In quali modi fare tesoro di queste immagini avrebbe aiutato i credenti perseguitati e tentati?<br />
In quali modi fare tesoro di queste immagini aiuterebbe te?</p>

<p>Preghiera finale (perch&eacute; il libro vuole che rispondiamo con l'adorazione): Apocalisse 1:5b-6.</p>

<h2 id="numeri">I numeri dell'Apocalisse</h2>
<p>In italiano, alcuni numeri hanno un senso oltre la matematica. Per esempio, 17 pu&ograve; rappresentare la sfortuna; 2 o 4 pochi (2 file di pasta, siamo in 4 gatti).
Questi sensi figurativi dipendono dalla cultura. In <i>Apocalisse</i> i sensi figurativi vengono da questo genere di letteratura, che nella Bibbia &egrave; rappresentato da Apocalisse, la seconda met&agrave; di Daniele, e alcuni altri brani, ma ci sono molti altri esempi nei testi non biblici.
I numeri che appaiono in <i>Apocalisse</i> sono:</p> 
<p>1: un breve periodo di tempo<br />
3: il mondo spirituale<br />
3&half;: 7x&half;, quindi incompleto, limitato, c'&egrave; qualcosa che dovr&agrave; ancora succedere<br />
4: la terra, la creazione<br />
5: approssimativo<br />
6: 7-1, quindi meno di perfetto, umano<br />
7: completezza, perfezione, l'essenza di una cosa<br />
10: approssimativo<br />
12: il popolo di Dio<br />
24: 12+12, quindi tutto il popolo di Dio, vecchio e nuovo<br />
42: 3&half; x12 - 42 mesi sono 3&half; anni<br />
144: 12x12<br />
666: 6 e 6 e 6 (?)<br />
1000: un lungo periodo di tempo?, un numero grande<br />
1260: 42x30 - 1260 giorni sono 3&half; anni<br />
12000: 12x1000, quindi la moltitudine del popolo di Dio<br />
144000: 144x1000<br />
200000000: moltissimi!</p>
<p>Nota che non tutti i numeri sono simboli. A volte contano veramente una cosa, per esempio Ap 1:16.</p>

<h2>Note esegetiche</h2>
<p><b>1</b> Questo libro &egrave; la rivelazione che Dio ha dato a Ges&ugrave;, che l'ha data a Giovanni mediante il suo angelo (Ap 22:16). Il contenuto &egrave; le cose che devono avvenire fra poco [non in senso temporale, ma che sono imminenti, certe; Ap 1:19; 22:6 (7,12); Lu 18:8; Rom 16:20; Dan 2:28-29,45].<br />
<b>2</b> Giovanni ha attestato tutto ci&ograve; che gli &egrave; stato rivelato.<br />
<b>3</b> Beato chi legge e ascolta (in una lettura in chiesa) il libro, e soprattutto chi crede e vive quello che &egrave; scritto (Ap 22:7) [dunque non &egrave; soltanto predizioni del futuro, ma si aspetta una risposta morale], perch&eacute; la fine era vicina [di nuovo, non temporale Ap 22:10].</p>

<p><b>4</b> Giovanni manda grazia e pace alle sette chiese di Asia [cio&egrave;, a tutta la chiesa - ce n'erano altri in Asia (Colosse, Troas, Ierapoli), ma probabilmente sette per rappresentare tutte] dal Padre (Ap 1:9; 4:8 (Ap 11:17; 16:5); Es 3:14), dai "sette spiriti" [probabilmente "spirito completo", cio&egrave; lo Spirito Santo] (Ap 3:1; 4:5; 5:6)<br />
<b>5</b> e da Ges&ugrave;, che &egrave; il fedele testimone (Ap 3:14; 19:11), il primo risorto (Col 1:18), e il governatore del mondo (Ap 19:16; Sal 89:28). A Ges&ugrave;, che ci ama e ci ha salvato dal peccato mediante la sua morte<br />
<b>6</b> e ci ha fatto diventare i suoi sudditi e sacerdoti di Dio (Ap 5:10; 20:6; 1P 2:5,9; Es 19:6; Is 61:6) siano la gloria e la potenza per sempre.<br />
<b>7</b> Ges&ugrave; ritorner&agrave; con le nuvole [la presenza divina - Es 13:21; 16:10; Mt 17:5; At 1:9], quando tutti lo vedranno. Ges&ugrave; sar&agrave; giustificato davanti a quelli che l'hanno ucciso. Tutti fanno lamenti per lui [perch&eacute; &egrave; stato ucciso ingiustamente, o perch&eacute; porter&agrave; la giustizia a tutti che sono ingiusti] (Mt 24:30; Mc 14:62; Dan 7:13; Zac 12:10).<br />
<b>8</b> Dio &egrave; l'inizio e la fine, ed &egrave; per sempre (Ap 1:4; anche Ap 21:6; 22:13); &egrave; l'Onnipotente.<p>
