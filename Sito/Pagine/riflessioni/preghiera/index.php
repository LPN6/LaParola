<h1>La preghiera</h1>
<p class="primalettera">Questi studi sulla preghiera si basano sul libro <i>Un appello per una riforma spirituale</i> di Don Carson, pubblicato da <i>Passaggio edizioni</i>.
I primi sei studi sono presi dal libro, ma ne seguono altri su altre preghiere nella Bibbia.</p>

<p>Ogni studio contiene alcuni paragrafi che creano la struttura dello studio.
Di solito sono idee prese dal libro di Carson; eventualmente una lettura della sezione appropriata del libro aiuter&agrave; a capire meglio quello che si potr&agrave; dire.</p>

<p>Il primo capitolo del libro di Carson contiene dai consigli pratici per la preghiera. Li ho separati in modo che ce ne sia uno in ogni studio,
per aver un equilibrio fra la teoria e la pratica, e per dare solo un consiglio alla volta invece di molti tutti insieme,
perch&eacute; sarebbe impossibile mettere in pratica tutti i consigli simultaneamente.
L'eccezione &egrave; nel quarto studio, che parla delle scuse per non pregare che Carson espone invece nel capitolo 7.</p>

<h2>Introduzione</h2>

<p>La preghiera &egrave; una fonte di grande benedizione, un momento in cui possiamo accogliere l'invito di Dio di venire da lui e di partecipare al suo banchetto celeste (Is 55:1).
&Egrave; quando possiamo veramente sperimentare la comunione con il nostro Creatore e Padre.
&Egrave; quando possiamo inginocchiarci in adorazione e confessione davanti alla sua santit&agrave; e quando possiamo godere la sua presenza, come un amico, perch&eacute; Ges&ugrave; ci ha aperto la via.
Ma per la stessa ragione &egrave; difficile fare degli studi sulla preghiera, perch&eacute; il nostro rapporto con Dio deve essere un motivo di meraviglia e non di studio.
Inoltre c'&egrave; il pericolo che si studi la preghiera invece di pregare!</p>

<p>La preghiera &egrave; anche potente, &egrave; il modo con cui noi possiamo avere potere nella nostra vita - non diventando potenti noi, ma utilizzando la potenza di Dio!
Giovanni 14:13-14 rivela una potenza enorme. In Efesini 6:18 &egrave; una delle due arme offensive contro Satana. In Giuda 20 &egrave; un modo per edificarsi nella fede.
Per noi &egrave; come la potenza dell'atomo, che c'&egrave; sempre stata ma fino al secolo scorso non veniva sfruttata; cos&igrave; noi abbiamo a disposizione la potenza della preghiera, ma spesso non la sfruttiamo.</p>

<p>La preghiera d&agrave; anche la tranquillit&agrave;, perch&eacute; invece di preoccuparci, dobbiamo pregare (Fili 4:6-7).
Quando in preghiera e ringraziamento consegniamo le nostre difficolt&agrave; a Dio, affinch&eacute; lui se ne faccia carico,
siamo riempiti della sua pace.</p>

<p>Anche se &egrave; difficile fare degli studi sulla preghiera, abbiamo tutti bisogno di aiuto per la preghiera, perch&eacute; la verit&agrave; &egrave; che &egrave; difficile pregare e pregare bene.
Non &egrave; sorprendente che sia difficile pregare, perch&eacute; siamo ancora pellegrini che hanno molto da imparare,
e non sperimenteremo mai la pienezza del nostro rapporto con Dio finch&eacute; non entreremo in paradiso.
&Egrave; sconcertante invece che nonostante questo invito alla comunione con Dio, questa potenza della preghiera e la pace che essa d&agrave;, noi continuiamo a pregare poco e male. 
Abbiamo bisogno di incoraggiamento per pregare di pi&ugrave;, e di insegnamenti per progredire nella conoscenza di Dio e poter cos&igrave; pregare meglio.</p>

<p>Questi studi non dicono tutto quello che c'&egrave; da dire sulla preghiera. Prendono per scontato, per esempio, che dobbiamo pregare.
Ma lo scopo principale &egrave; di aiutarci a pregare meglio, non in modo superficiale ma secondo tutta la volont&agrave; di Dio.
Il metodo per raggiungere questo scopo &egrave; di esaminare alcune delle preghiere della Bibbia per scoprire come dovremmo rivolgerci al nostro Signore.
Ci sar&agrave; anche un "angolo dei consigli" in ogni studio, con alcuni suggerimenti pratici per pregare nel modo migliore,
e che possono anche essere degli spunti per condividere con gli altri i suggerimenti che danno per la preghiera.</p>

<p>Gli studi non sono un elenco di tecniche che garantiscono una vita di preghiera perfetta: queste techniche non esistono.
La preghiera &egrave; una manifestazione di un rapporto con Dio, e non ci sono tecniche per vivere un rapporto.
Ma vogliamo ascoltare quello che la Bibbia dice riguardo alla natura di Dio e al nostro rapporto con lui, in modo di vivere nel modo giusto questo rapporto.
Anche l'angolo dei consigli contiene solo suggerimenti e non leggi; possono essere utili o meno per una certa persona in un certo momento della sua vita.</p>

</p>

