<h1>Il gran mandato (Matteo 28:16-20)</h1>

<p><i>1. Cosa impariamo dei discepoli in Mt 28:16-17?</i></p>
<p>Sono ubbidienti alla guida di Ges&ugrave;, hanno capito (dopo la risurrezione) che era pi&ugrave; di un uomo, per&ograve; c'erano ancora dei dubbi (forse si riferisce ai dubbi di Tommaso prima di vedere Ges&ugrave; risorto Gv 20:24-29).</p>

<p><i>2. Se il Figlio era onnipotente prima della sua incarnazione, e Ges&ugrave; aveva autorit&agrave; su tutto (demoni, malattia, natura, morte, eccetera), qual &egrave; il significato di "ogni potere (o meglio: autorit&agrave;) mi &egrave; stato dato in cielo e sulla terra"?</i></p>
<p>Anche se Dio &egrave; pi&ugrave; potente di tutto, c'erano e ci sono altri poteri. La loro sottomissione e sconfitta &egrave; stata assegnata a Ges&ugrave;, che regnando distrugger&agrave; ogni opposizione. 1Cor 15:24-28 lo spiega: Ges&ugrave; risorto regna adesso, mettendo tutti i suoi nemici sotto i suoi piedi (cio&egrave;, sconfiggendoli - anche se la realt&agrave; &egrave; che Dio ha gi&agrave; posto ogni cosa sotto i suoi piedi), di cui l'ultimo sar&agrave; la morte. Poi al ritorno di Cristo, quando ogni potere (che si oppone a Dio) sar&agrave; distrutto, consegner&agrave; il regno al Padre.</p>

<p><i>3. Perch&eacute; "dunque" all'inizio del versetto Mt 28:19?</i></p>
<p>Siccome Ges&ugrave; ha l'autorit&agrave; e regna su ogni autorit&agrave;, per distruggere chi si oppone a Dio, i discepoli dovevano andare e conquistare le persone (fare discepoli) per Cristo. Sicuramente la potenza di Ges&ugrave; &egrave; un aiuto nel nostro discepolato, ma il fare discepoli &egrave; prima di tutto il modo in cui la sua autorit&agrave; sui popoli e altri poteri viene esercitata.</p>

<p><i>4. Quali sono i componenti del fare discepoli? (Mt 28:19-20)</i></p>
<p>Prima di tutto, bisogna andare. Forse andare ad un altro popolo, ma anche gli italiani sono un popolo e possiamo fare discepoli di loro. Ma bisogna comunque andare da loro, uscire dai nostri gruppi di cristiani maturi e pescarli dove sono.</p>
<p>Poi, battezzare e insegnare, cio&egrave; evangelizzazione e la conversione, poi aiutare a maturare con la santificazione (bisogna imparare i comandamenti e ad osservarli). Ci sono chiese e credenti bravi ad evangelizzare ma lasciano i nuovi credenti come bambini spirituali, e ci sono chiese e credenti maturi con un ottimo insegnamento, ma poca evangelizzazione e quindi pochi nuovi discepoli. In ogni caso, c'&egrave; poco discepolato. Bisogna avere l'equilibrio di tutti e due i componenti. Potete riflettere da quale parte siamo come individui, come gruppo e come chiesa.</p>

<p><i>5. Come ci aiuta l'ultima promessa?</i></p>
<p>Rimaniamo discepoli di Ges&ugrave; per tutta la vita, che continua ad aiutarci a crescere nel rapporto con Dio. &Egrave; anche presente con noi per aiutarci mentre discepoliamo gli altri - &egrave; un compito troppo arduo per noi, ma con Ges&ugrave; lo pu&ograve; fare.</p>

<p><i>Conclusione</i></p>
<p>Abbiamo visto le diverse fasi del discepolato degli apostoli da parte di Ges&ugrave;:</p>
<ul>
<li>Vieni e vedi (4 mesi, seguiti da 2 mesi di pausa e riflessione)</li>
<li>Vieni e seguimi (10 mesi)</li>
<li>Vieni e sta con me (3 mesi, poi mandati in missione, poi altri 17 mesi)</li>
<li>Dimora in me</li>
<li>Vai con me (tutto il resto della vita)</li>
</ul>
<p>Abbiamo considerato questo discepolato come un modello, o almeno un esempio, per il nostro discepolato. Rimane per noi la sfida: questi 16 studi sono stati solo un insegnamento per noi? In quel caso, non ci aiuta come discepoli, perch&eacute; i discepoli devono essere insegnati a osservare tutte quante le cose che Ges&ugrave; ci ha comandate. E il suo comando per noi discepoli &egrave; "Andate e fate miei discepoli". Andiamo quindi e facciamo discepoli, se vogliamo completare il nostro percorso di discepolato, altrimenti rimaniamo bloccati alla fase 4. Che &egrave; bello (dimorare in Ges&ugrave;), ma non &egrave; dove Ges&ugrave; vuole che rimaniamo.</p>

