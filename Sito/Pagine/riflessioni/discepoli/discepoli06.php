<h1>Proteggere i discepoli (Marco 2:1-3:6)</h1>

<p><i>1. In quali modi il primo racconto di questo capitolo continua i temi dello studio precedente? (Mc 2:1-12)</i></p>
<p>La missione di Ges&ugrave; era di annunciare la Parola, ma guariva quando l'opportunit&agrave; si presentava - ma la guarigione spirituale (perdono) era la priorit&agrave;.</p>
<p>Ges&ugrave; ha autorit&agrave;, non solo nell'insegnamento e sui demoni, ma anche per perdonare.</p>
<p>Oltre a vedere e capire meglio il ministero di Ges&ugrave;, i discepoli hanno visto l'importanza della fede, che avrebbe aiutato il loro rapporto con Dio e Ges&ugrave;, e avrebbe aiutato quando loro avrebbe cominciato a fare discepoli (ci vuole tanta fede nell'opera di Dio per discepolare qualcuno).</p>

<p><i>2. In quali modi la chiamata di Levi (cio&egrave; Matteo Mt 9:9; 10:3; Mc 3:18) &egrave; simile alla chiamata degli altri discepoli in Mc 1:16-20 ? (Mc 2:13-14)</i></p>
<p>Era vicino al mare (non importante!)</p>
<p>Chiamato mentre era a lavoro</p>
<p>Ges&ugrave; semplicemente ordina</p>
<p>Il commando &egrave; di seguirlo</p>
<p>La risposta &egrave; immediata, lasciando tutto per seguirlo</p>

<p><i>3. Cosa aggiunge il racconto del pasto (un grande banchetto secondo Lu 5:29) da Matteo alla nostra comprensione della missione di Ges&ugrave;? (Mc 2:15-17)</i></p>
<p>Sappiamo gi&agrave; che era di predicare (Mc 1:38), chiamando a ravvedersi e a credere (Mc 1:15). Qui dice che &egrave; venuto per quelli che possono ravvedersi (perch&eacute; si riconoscono peccatori) - non sta con loro perch&eacute; approva di quello che fanno, ma perch&eacute; devono cambiare.</p>
<p>Ges&ugrave; non &egrave; contaminato dal contatto con i peccatori, ma loro sono "contaminati" da Ges&ugrave;.</p>

<p><i>4. Cosa impariamo dei discepoli (di Matteo, e degli altri) in questo racconto? (Mc 2:15-17)</i></p>
<p>Di Matteo: &egrave; la prima volta che uno dei discepoli svolge un ministero pubblico - ospita un pasto. Spesso i nuovi credenti hanno tanta voglia di condividere quello che hanno scoperto con i loro tanti amici non credenti (noi che siamo meno nuovi abbiamo spesso meno voglia e meno amici non credenti) - usiamo questa voglia e queste amicizie per far crescere il regno di Dio, e dare le prime opportunit&agrave; nel ministero al nuovo credente.</p>
<p>Degli altri: c'erano diversi cerchi - i pochi discepoli chiamati, e i molti che lo seguivano</p>
<p>C'era un'aspettativa che i discepoli facessero il portavoce di Ges&ugrave;, ma &egrave; Ges&ugrave; che risponde, forse per proteggere i discepoli che sono ancora deboli, che forse non sanno ancora rispondere.</p>

<p><i>5. Cosa impariamo della missione di Ges&ugrave;, e dei discepoli, dal racconto del digiuno? (Mc 2:18-22)</i></p>
<p>Ges&ugrave; d&agrave; gioia ai discepoli, che va espressa nella vita (ma non quando sar&agrave; tolto).</p>
<p>Ges&ugrave; introduce qualcosa di nuovo, e i vecchi modi di pensare non valgono pi&ugrave;.</p>
<p>I discepoli devono gioire di essere con Ges&ugrave;.</p>

<p><i>6. Cosa impariamo della missione di Ges&ugrave;, e dei discepoli, dai racconti del sabato? (Mc 2:23-3:6)</i></p>
<p>Ges&ugrave; d&agrave; una nuova interpretazione, diversa da quella del sistema religioso attuale, dell'Antico Testamento. Cos&igrave;, di nuovo, mostra la sua autorit&agrave;.</p>
<p>Lo pu&ograve; fare perch&eacute; &egrave; il signore del sabato, cio&egrave;, pu&ograve; decidere lui quello che &egrave; giusto fare e quello che &egrave; sbagliato fare sul sabato.</p>
<p>Ges&ugrave; &egrave; considerato responsabile per il comportamento dei discepoli.</p>

<p><b>Conclusione:</b> &egrave; necessario in questo periodo di "venire e seguire" di proteggere i discepoli - anche da altri credenti che vorranno costringere i discepoli ad entrare nei loro schemi, che devono esprimono la loro fede nello stesso modo, che devono essere inseriti nella loro struttura, che non possono provare quello che &egrave; gi&agrave; stato fatto senza successo. I discepoli vanno incoraggiati invece a fare cose nuove, a raggiungere gli amici che di solito non sono raggiunti.</p>


