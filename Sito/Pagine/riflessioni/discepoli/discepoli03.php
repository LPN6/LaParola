<h1>Persuasione creativa (Giovanni 3-4)</h1>
<p class="primalettera">In questi due capitoli ci sono due delle conversazioni pi&ugrave; conosciute dei Vangeli, con Nicodemo e la donna samaritana. Se vuoi, puoi discutere e fare qualche domanda su Gv 3:1-21 e Gv 4:7-25. Ma in questi appunti ci concentreremo sui brani che hanno a che fare con i discepoli.</p>

<p><i>1. Come si possono spiegare i movimenti di Ges&ugrave;? (Gv 3:22-23; 4:1-3)</i></p>
<p>Non &egrave; detto perch&eacute; ha lasciato Gerusalemme, ma di solito rimaneva solo per le feste religiose, quando si doveva andare al tempio.</p>
<p>&Egrave; andato nelle campagne della Giudea (la provincia di Gerusalemme) perch&eacute; c'era il fiume Giordano, e poteva (attraverso i suoi discepoli) battezzare delle persone.</p>
<p>Poi &egrave; andato in Galilea perch&eacute; i farisei avevano sentito che faceva pi&ugrave; discepoli di Giovanni e che battezzava pi&ugrave; di Giovanni (in realt&agrave; i discepoli battezzavano per lui). Suppongo che non fosse perch&eacute; aveva paura dei farisei, ma perch&eacute; non era il tempo per un confronto con i farisei (Gv 7:6-8): era il tempo per farsi vedere dai discepoli e di formarli. I discepoli non erano ancora pronti per un conflitto, per sentire la necessit&agrave; di prendere la propria croce per seguire Ges&ugrave;.</p>

<p><i>2. Che cosa hanno visto e fatto i discepoli?</i></p>
<p>Non so quanto abbiano visto di Nicodemo e di Giovanni il battista, ma Ges&ugrave; ha cominciato a coinvolgerli nel suo ministero, facendoli battezzare per lui.</p>
<p>Da una parte, Ges&ugrave; li ha protetti da un coinvolgimento troppo forte perch&eacute; non erano pronti; dall'altra parte li ha gi&agrave; coinvolti in qualcosa che erano capaci di fare.</p>

<p><i>3. Quanto hanno visto i discepoli della conversazione con la donna samaritana? (Gv 4:4-28)</i></p>
<p>Niente: sono partiti prima che la donna arrivasse, e sono arrivati prima che lei andasse ma dopo che aveva finito di parlare con Ges&ugrave;.</p>
<p>Ma il fatto che abbiamo i dialoghi con Nicodemo e con la donna vuol dire che a qualche punto Ges&ugrave; ha raccontato ai discepoli quello che &egrave; stato detto, cos&igrave; avevano l'esempio di una persuasione e un'evangelizzazione creativa, che parla secondo lo stato e i bisogni dell'altra persona.</p>

<p><i>4. Quale era la testimonianza della donna, e la sua conseguenza? (Gv 4:28-30,39-42)</i></p>
<p>"Venite a vedere" - una frase che dobbiamo ormai riconoscere. Ma c'&egrave; anche la testimonianza della conoscenza sovrannaturale di Ges&ugrave;.</p>
<p>Molti hanno creduto a causa della testimonianza personale della donna, ma di pi&ugrave; hanno creduto perch&eacute; sono andati a vedere (e cos&igrave; hanno sentito) Ges&ugrave; a cui testimoniava.</p>
<p>Cos&igrave; anche la nostra testimonianza &egrave; importante, ma a volte &egrave; pi&ugrave; efficace il "vieni a vedere" - abbiamo discusso come dire questo nella seconda domanda del primo studio.</p>

<p><i>5. I discepoli erano sorpresi che Ges&ugrave; parlasse sia con una donna sia con un samaritano. Ma &egrave; stato il momento opportuno per Ges&ugrave; iniziare ad insegnare ai discepoli. (Almeno, non c'&egrave; nessun insegnamento ai discepoli racconto nei Vangeli prima di questo.) Quali erano i punti principali del suo insegnamento? (Gv 4:32-38)</i></p>
<p>Il sostenimento viene dall'ubbidienza al Padre e compiendo la sua missione, cio&egrave;, soddisfa e d&agrave; piacere quanto il mangiare (vedi anche Dt 8:3; Mt 4:4).</p>
<p>Il mondo (anche i 'tab&ugrave;' e i disprezzati come donne e samaritani) &egrave; pronto per la 'raccolta', cio&egrave; di un nuovo rapporto con Dio attraverso Ges&ugrave;.</p>
<p>Altri hanno cominciato la missione (quelli dell'Antico Testamento e/o Giovanni il battista), i discepoli devono completare questa opera e riceveranno una ricompensa.</p>

<p><i>6. Perch&eacute; l'ha detto in quel momento ai discepoli?</i></p>
<p>Vedendo Ges&ugrave; parlare con una donna samaritana, che attirava persone (come Nicodemo e i Samaritani) a s&eacute; come il Messia, dovevano capire che non era un tipico rabbino seguito da un gruppo di discepoli. Aveva una missione globale (per ogni tipo di persona, da Nicodemo a donne samaritane), e loro dovranno fare parte di questa missione come hanno gi&agrave; battezzato.</p>

<p>Questo sembra la fine della prima parte della formazione dei discepoli, la fase "vieni a vedere", che &egrave; durato circa 4 mesi. (I discepoli o altri seguaci non sono menzionati nel Vangelo di Giovanni da Gv 4:43 a Gv 5:47.) Almeno in parte, hanno visto come &egrave; Ges&ugrave;, hanno capito la sua missione e il loro ruolo. Ges&ugrave; li ha lasciati con un invito in sospeso. Adesso dovevano pensarci un po', per dare tempo affinch&eacute; questi semi crescessero in convinzione, per rispondere alla domanda implicita: Voglio ritornare alla vita di prima, oppure fare parte della raccolta? Poi fra almeno 2 mesi Ges&ugrave; li avrebbe chiamato ad un impegno pi&ugrave; grande (di circa 10 mesi) con una nuova fase di formazione, la fase "vieni a seguirmi", che inizieremo a vedere la prossima volta.</p>
<p>Anche noi non dobbiamo affrettare un impegno maggiore per Ges&ugrave;, deve essere una decisione ragionata e sincera piuttosto di essere presa al momento.</p>

<h2>Appendice</h2>
<p>Quello che segue &egrave; un elenco di principi e suggerimenti che sono venuti fuori dagli studi sulla fase "Vieni e vedi".</p>
<ul>
<li>Scegli le persone come tuo metodo.</li>
<li>Aiuta potenziali convertiti a prendere decisioni ferme.</li>
<li>Riconosci il tuo ministero e continua a fare quello.</li>
<li>Dai ai discepoli un assaggio di ministero.</li>
<li>Dai ai discepoli una visione di quello che potranno diventare.</li>
<li>Rendi facile il dire di no.</li>
<li>Motiva i discepoli con il metodo indiretto di essere un modello.</li>
<li>Identifica il nemico spirituale.</li>
<li>Usa un metodo flessibile di evangelizzazione.</li>
<li>Non permettere il pregiudizio di impedire al ministero.</li>
<li>Dimostra che sai dove stai andando.</li>
<li>Riconosci l'importanza del momento opportuno nel tuo ministero.</li>
<li>Sfida i tuoi discepoli a condividere la tua visione.</li>
<li>Dai ai discepoli tempo per prendere una decisione ferma.</li>
</ul>

