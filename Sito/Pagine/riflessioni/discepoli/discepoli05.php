<h1>La missione di Ges&ugrave; (Marco 1:21-45)</h1>
<p class="primalettera">Ges&ugrave; fa vedere il suo ministero, e il suo carattere, ai discepoli appena chiamati. &Egrave; vero che in Luca questi avvenimenti sono prima della chiamata (Lu 4:31-44), ma in ogni caso i discepoli probabilmente erano presenti comunque - per esempio, Ges&ugrave; va nella casa di Pietro.</p>

<p><i>1. Qual &egrave; la caratteristica dell'insegnamento di Ges&ugrave; che stupiva di pi&ugrave;? (Mc 1:21-28)</i></p>
<p>L'autorit&agrave; (Mc 1:22,27) - per l'insegnamento in s&eacute; (di solito diceva "Io vi dico..." piuttosto di "Qualcuno ha detto...", per esempio Mt 5:18,22,26,28,32,34,39,44; 7:29; era anche nuovo secondo Mc 1:27; anche costringeva una riposta da parte degli ascoltatori, non era possibile dire "Che bel discorso" e non essere cambiati come &egrave; vero di tanti insegnanti), ma anche perch&eacute; l'insegnamento &egrave; dato da qualcuno che dimostrava di avere autorit&agrave; sugli spiriti immondi.</p>
<p>Negli altri miracoli di questo capitolo, Ges&ugrave; mostra la sua autorit&agrave; anche sulla malattia.</p>

<p><i>2. Perch&eacute; Ges&ugrave; ha guarito alcuni ma non tutti? (Mc 1:29-45)</i></p>
<p>Ha guarito il lebbroso perch&eacute; si &egrave; impietosito (Mc 1:41) - non poteva venire faccia a faccia con la sofferenza senza fare qualcosa.</p>
<p>Ma mai &egrave; andato per guarire qualcuno, rispondeva sempre agli ammalati che venivano da lui. Anzi, si &egrave; ritirato da solo e poi &egrave; andato via piuttosto di continuare a guarire (Mc 1:35-38). Perch&eacute; la sua missione era di predicare (la venuta del regno di Dio) in tutta la regione (Mc 1:38,15).</p>

<p><i>3. Quali erano le priorit&agrave; di Ges&ugrave; che vengono fuori da questo brano?</i></p>
<p>Insegnamento, preghiera, evangelizzazione, compassione quando ci sono le opportunit&agrave;.</p>

<p><i>4. Mettiamoci nei panni dei discepoli. Dopo aver visto Ges&ugrave; per 4 mesi, adesso lo seguono per imparare da lui - non lezioni da un libro di testo, ma dall'esempio della sua vita e del suo ministero. Cosa hanno imparato?</i></p>
<p>Diverse cose, per esempio: come esporre la Parola e la sua potenza; la necessit&agrave; di compassione; l'importanza di tempo da solo e con Dio e non solo fare attivit&agrave;; rimanere centrati sull'obiettivo.</p>

<p><i>5. Come puoi mettere in pratica questo modo di discepolare altri nel tuo rapporto con altri credenti? Ed anche nel tuo modo di seguire Ges&ugrave; come discepolo?</i></p>
<p>Spesso &egrave; sufficiente ascoltarti per capire l'importanza e la potenza di esporre la Parola, ma spesso formazione specifica su come pu&ograve; essere un aiuto.</p>
<p>Compassione e tempo con Dio sono spesso cose che nascondiamo dagli altri (per non fa sapere alla sinistra quello che fa la sinistra, e per stare soli), ma forse dobbiamo pensare come usarli come opportunit&agrave; di discepolato.</p>

