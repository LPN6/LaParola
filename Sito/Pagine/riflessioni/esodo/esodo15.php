<h1>Dio &egrave; sommamente glorioso (Esodo 15:1-21)</h1>
<p class="primalettera">Questo capitolo ripete il contenuto del capitolo precedente, il passaggio del mar Rosso. Per&ograve; lo scopo &egrave; diverso: invece di riflettere sul significato dell'evento, &egrave; un invito a lodare Dio. Dobbiamo non solo sapere che Dio ci ha salvati, ma celebrare con gioia questa vittoria. Cos&igrave; anche noi glorificheremo il Signore per quello che &egrave; e quello che ha fatto, per gli Israeliti e per noi. Infatti, secondo Ap 15:2-3 canteremo questo brano in cielo per celebrare la vittoria di Dio sul male.</p>

<p><i>1. Leggete Es 15:19-21, e ricordate che anche noi loderemo Dio per l'esodo e per la nostra salvezza.</i></p>
<p><i>2. Leggete Es 15:1-10. Come &egrave; il rapporto fra Israele e Dio? (Es 15:2)</i></p>
<p>Yahweh &egrave; il loro Dio, e il Dio del padre (cio&egrave; di Abraamo, Isacco, Giacobbe, ...)</p>
<p>Dio &egrave; l'oggetto della loro lode, e lo esalteranno.</p>
<p>Dio la loro forza (cio&egrave; solo lui compie delle cose per loro, come la salvezza) - se pu&ograve; distruggere gli Egiziani, pu&ograve; vincere contro tutti</p>
<p>Dio li ha salvati. Infatti l'esodo &egrave; la prima volta che la Bibbia parla di Dio che salva.</p>
<p><i>3. Che cosa hanno imparato di Dio dall'attraversata del mar Rosso? (Es 15:3-10)</i></p>
<p>Che combatte contro i suoi avversari con ira, schiacciandoli e consumandoli</p>
<p>&Egrave; forte e grande</p>
<p>Controlla la natura</p>
<p><i>4. In quali modi noi abbiamo lo stesso rapporto? In quali eventi o circostanze della tua vita hai imparato le stesse cose di Dio? Contro quali avversari devi ancora vedere una dimostrazione della forza di Dio?</i></p>
<p>Ogni atto di misericordia che sperimentiamo dovrebbe confermare l'affermazione, "Il Signore &egrave; la mia forza" e scaturisce in lode.</p>
<p><i>5. Glorificate e esaltate Dio per quello che avete discusso finora, con la preghiera e/o un canto.</i></p>
<p><i>6. Leggete Es 15:11-18. In quali modi le caratteristiche di Es 15:11 sono state viste nell'esodo?</i></p>
<p>Non c'&egrave; dio come lui, neanche il faraone n&eacute; gli d&egrave;i egiziani.</p>
<p>&Egrave; rimasto santo in tutte le sue azioni, togliendo qualsiasi sfida alla sua maest&agrave;</p>
<p>Ha fatto prodigi tremendi.</p>
<p><i>7. La fiducia per il futuro viene da una convinzione di quello che &egrave; successo nel passato, e della fedelt&agrave; di Dio. Cosa succeder&agrave; nel futuro per gli Israeliti, e perch&eacute; potranno affrontare tutto con sicurezza? (Es 15:14-18)</i></p>
<p>Ci saranno altri nemici. Ma Israele sa che non saranno un problema, siccome Dio ha potuto sconfiggere Egitto. Anzi, le altre nazioni hanno gi&agrave; sentito dell'esodo, e sanno che sar&agrave; un problema.</p>
<p>Israele invece sar&agrave; piantato nella sua dimora.</p>
<p>Infatti Dio ha regnato sull'Egitto, e regner&agrave; per sempre nel futuro.</p>
<p><i>8. Quali dubbi ha per il futuro? Quali sono le sicurezze che abbiamo?</i></p>
<p>La sicurezza &egrave; che Dio trionfa su tutti i suoi (nostri) avversari, e che abbiamo una dimora preparata (Gv 14:2-3).</p>
<p><i>9. Glorificate e esaltate Dio per quello che avete discusso.</i></p>


