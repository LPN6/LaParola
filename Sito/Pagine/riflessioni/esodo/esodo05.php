<h1>Dio promette (Esodo 5:1-7:7)</h1>

<p><i>1. Che cosa pensava il faraone di Dio? (Es 5:1-4)</i></p>
<p>Non ha riconosciuto il SIGNORE (Yahweh) come Dio (o uno dei suoi d&egrave;i), e quindi non gli doveva ubbidire.</p>
<p><i>2. Quali erano le conseguenze del primo incontro fra Mos&egrave; e il faraone? (Es 5:5-21)</i></p>
<p>Il faraone ha fatto gli Israeliti lavorare di pi&ugrave;, siccome (secondo lui) avevano troppo tempo libero per pensare ai sacrifici - erano troppo pigri.</p>
<p>Siccome non potevano fare il lavoro imposto, i sorveglianti israeliti sono stati percossi.</p>
<p>I sorveglianti hanno criticato Mos&egrave; e Aaronne per averli messi in cattiva luce, dando una scusa agli Egiziani per ucciderli.</p>
<p><i>3. Come ha risposto Mos&egrave; a questi eventi? (Es 5:22-23)</i></p>
<p>Lamentandosi a Dio che le cose erano peggiorate, che Dio non aveva liberato come aveva promesso, e che ha mandato Mos&egrave;.</p>
<p><i>4. Pu&ograve; capitare che facciamo qualcosa per Dio (o qualcosa che Dio comanda), e non va come speriamo, anzi potrebbe peggiorare la situazione. Per esempio organizzare un evento evangelistico a cui nessuno viene oppure il relatore &egrave; pessimo, parlare con un amico di Ges&ugrave; che lo fa allontanare. Potete pensare di esempi concreti nella vostra vita? Come vi siete sentiti dopo?</i></p> 
<p><i>5. Come ha risposto Dio a Mos&egrave;? (Es 6:1-8)</i></p>
<p>Pi&ugrave; o meno come aveva detto al prugno ardente. Di solito non abbiamo bisogno di nuove promosse, ma di fidarci delle promesse che abbiamo.</p>
<p>Una promessa che faraone sar&agrave; costretto dalla potenza di Dio a lasciar andare gli Israeliti.</p>
<p>Dio &egrave;: dice "Io sono 'Io sono'" (4 volte in questi versetti), e Israele &egrave; il suo popolo con cui ha fatto un patto di dare il paese di Canaan.</p>
<p>Ha sentito le grida degli Israeliti, e si &egrave; ricordato (cio&egrave; ha deciso di agire) del patto.</p>
<p><i>6. Come possono queste affermazioni aiutarci in situazioni come quelle della domanda 4?</i></p>
<p><i>7. Come hanno risposto gli Israeliti al messaggio da Dio? (Es 6:9)</i></p>
<p>Non hanno creduto.</p>
<p><i>8. Vi &egrave; mai successo che lo scoraggiamento ha offuscato la potenza e le promesse di Dio?</i></p>
<p><i>9. Come ha risposto Mos&egrave; al messaggio da Dio? (Es 6:10-13,28-30)</i></p>
<p>Anche lui ha creduto poco, siccome gli Israeliti non credevano e non sapeva parlare.</p>
<p>Abbiamo saltato la genealogia (Es 6:14-27), ma uno suo scopo &egrave; di collegare Mos&egrave; con il Dio d'Abraamo, Isacco e Giacobbe, perch&eacute; sono discendenti di Levi il figlio di Giacobbe.</p>
<p><i>10. Che cosa &egrave; nuovo nell'ultimo comando di Dio a Mos&egrave; di parlare al faraone? (Es 7:1-7)</i></p>
<p>Mos&egrave; sar&agrave; come Dio a faraone, e Aaronne il suo profeta.</p>
<p>Dio indurir&agrave; il cuore del faraone (ne parleremo nei prossimi studi).</p>
<p>Dio far&agrave; tanti segni e prodigi, e grandi atti di giudizio.</p>
<p>Il faraone non ascolter&agrave;. Quindi Mos&egrave; aveva ragione in Es 6:12,30! La mancanza di una risposta non vuol dire che &egrave; fuori del piano o della volont&agrave; di Dio, forse &egrave; proprio il cuore indurito che Dio vuole per compiere i suoi propositi. Noi dal nostro punto di vista possiamo dire che qualcosa &egrave; andato bene solo se vediamo la risposta giusta, per esempio un evento evangelistico se diversi credono in Ges&ugrave;.</p>
<p>Gli Egiziani sapranno che "io sono 'io sono'" - il contrario di Es 5:2.</p>
<p><i>11. Ritorniamo all'ottima domanda di Mos&egrave; in Es 5:22-23. Se Dio ha mandato Mos&egrave; a liberare il suo popolo, perch&eacute; le cose sono peggiorate? &Egrave; inteso che Dio le ha fatte peggiorare - Mos&egrave; chiede, "perch&eacute; [tu] hai fatto del male a questo popolo"?</i></p>
<p>Lo scopo di Dio &egrave; di farsi conoscere. Al faraone, come il Dio di tutto e quindi anche di faraone. Dio doveva permettere a faraone di fare il peggio che poteva, per mostrare di essere pi&ugrave; potente di un faraone potente. Ma anche agli Israeliti, come il Dio che libera anche dalla situazione pi&ugrave; estrema, anche quando i liberati non credono in lui (Es 6:9).</p>
<p>In pratica, liberare degli schiavi sarebbe stato troppo facile e non avrebbe mostrato abbastanza della potenza di Dio. Doveva liberare degli schiavi angosciati e oppressi pi&ugrave; di normale, che non credevano nella sua potenza.</p>
<p>Similmente con noi: Dio ha scelto di creare un popolo da noi mentre eravamo peccatori, increduli, morti. Solo quando era "impossibile" ed eravamo senza speranza, Dio ha mostrato la sua grande potenza liberandoci nella morte e risurrezione di Ges&ugrave; Cristo.</p>

