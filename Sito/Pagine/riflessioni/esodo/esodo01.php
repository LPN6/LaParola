<h1>Dio mantiene le sue promesse (Esodo 1)</h1>
<p><i>1. Le promesse di Dio ad Abraamo in Gen 12:1-3 hanno spinto la narrativa del racconto della sua vita. Quali erano le promesse?</i></p>
<p>Una grande nazione da lui, benedetto, nome grande, fonte di benedizione, tutti benedetti in lui. Inteso (e esplicito in Gen 12:7; 13:14-17) &egrave; il possesso del paese di Canaan.</p>
<p><i>2. Dopo Abraamo, ci sono state tre generazioni (Isacco, Giacobbe, Giuseppe e i suoi fratelli) e poi altri 400 anni per arrivare al libro di Esodo (Gen 15:13-16; 46:3; 50:22-26). In Es 1:1-7, a che punto &egrave; l'adempimento delle promesse?</i></p>
<p>&Egrave; una grande nazione, ma non benedetto n&eacute; fonte di benedizione, e nel paese sbagliato.</p>
<p><i>3. Qual era la situazione degli Israeliti? (Es 1:8-10)</i></p>
<p>Gli Egiziani avevano dimenticato che Giuseppe aveva salvato Egitto. Avevano paura invece, siccome gli Israeliti erano numerosi, che avrebbero combattuto contro di loro.</p>
<p><i>4. Qual era la prima strategia degli Egiziani per rendere gli Israeliti meno potenti? Ha funzionato? (Es 1:11-14)</i></p>
<p>Lavori forzati, oppressione, schiavit&ugrave;, amarezza e asprezza</p>
<p>Non ha funzionato, perch&eacute; con pi&ugrave; oppressione il popolo si moltiplicava di pi&ugrave;.</p>
<p>Nota che gi&agrave; dall'inizio il faraone si oppone ai propositi di Dio, un'opposizione che crescer&agrave; sempre di pi&ugrave; nei primi 14 capitoli del libro.</p>
