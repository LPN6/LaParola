<p>Temere Dio = aver fiducia e fede in Dio e la sua Parola, odiare ci&ograve; che &egrave; contrario alla sua volont&agrave;. &Egrave; una cosa positiva, di rendere conto a Dio per le proprie azioni, non negativa di avere paura di lui.</p>
<p><i>9. Qual era la terza strategia per rendere gli Israeliti meno potenti? Ha funzionato? (Es 1:22)</i></p>
<p>Gli Egiziani dovevano buttare i neonati maschi nel fiume. Non si sa ancora se abbia funzionato, vedremo nel prossimo capitolo.</p>
