<p>Fa morire i maschi alla nascita. Non ha funzionato, perch&eacute; le levatrici non hanno ubbidito.</p>
<p><i>7. Perch&eacute; le levatrici hanno fatto cos&igrave;? Qual era la conseguenza?</i></p>
<p>Temevano Dio (Es 1:21). Conseguenze: salvezza per gli Ebrei, prosperit&agrave; per le levatrici (Es 1:20-21).</p>
<p>Questo &egrave; il primo accenno ad uno dei temi pi&ugrave; importanti del libro: Chi &egrave; il re? Dio o il faraone?</p>
