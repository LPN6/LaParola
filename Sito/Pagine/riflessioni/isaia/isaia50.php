<h1>Isaia 50:4-11</h1>

<p>In questa sezione di Isaia, che saranno ulteriori approfondimenti sul comportamento e sull'atteggiamento del servo. Per&ograve;, non &egrave; solo il Servo speciale di Dio che deve avere questo comportamento e atteggiamento, diventa anche un modello per tutti quelli che vogliono servire Dio.</p>

<p><i>In Is 50:4-9, e forse anche fino al versetto 11, il servo del Signore parla di nuovo. Come viene descritto il rapporto fra Dio e il servo, e fra il servo e gli altri, in Is 50:4-5?</i></p>

<p>Dio risveglia e apre l'orecchio del servo affinch&eacute; il servo possa ascoltare quello che Dio gli dice. Cos&igrave; Dio gli d&agrave; le parole da dire. Il servo &egrave; ubbidiente a quello che Dio gli dice.</p>
<p>Lo scopo di questa comunicazione da Dio &egrave; affinch&eacute; il servo possa dare le parole di Dio agli stanchi.</p>

<p>La fine di Is 50:4 aggiunge che non &egrave; una caratteristica solo del servo del Signore. Tutti i discepoli di Dio devono ascoltare Dio, e poi ubbidirgli per aiutare gli altri.</p>

<p><i>Dove porta questo ascolto e ubbidienza del servo? (Is 50:6)</i></p>

<p>Porta alle percosse e agli insulti.</p>
<p>Ci fa ricordare i processi di Ges&ugrave; Cristo, dove gli hanno sputato in faccia, dato dei pugni, schiaffeggiato, preso in giro, flagellato, schernito, percosso, e insultato (Mt 26:67-68; 27:26-30).</p>

<p><i>Questo atteggiamento del servo di subire gli insulti &egrave; anche quello di tutti i discepoli, secondo Mt 5:38-48; 1P 2:20-23?</i></p>

<p>S&igrave;! Rifletti su quello che vuol dire al tuo posto di lavoro, nella tua famiglia, anche nella tua chiesa, vivere questo tipo di vita di subire gli oltraggi.</p>

<p>A questo punto, dovrebbe sorgere la domanda: se Dio ha parlato al servo e il servo ha ubbidito a Dio per aiutare i deboli, come pu&ograve; questo comportamento durante gli oltraggi essere utile? Ci sono due risposte. Leggeremo di quella principale in Is 52:13-53:12, che &egrave; anche la conclusione della riflessione di Pietro in 1P 2:24-25. La seconda &egrave; che Ges&ugrave; ci ha lasciato un esempio di come reagire quando siamo deboli (1P 2:21).</p>

<p><i>Quali erano gli atteggiamenti del servo durante gli oltraggi? (Is 50:7-9)</i></p>

<p>Il servo &egrave; stato oltraggiato ma non abbattuto. Sapeva che Dio lo soccorreva e che non sarebbe stato deluso da Dio. Questo &egrave; l'atteggiamento di Paolo in 2Cor 4:7-11 - era in difficolt&agrave; ma mai disperato. La causa delle difficolt&agrave; era perch&eacute; viveva la morte di Cristo e affinch&eacute; tutto fosse attribuito a Dio.</p>
<p>Inoltre, non importava quello che gli altri pensavano di lui, se meritava di essere punito con le percosse o meno. Era importante invece il verdetto di Dio che lo giustificava e che era vicino a lui. Questo &egrave; l'atteggiamento di Paolo in Rom 8:31-39 - Dio &egrave; vicino a noi perch&eacute; nessuna avversit&agrave; pu&ograve; separarci dall'amore di Cristo, e nessuno ci pu&ograve; condannare n&eacute; accusare perch&eacute; Dio &egrave; colui che ci giustifica.</p>

<p><i>Come dobbiamo rispondere a questo messaggio dal servo? (Is 50:10-11)</i></p>

<p>Il servo &egrave; pi&ugrave; di un esempio da seguire. Non ascoltarlo porta alle conseguenze gravi.</p>
<p>Ci sono due possibilit&agrave;: temerlo, ascoltarlo, confidare in Dio (anche se siamo nelle tenebre, o nelle difficolt&agrave; o ci siamo allontanati da Dio, andiamo avanti ma nella forza del Signore), oppure tornare alla nostra ribellione e ricevere dolore da Dio.</p>

