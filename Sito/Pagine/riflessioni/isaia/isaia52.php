<h1>Isaia 52:7-12</h1>

<p><i>Come viene descritto il messaggio dei messaggeri in Is 52:7-9?</i></p>

<p><b>Buone notizie, notizie liete:</b> questo termine, in greco, &egrave; l'origine della parola &ldquo;vangelo&rdquo;, che era in italiano &ldquo;evangelo&rdquo;, cio&egrave; eu (buono) pi&ugrave; angelo (messaggio). Per questo motivo Paolo cita questo versetto come una benedizione per i Cristiani che annunciano le buone notizie di Ges&ugrave; (Rom 10:14-15).<br />
<b>Pace:</b> non la pace fra due nazioni a guerra, ma la pace con Dio che Ges&ugrave; porta, per esempio Gv 14:27; Mt 11:28-30; Rom 5:1; Col 1:20. In ebraico, &egrave; la parola shalom, cio&egrave;, essere nel giusto stato, soprattutto davanti a Dio.<br />
<b>Salvezza:</b> i Giudei erano in Babilonia, lontani da Dio. Noi eravamo nel peccato, lontani da Dio. C'era bisogno di essere salvati da una condizione e trasportati presso Dio.<br />
<b>Regno di Dio:</b> sembrava che la Babilonia regnasse; a noi pu&ograve; sembrare che regni tutt'altro (i politici, il denaro, la cultura che ci circonda) che Dio. Ma il messaggio &egrave; che Dio regna, quindi noi dobbiamo sottometterci a lui, e i suoi decreti e i suoi propositi saranno realizzati.</p>

<p>Poi ci doveva essere la gioia vedendo Dio ritornare alla sua dimora a Gerusalemme (Sion) dopo averla (temporaneamente) abbandonata, e che Dio consolava il suo popolo (Is 40:1). Cos&igrave; anche noi dobbiamo prorompere in grida di gioia perch&eacute; siamo stati consolati e salvati, e quando lo vediamo consolare e salvare altre persone.</p>

<p><i>Quali sono le caratteristiche della salvezza dei Giudei dalla Babilonia in Is 52:10-12, e quali paralleli ci sono con la nostra salvezza?</i></p>

<p>La salvezza era per il suo braccio santo, cio&egrave;, effettuata dalla sua potenza e con la sua santit&agrave;.</p>
<p>Era visibile a tutte le nazioni. Non solo l'opera di Ges&ugrave; &egrave; rivelata a tutte le nazioni (tramite i messaggeri di Is 52:9), era per tutte le nazioni (perch&eacute; salvare Israele era troppo poco Is 49:6; Lu 2:29-32).</p>
<p>Significa uscire dall'impurit&agrave;: da Babilonia per i Giudei, e per noi da ogni impurit&agrave; perch&eacute; siamo il tempo di Dio (2Cor 6:16-18, che cita questi versetti; anche Ap 18:4-5).</p>
<p>Tranquillit&agrave; nella salvezza, perch&eacute; Dio fa tutto, &egrave; presente e protegge, come noi che non dobbiamo darsi da fare per essere salvati (perch&eacute; &egrave; tutto compiuto in Cristo Ges&ugrave;), ma dobbiamo camminare con lui che &egrave; sempre con noi (Mt 28:20).</p>

