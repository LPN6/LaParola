<h1>Isaia 52:13-53:12</h1>

<p>Il servo di Dio non &egrave; solo un esempio da seguire per noi nelle sue sofferenze, ma le sue sofferenze hanno anche compiuto qualcosa. Mentre ci sono diverse interpretazioni ebraiche di questo brano per identificare il servo sofferente (per esempio un Messia gi&agrave; venuto, come Ezechia o uno che non si &egrave; rivelato; o il popolo giudeo che ha sofferto nell'esilio babilonese o nella dispersione attuale; o una parte pia della nazione), &egrave; difficile capire come la sua sofferenza porta un beneficio agli altri. Tranne nell'ultimo esempio, in cui una parte della nazione soffre al posto del resto. Come Cristiani, lo vediamo nella sofferenza di Ges&ugrave; Cristo, l'unico Giudeo perfetto, che ha sofferto non solo al posto degli altri giudei ma anche al posto di tutti. Cos&igrave; ci sono citazioni o allusioni a questo brano circa 85 volte nel Nuovo Testamento.</p>

<p><i>Qual &egrave; il contrasto fra l'aspetto del servo e il suo stato in Is 52:13-14?</i></p>

<p>L'aspetto &egrave; cos&igrave; sfigurato che molti sono sbigottiti, eppure il servo &egrave; esaltato.</p>

<p><i>Anche in Is 52:14-15 c'&egrave; un contrasto fra la reazione passata (14) e la reazione futura (15). Cosa penseranno del servo?</i></p>

<p>Invece di essere sbigottiti dal suo aspetto, lo ammiranno e non potranno dire niente contro di lui, perch&eacute; avranno capito qualcosa che non sapevano prima. Questo capovolgimento &egrave; gi&agrave; stato descritto in Is 49:7.</p>

<p><i>Il primo e dopo del servo descrivono la sofferenza (soprattutto durante il processo) e la morte di Ges&ugrave;, e poi la sua esaltazione alla sua risurrezione e ascensione alla destra di Dio. &Egrave; una buona notizia che non tutti hanno sentito o appreso. Secondo Rom 15:20-21, che cosa doveva Paolo fare come conseguenza, e qual &egrave; il nostro compito?</i></p>

<p>Paolo voleva predicare a chi non aveva udito parlare, affinch&eacute; Ges&ugrave; potesse essere conosciuto da tutti. Anche se noi (forse) non abbiamo il compito di andare dove Ges&ugrave; &egrave; sconosciuto, abbiamo il privilegio di andare dove siamo, in famiglia, al posto di lavoro, al bar, e di annunciare la gloria del Ges&ugrave; Cristo crocifisso.</p>

<p><i>Con un messaggio cos&igrave; meraviglioso, di qualcuno esaltato e reso sommamente eccelso da Dio stesso, forse ci aspetteremmo tanti che vorrebbero conoscerlo. Ma il senso di Is 53:1 &egrave; che sono pochi quelli che credono: &ldquo;Chi &egrave; quello che ha creduto? Dove &egrave;?&rdquo; Giovanni l'evangelista e Paolo lo capiscono in quel senso in Gv 12:37-41 e Rom 10:15-16. Che cosa ci dovremmo aspettare?</i></p>

<p>Che nonostante l'annuncio, il Signore si rivela come &egrave; veramente a pochi, e pochi credono in lui.</p>

<p><i>Come vengono descritte l'origine e la vita del servo in Is 53:2-3?</i></p>

<p>Era piccolo (nel senso di insignificante), anche se aveva la promessa di vita dove non c'era. Non c'era niente nel suo aspetto da attirare lo sguardo. Come una persona qualsiasi in un angolo remoto dell'impero romano, non meritava nessuna stima. Nella sua vita, era disprezzato e spregiato (dai capi, ma anche dalla famiglia e dai compaesani) e abbandonato (anche dagli amici), portava i dolori e la sofferenza. Non era venuto per salvare con l'aspetto di Rambo o di James Bond.</p>

<p><i>Perch&eacute; il servo di Dio, sostenuto da Dio, il suo eletto di cui Dio si compiaceva, con lo Spirito di Dio (Is 42:1) era un uomo di dolore e sofferenza, secondo Is 53:4-6?</i></p>

<p>Perch&eacute; portava il nostro dolore e la nostra sofferenza. Non toccavano a lui (anche se si poteva ritenere che &egrave; stata una punizione e umiliazione da Dio). In modo particolare, &egrave; stato trafitto (un riferimento alla croce) per le nostre trasgressioni, stroncato (la sua morte) per le nostre iniquit&agrave;, castigato nel nostro posto.</p>
<p>Come conseguenza, noi abbiamo pace con Dio (vedi Gv 14:27; Rom 5:1; Col 1:19-20) invece di castigo, abbiamo guarigione invece di malattia (secondo Mt 8:16-17 guarigione fisica (anche se il corpo perfetto ci &egrave; dato solo dopo la nostra risurrezione), ma secondo 1P 2:23-25 anche guarigione spirituale, il perdono dei peccati).</p>

<p><i>Come ha reagito (Is 53:7)? Come dovremmo reagire noi a simili maltrattamenti non meritati?</i></p>

<p>Si &egrave; lasciato umiliare senza aprire la bocca. Probabilmente nel senso di non reagire per difendersi, ma lo vediamo nel senso letterale ai suoi processi (Mt 26:62-63; 27:12-14; Lu 23:9).</p>

<p>Come abbiamo visto in Is 50 e in 1P 2:20-23, &egrave; un esempio che anche noi dobbiamo seguire.</p>

<p>Nota che questo &egrave; il brano che l'eunuco etiope leggeva ma non capiva (At 8:32-35). Per noi, questo capitolo di Isaia &egrave; forse familiare, ma per molti &egrave; un lieto messaggio che va spiegato (Is 52:15).</p>

<p><i>Che cosa &egrave; successo in seguito al servo (Is 53:8-9)?</i></p>

<p>&Egrave; stato arresto, condannato, e ucciso. A quelli del suo tempo, sembrava la morte di un criminale qualsiasi, senza valore, anche se era per portare i peccati.</p>
<p>Era ritenuto uno degli empi, ma invece, essendo giusto (citato in 1P 2:22), &egrave; stato contato con i ricchi (forse Mt 27:57-60).</p>

<p><i>Che cosa &egrave; successo veramente alla morte di Ges&ugrave; (Is 53:10-12)?</p></i>

<p>Prima di tutto, non era la vittoria dell'empiet&agrave;, perch&eacute; era la volont&agrave; del Signore - non di fare male, ma di compiere il pi&ugrave; grande bene tramite la malvagit&agrave; (At 2:23).</p>
<p>Nonostante il fatto che era l'opera di Dio, non era visto cos&igrave; e Ges&ugrave; era contato fra i malfattori (in generale in Lu 22:37; sulla croce fra i 2 ladroni in Mc 15:28 che per&ograve; non &egrave; contenuto in alcuni manoscritti importanti).</p>

<p>Era un sacrificio per i peccati - come i sacrifici dell'Antico Testamento, otteneva il perdono. Toglieva la nostra iniquit&agrave;, portava il peccato.<br />
Render&agrave; molti giusti.<br />
Intercede per i colpevoli.<br />
Anche Ges&ugrave; riceve alcune cose come conseguenza:<br />
- Ges&ugrave; avr&agrave; una discendenza, il suo popolo che crede in lui.<br />
- L'opera del Signore prosperer&agrave; in lui (che si vede nella storia della chiesa)<br />
- Avr&agrave; anche un premio, ossia le moltitudini (quelli che credono in lui, perch&eacute; salvare alcuni &egrave; &ldquo;troppo poco&rdquo; per lui Is 49:6), che riceveranno anche loro una parte del bottino (Rom 8:17): la salvezza, il perdono, la pace, l'opera di Dio in noi.</p>

<p>Il Signore Ges&ugrave; Cristo &egrave; stato innalzato, esaltato, e reso sommamente eccelso. Noi siamo il suo premio, e in lui abbiamo ricevuto un bottino del perdono, la giustizia, e l'intercessione da parte di chi &egrave; alla destra di Dio. Tutto questo perch&eacute; Ges&ugrave; ha sofferto per noi, per portare le nostre sofferenze.</p>

