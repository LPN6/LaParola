<h1>Isaia 42</h1>

<p>Nel capitolo 40, Dio ha consolato il suo popolo affermando la sua grandezza e la sua sovranit&agrave;. Nel capitolo 42, Dio inizia a spiegare come avrebbe aiuto i Giudei in esilio, un aiuto che sarebbe esteso a tutto il mondo. Dio aiuta con il servizio.</p>

<p><i>Qual &egrave; il rapporto del servo con Dio (Is 42:1-4)?</i></p>

<p>Il servo &egrave; prima di tutto il servo di Dio, il suo eletto di cui si compiace. C'&egrave; un'eco dell'ultima descrizione in quella che la voce celeste afferma di Ges&ugrave; al suo battesimo e alla sua trasfigurazione (Mt 3:17; 17:5).</p>
<p>Dio lo sostiene e mette il suo Spirito su di lui. Lo Spirito su di lui &egrave; profetizzato anche in Is 11:2; 61:1, e in Ges&ugrave; &egrave; stato visto al suo battesimo (Mt 3:16).</p>
<p>Tutto questo indica un rapporto particolare con Dio, di cui Ges&ugrave; ha le qualit&agrave;.</p>

<p><i>Quali sono le caratteristiche del servo (Is 42:1-4)?</i></p>

<p>Umilt&agrave; e gentilezza, non far&agrave; male al debole.</p>
<p>Per&ograve;, non si arrender&agrave; fino a quando avr&agrave; compiuto il suo compito.</p>

<p><i>Che cosa &egrave; il compito del servo (Is 42:1-4)?</i></p>

<p>Manifestare la giustizia alle nazioni e secondo la verit&agrave;, e stabilire la giustizia sulla terra.</p>
<p>Secondo Is 11:3-4, questa include la giustizia sociale, diffendendo i deboli e i poveri, anche punendo l'empio - la gentilezza non vuol dire accettare l'ingiustizia. Per&ograve;, l'aspetto globale del compito del servo qui indica che il servo manifester&agrave; e stabilit&agrave; una giustizia in senso pi&ugrave; largo, con tutta la giustizia di Dio, incluso una vita in un giusto rapporto con lui.</p>

<p><i>Chi &egrave; il servo di Dio?</i></p>

<p>Il termine pu&ograve; essere usato in senso generale, di chiunque opera per Dio, come Isaia (Is 20:3) e Eliachim, un ufficiale del re Ezechia (Is 22:20). Per&ograve;, in questi capitoli ha un senso pi&ugrave; specifico, di colui che adempie i propositi di Dio. In primo luogo, &egrave; la nazione di Israele, il scelto servo di Dio (Is 41:8-9), che doveva portare la giustizia di Dio a tutte le nazioni. Per&ograve;, Israele non ci &egrave; riuscito, in parte per il loro peccato. Infatti, il servo doveva anche ricondurre Israele a Dio (Is 49:5-6) - il servo di Dio aveva bisogna del Servo di Dio.</p>
<p>Cos&igrave; Ges&ugrave; Cristo, il vero popolo di Dio, adempie pienamente il ruolo del servo di Dio. Lo vediamo, per esempio, in Mt 12:14-21. Ges&ugrave; guarisce (un tipo di giustizia), ma non reagisce all'opposizione e chiede di non far udire quello che fa.</p>

<p><i>In quali modi il servo di Dio compie il suo compito (Is 42:5-7)?</i></p>

<p>Dipendendo dal Dio Creatore e Sostenitore dell'universo e della vita, e seguendo la sua guida.</p>
<p>Diventa il patto del popolo di Dio (in lui Dio promette di essere fedele al suo popolo, e in lui loro promettono di ubbidire a Dio) e luce per le nazioni (rivela la giustizia di Dio; Lu 2:32; At 13:47; 26:23).</p>
<p>Guarisce e libera gli oppressi (simile a Mt 11:4-5, che &egrave; per&ograve; una citazione di Is 35:4-6).</p>
<p>Il modo esatto in cui il servo compie il suo compito viene approfondito nei capitoli seguenti.</p>

<p><i>Quali sono le caratteristiche di Dio che sono l'oggetto di lode da parte di tutte le nazioni (Is 42:8-12)?</i></p>

<p>Yahweh, il Dio di Israele, &egrave; l'unico che va glorificato. E sicuramente non gli idoli.</p>
<p>Quello che ha detto nel passato &egrave; successo, e predir&agrave; anche quello che succeder&agrave; nel futuro.</p>

<p><i>Cosa far&agrave; Dio (Is 42:13-17)?</i></p>

<p>Trionfer&agrave; come un guerriero, dopo aver aspettato per la sua pazienza (altrimenti tutti sarebbero stati sterminati prima di essere salvati 2P 3:9,15).</p>
<p>Devaster&agrave; il paese e non aiuter&agrave; gli idolatri, ma prender&agrave; cura dei ciechi (che probabilmente stanno per tutti i deboli; &egrave; simile ai versetti Is 42:3,7).</p>

<p><i>I versetti Is 42:18-25 parlano di Israele, il servo imperfetto. Come viene descritto in Is 42:18-20?</i></p>

<p>Come sordi e ciechi, perch&eacute; non ascoltano Dio, pur avendo un rapporto special con lui, pur avendo visto tante opere di Dio a cui non hanno fatto caso.</p>
<p>Questo ci deve fare riflettere. Ancora oggi &egrave; possibile fare parte del popolo di Dio, ma non ascoltarlo e prendere alla leggera le grandi cose che abbiamo visto Dio fare nella nostra vita.</p>

<p><i>Come ha risposto Dio a questo servo imperfetto (Is 42:21-25)?</i></p>

<p>Israele compiace al Signore (come descritto in Is 42:1). Non perch&eacute; il popolo era bravo, ma perch&eacute; Dio voleva magnificare la sua giustizia e la sua legge. Cos&igrave; il popolo era spogliato, pur rimanendo il suo servo prediletto. Era spogliato da Dio, non dalla Babilonia, nel senso che Dio ha lasciato alla Babilonia di saccheggiarlo, e Babilonia ha eseguito l'ira di Dio.</p>
<p>Di nuovo, deve fare riflettere a noi che siamo in avvenire (Is 42:23). Possiamo essere disciplinati per i nostri errori, ma la grazia e la gloria di Dio superano il nostro peccato.</p>

<p>Quello che &egrave; chiaro &egrave; che ci voleva un servo migliore - migliore di Israele, ma anche migliore di noi, che falliamo altrettanto. Per questo noi abbiamo il Signore Ges&ugrave; Cristo, per cui lodiamo (Is 42:10-12) e siamo umili (siamo come Is 42:18-20). Ma poi cerchiamo di essere un servo di Dio come lo &egrave; Ges&ugrave;, manifestando la giustizia, con gentilezza, umilt&agrave; e dipendenza dal Creatore e Sostenitore, e senza arrenderci (Is 42:2-5).</p>

