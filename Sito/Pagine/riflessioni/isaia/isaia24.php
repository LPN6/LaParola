<h1>Isaia 24-25</h1>
<p class="primalettera">Dopo la descrizione del regno del Messia e la conseguente lode nei capitoli Is 11-12, ci sono 11 capitoli che raccontano il giudizio contro delle nazioni specifiche: Babilonia, Assiria, Filistea, Moab, Siria, Egitto, Etiopia, Edom, Arabia, Giuda, e Tiro. Poi i capitoli Is 24-27 parlano del giudizio sulle nazioni in generale, del ritorno di Ges&ugrave; Cristo, con anche alcuni brani di adorazione.</p>

<p><i>Quali sono le parole usate per descrivere il giudizio in Is 24:1-13?</i></p>

<p>Terra: deserta, vuota, desolata (come Gen 1:2 - la terra &egrave; disfatta, nel senso di ritornare allo stato prima che Dio la riempisse); in lutto, langue, spossata (come Rom 8:22, ma non si riferisce alla stessa cosa); maledetta</p>
<p>Persone: universale (Is 24:2), trasgressori (Is 24:5), pochi (Is 24:6), senza gioia (Is 24:7-9,11)</p>

<p><i>Quali sono i due gruppi di persone descritti in Is 24:14-20?</i></p>

<p>Nonostante la desolazione, c'&egrave; ancora un resto o residuo di superstiti che vuole glorificare Dio.</p>
<p>Ma ci sono anche i perfidi, per cui ci sar&agrave; ancora la punizione (fossa e laccio, cateratte aperte come al diluvio universale Gen 7:11, terra scossa).</p>

<p><i>Che cosa aggiunge Is 24:21-23 a questa descrizione del giudizio?</i></p>

<p>La punizione &egrave; non soltanto sulla terra, ma anche sugli esseri celesti. Tutti i ribelli saranno rinchiusi in prigione in attesa della punizione. (1P 3:19; 2P 2:4; Giuda 6 parlano di spiriti in prigione, ma sono in prigione dal tempo di No&egrave;. Ap 20:1-3,7-10 descrive una prigionia millenaria di Satana, dopo di cui &egrave; rilasciato ma subito giudicato.)</p>
<p>Il sole e la luna saranno vergognati (forse perch&eacute; adorati nell'antichit&agrave;), e daranno meno luce, soprattutto in confronto con lo splendore della gloria del Signore (come Mt 24:29 (che si riferisce a Is 13:10; 34:4; Gioele 2:10,31), Is 60:19-20; Ap 21:23) in presenza dei suoi anziani, che rappresentano il suo popolo (come in Es 24:9-10; Ap 4:4).</p>

<p>&Egrave; impossibile unire questi tre descrizioni di giudizio, con la lode in mezzo, in una struttura cronologica. &Egrave; meglio capirle come descrizioni con immagini diverse del giudizio forte di Dio, che poi si manifesta in diversi momenti. Per&ograve;, le immagini sottolineano diversi aspetti del giudizio:<br />
Il giudizio sulla terra, che ritorna allo stato originale, a causa del peccato. Si &egrave; manifestato, per esempio, nel giudizio del paese di Giuda a mano dei Babilonesi.<br />
Il giudizio sulle persone, che per lo pi&ugrave; perdono la gioia (le cose belle della terra vengono da Dio), ma un resto rimane per lodarlo nonostante il fatto che il peccato rimane.<br />
Il giudizio sugli esseri spirituali, che &egrave; in parte passato (anche in Cristo Col 2:15) e in parte futuro.<br />
Il giudizio universale (come i versetti Is 24:1,18-19,23), dopo cui rimane solo la gloria di Dio.</p>

<p><i>Per quali motivi potresti lodare Dio dopo aver letto il capitolo 24?</i></p>

<p>Alcune possibilit&agrave; sono la sua giustizia, i suoi propositi e disegni perfetti, la sua potenza per vincere il male, il regno glorioso in mezzo al suo popolo.</p>

<p><i>Per quali motivi Isaia loda Dio in Is 25:1-5, dopo la rivelazione del capitolo 24?</i></p>

<p>Probabilmente alcuni motivi sono simili a quelli della tua risposta nella domanda precedente:</p>
<ul>
<li>fa cose meravigliose (Is 25:1);</li>
<li>i suoi disegni, concepiti nel lontano passato, sono fedeli e stabili, cio&egrave; sicuramente si eseguiranno (Is 25:1) - nel caos della vita, anche nella sconfitta come era il caso per i Giudei, &egrave; buono lodare per darti il giusto punto di vista;</li>
<li>distrugge chi si oppone a lui (Is 25:2) - qui rappresentato da una citt&agrave; (che &egrave; spesso identificata con Babilonia come rappresentativa della malvagit&agrave; umana, ma la Babilonia non era ancora un potere nel Medio Oriente);</li>
<li>&egrave; una fortezza per il debole perch&eacute; i malvagi non possono spostare Dio (Is 25:4-5) - anche se i Babilonesi renderanno la terra deserta, Dio &egrave; il rifugio del resto e i Babilonesi non vinceranno. &Egrave; un rifugio da lodare anche per noi, se capiamo che noi siamo deboli ma lui &egrave; potente; un rifugio nelle persecuzioni, nelle tentazioni, negli attacchi di Satana, nei sensi di colpa, e cos&igrave; via.</li>
</ul>

<p>Per tutto questo, il popolo forte (di Dio) lo glorifica, ma le (altre) nazioni potenti lo temono (Is 25:3).</p>

<p><i>Anche se in questi due capitoli c'&egrave; un contrasto fra il popolo di Dio (i Giudei) e le altre nazioni, e gli undici capitoli precedenti hanno raccontato il giudizio sulle altre nazioni, c'&egrave; anche un altro lato in Is 25:6-12. Qual &egrave;?</i></p>

<p>Che le altre nazioni parteciperanno al grande banchetto che Dio prepara a Gerusalemme (monte Sion).</p>
<p>Il banchetto &egrave; un'immagine usata a volte (Es 24:11; Lu 14:15; 22:16), ma solo dopo Ges&ugrave; l'invito al banchetto &egrave; esteso ai non Israeliti (Mt 8:11), perch&eacute; bisogna togliere un velo sui loro occhi (la cecit&agrave; spirituale, come 2Cor 3:15-16, che &egrave; per&ograve; su Israele in quel brano). Noi che siamo Gentili dobbiamo sempre ricordarci che possiamo fare parte del popolo di Dio solo perch&eacute; Dio, per la sua grazia, ha tolto il velo da noi.</p>
<p>A questo punto non ci sar&agrave; pi&ugrave; la morte (diversamente da quello che alcuni affermano, la vita eterna &egrave; insegnata nell'Antico Testamento) n&eacute; le lacrime n&eacute; la vergogna, che &egrave; chiaramente adempiuta nella Nuova Gerusalemme celeste (Ap 21:4).</p>

<p>Per tutto questo lodiamo il Dio in cui abbiamo sperato (Is 25:9). Per questo possiamo impegnarci con tutto quello che abbiamo, possiamo sacrificare tutto la nostra energia e forza e beni, sapendo che tutto &egrave; stato speso bene e non invano, quello in cui abbiamo sperato trionfer&agrave; perch&eacute; fa parte dei disegni di Dio concepiti da tempo, fedeli e stabili.</p>

