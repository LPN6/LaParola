<h1>Isaia 54-55</h1>

<p>Abbiamo visto, nei capitoli precedenti, l'opera del servo del Signore. Ha restaurato il suo popolo con la sua sofferenza e morte. Adesso vediamo il significato per noi. Nel capitolo 54 ci sono tre immagini di come la grazia di Dio pu&ograve; capovolgere la situazione, e il capitolo 55 spiega come ricevere e godere questa grazia.</p>

<p><i>La sterile rappresenta Gerusalemme. In quale stato era, per essere chiamata sterile? In che modo la sua situazione sarebbe stata capovolta? (Is 54:1-3)</i></p>

<p>Isaia parla profeticamente del tempo dell'esilio di Giuda, quando sembra che non ci sia n&eacute; speranza n&eacute; futuro. Per&ograve;, Dio promette che avr&agrave; una discendenza e dovr&agrave; ristrutturare la casa per creare pi&ugrave; spazio. Il versetto &egrave; citato in Gal 4:27, riferendosi a Sara e Agar e metaforicamente ai Cristiani della grazia in confronto con quelli che seguono la legge. Per questo dovevano gioire e rallegrarsi.</p>

<p><i>L'immagine cambia a una moglie abbandonata o una vedova. Come &egrave; descritto il suo stato? (Is 54:4)</i></p>

<p>Confusa, vergognata, infame, perch&eacute; senza marito e senza possibilit&agrave; di avere figli.</p>

<p><i>Se era abbandonata o vedova, era perch&eacute; il marito non c'era pi&ugrave;. Come era suo marito? (Is 54:5)</i></p>

<p>Lo sposo era Dio stesso: il Creatore, il Signore degli eserciti, il suo Redentore, il Santo di Israele e il Dio di tutta la terra.</p>

<p><i>Come si spiega l'abbandono da parte di Dio di qualcuno a cui ha fatto delle promesse? (Is 54:6-10)</i></p>

<p>Per un breve momento di ira, Dio l'abbandonata, ma vedendo l'afflizione della donna, Dio, per la sua compassione e amore eterno, avr&agrave; piet&agrave; e la richiamer&agrave;. Promette inoltre che il suo amore non si allontaner&agrave; pi&ugrave; da Israele.</p>

<p>Questa &egrave; anche una descrizione del rapporto del Padre con Ges&ugrave;, che per un breve momento (3 giorni) &egrave; stato soggetto all'ira di Dio e abbandonato da lui, ma &egrave; stato richiamato a Dio per un amore eterno.</p>

<p>Descrive anche la conversione del Cristiano. Pur essendo creati da Dio per avere un rapporto con lui, una persona &egrave; senza Dio e soggetta all'ira di Dio, fino a quando Dio lo richiama e, grazie all'opera del servo di Dio, diventa una sposa di Cristo (Ef 5:25-27) e riceve le promesse di non essere mai abbandonata.</p>

<p>In Is 54:11-14 c'&egrave; un messaggio simile, ma con l'immagine di una citt&agrave;: era afflitta, sbattuta, e sconsolata, ma ricever&agrave; ricchezze da Dio (un'immagine ripresa in Ap 21:18-21) e istruzione (citato da Ges&ugrave; in Gv 6:45).</p>

<p><i>Che cosa viene aggiunto al messaggio, usando questa immagine? (Is 54:15-17)</i></p>

<p>Le altre nazioni possono cercare di fare la guerra contro la citt&agrave;, anche con alleanze, ma falliranno, perch&eacute; saranno alleanze senza Dio ed &egrave; Dio che decide l'esita delle guerre.</p>

<p><i>Qual &egrave; l'invito di Dio, e a chi &egrave; rivolto? (Is 55:1)</i></p>

<p>Di venire per ricevere le necessit&agrave; della vita. Quelli che non hanno niente sono quelli che devono venire; cio&egrave;, &egrave; un atto di grazie. Ci sono inviti simili in Ap 21:6; 22:17; vedi anche l'invito di Ges&ugrave; in Mt 11:28.</p>

<p><i>Come si fa a rifiutare l'invito? (Is 55:2)</i></p>

<p>Usare le proprie risorse per cibo scadente. Questa ironia &egrave; tipica nel mondo moderno, ma anche in ogni et&agrave; - di servire gli idoli che non possono darci quello che vogliono, di faticarsi per ottenere quello che non pu&ograve; darci la vera soddisfazione, che siano i beni materiali, il controllo della propria vita, la sessualit&agrave;, l'autorealizzazione, la conoscenza, i rapporti, la felicit&agrave;, la tranquillit&agrave;, o altro.</p>

<p><i>Come si accetta l'invito, e che cosa si riceve? (Is 55:3)</i></p>

<p>Porgere l'orecchio e ascoltate, che sottintende l'ubbidienza.</p>
<p>Poi ci sar&agrave; il patto eterno (quello con Davide, che suo figlio avrebbe avuto un regno eterno) e le promesse davidiche (sempre quella del figlio di Davide). Infatti, secondo At 13:34, la promessa &egrave; stata adempiuta quando Ges&ugrave;, il discendente di Davide, &egrave; stato risuscitato per regnare in eterno.</p>

<p><i>Davide e Israele non sono stati benedetti solo per il proprio beneficio, ma per quale altro motivo? (Is 55:4-5)</i></p>

<p>Per testimoniare (di Dio), per regnare sugli altri popoli (per Dio - Davide l'ha fatto in parte, ma Ges&ugrave; regner&agrave; su tutte le nazioni), e per attirare altri a s&eacute; quando vedono come Dio li ha glorificati.</p>

<p><i>Qual &egrave; il nuovo invito? (Is 55:6)</i></p>

<p>Di cercare Dio e invocarlo (cio&egrave;, dipendere da lui, chiedere il suo intervento) mentre &egrave; ancora possibile. Non &egrave; scontato, perch&eacute; &egrave; difficile per noi umani di conoscere Dio, ma si fa trovare (At 17:27), rivelandosi a noi e soprattutto manifestandosi come uno di noi in Ges&ugrave; Cristo.</p>

<p><i>Come si riceve questo invito? (Is 55:7)</i></p>

<p>Convertendosi a Dio, cio&egrave;, cambiando comportamento e ricevendo il perdono.</p>

<p><i>I versetti Is 55:8-9 iniziano con la parola, &ldquo;infatti&rdquo;, e sono quindi un motivo per cercarlo, e forse anche il modo. Qual &egrave; il motivo?</i></p>

<p>Non possiamo conoscere o comprendere i pensieri e le vie di Dio (vedi anche Rom 11:33). Per questo motivo dobbiamo cercarlo, non &egrave; una cosa che &egrave; naturale per noi. Inoltre, dobbiamo capire come lui si rivela, non dobbiamo possiamo arrivare con i nostri ragionamenti - la sua rivelazione di s&eacute; sar&agrave; vera anche se non completa.</p>

<p>Possibilmente la parola, &ldquo;infatti&rdquo;, si riferisce in modo particolare alla fine del versetto 7. Le vie di Dio sono diverse da quelle dagli uomini, perch&eacute; Dio ha piet&agrave; e perdona, per cui possiamo avere fiducia se ritorniamo a lui.</p>

<p><i>I versetti Is 55:8-9 parlano della necessit&agrave; della rivelazione di Dio per conoscerlo. I versetti Is 55:10-11 parlano della sufficienza e dell'efficacia della sua Parola. Che cosa fa?</i></p>

<p>Fa esattamente quello che Dio vuole. Dio parla per rivelarsi, ma siccome Dio opera tramite la parola (&ldquo;Dio disse&hellip; e la luce fu&rdquo;), &egrave; anche vero che quello che Dio comanda viene sempre eseguito.</p>

<p>L'annuncio della Parola di Dio ha sempre l'effetto che Dio vuole. Che non &egrave; sempre l'effetto che noi desideriamo. Anche se la sua Parola &egrave; efficace e potente, possiamo annunciarla e non vedere nessun effetto negli ascoltatori. Come pure noi possiamo ascoltare la Parola senza essere cambiati, come nella parabola del seminatore (Mc 4:3-20). Ma la nostra sicurezza &egrave; che succede esattamente quello che Dio ha deciso.</p>

<p><i>Qual deve essere la risposta a tutto questo? (Is 55:12-13)</i></p>

<p>Anche se il riferimento specifico &egrave; il ritorno dall'esilio (&ldquo;partirete&hellip; ricondotti&rdquo;), il principio &egrave; sempre valido: con gioia seguiamo la via di Dio, perch&eacute; la sua rivelazione ci &egrave; data, e questo &egrave; un motivo per glorificare Dio.</p>

