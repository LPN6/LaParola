<h1>Addins for LaParola</h1>

<p>
For more information on these addins, see the help file of the program.<br />
To install these components, use the <i>Update</i> command of the program, or click on the name of the addin, unzip the download file, and copy the files to the directory in which you installed the program. If when you click on the name, the file is opened in the browser instead of being downloaded, right click instead the name and choose to save it.
</p><p>
Per ulteriori informazioni su questi componenti addizionali, vedi il file della guida del programma.<br />
Per installare questi componenti, usa il comando di aggiornamento nel programma, oppure clicca sul nome del componente, scompatta il file scaricato, e copia i file dentro l'archivio alla cartella in cui hai installato il programma. Se, quanche fai clic sul nome, il file &egrave; aperto nel browser invece di essere scaricato, fai invece un clic con il tastro destro del mouse sul nome e scegli di salvare il file.
</p>

