<h1>Enciclopedia biblica</h1>
<p class="primalettera">Questa parte del sito contiene un'enciclopedia biblica, cio&egrave; una descrizione dei termini usati nella Bibbia.
Ci sono tutti i nomi di persone, citt&agrave;, e nazioni, ma anche molte altre parole come i mesi, i materiali, le parole straniere, e cos&igrave; via.
Questa &egrave; la stessa enciclopedia che fa parte del <a href="/programma/">programma della Bibbia</a>.</p>
<p>Questa enciclopedia pi&ugrave; essere letta e usata in diversi modi:</p>
<ul>
<li>cercando la voce desiderata su questo sito, usando le lettere o facendo una ricerca per una parola (basta digitare solo le prime lettere) nella tabella in fondo alla pagina;</li>
<li>scaricando un <a href="Enciclopedia biblica.pdf">file PDF</a>;</li>
<li>usando la collezione di note del <a href="/programma/windows.php">programma per Windows</a> (usa il comando <i>Aggiorna</i> del menu <i>Strumenti</i> per scaricarla e installarla);</li>
<li>comprare il testo per <a href="https://www.amazon.it/dp/B095ZY6RYS">Kindle</a> oppure come <a href="https://www.amazon.it/dp/B095MFR4GV">libro cartaceo</a>;</li>
<li>comprare la raccolta completa di 4 libri per <a href="https://www.amazon.it/dp/B0965RGT3G">Kindle</a> oppure come <a href="https://www.amazon.it/dp/B095PDTBSJ">libro cartaceo</a>.</li>
</ul>
<p>C'&egrave; anche un disegno che include i rapporti fra le persone in questo dizionario al sito di <a href="AG/indice.htm">Vinicio Montagnani</a>.</p>
<p><strong>Nota 1:</strong> Ogni voce ha collegamenti ipertestuali ai brani biblici che contengono il termine, ed anche alle voci di altri termini collegati.</p>
<p><strong>Nota 2:</strong> L'ortografia della Nuova Riveduta &egrave; usata per tutte le parole e in tutte le descrizioni. Ma se un nome con l'ortografia di un'altra versione &egrave; usata nella ricerca, la descrizione giusta dovrebbe essere trovata.</p>
