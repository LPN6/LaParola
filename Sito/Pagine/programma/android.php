<h1>Android</h1>
<p class="primalettera">Questo programma per il sistema operativo Android visualizza e ricerca la Bibbia e dei commentari. La versione attuale &egrave; 1.2.0. Ringrazio moltissimo Ignazio Di Napoli per il grande aiuto che mi ha dato nella creazione di questa app, scrivendo tutto il codice per l'interfaccia del programma.</p>

<h2>Installazione</h2>
<p>Il modo migliore per installare il programma &egrave; da <a href="https://play.google.com/store/apps/details?id=net.laparola">Google Play</a>.</p><img src="chart.png" height="230" width="230" alt="QR code" />
<p>&Egrave; anche possibile scaricare il <a href="/file/LaParola.apk">file APK</a> per installare il programma manualmente.</p>
<p>Il primo avvio sar&agrave; un po' lento mentre il programma prepara il testo della Bibbia, ma dopo sar&agrave; pi&ugrave; veloce.</p>

<h3>Installazione di altri testi</h3>
<p>Il file del programma che si scarica include la versione <i>Nuova Riveduta 2006</i>. Il modo pi&ugrave; facile per installare altre versioni della Bibbia &egrave; con la <i>Libreria</i> del programma - vedi le istruzioni qui sotto.</p>
<p>Per&ograve; &egrave; anche possibile fare un'installazione manuale di altri testi. Per installare altri testi, vai con il computer alla <a href="/javafile/">pagina con i file per Java</a>. Scarica i file desiderati e scompattali, per creare dei file con estensione .lpj Questi file vanno copiati nella cartella dell'Android in cui si trovano i file del programma, che dipende dal dispositivo, ma che &egrave; spesso una cartella <i>laparola</i> della memoria.
Poi &egrave; necessario riavviare il programma.</p>

<h2>Istruzioni per l'uso</h2>
<p>Descrivo qui le funzioni principale del programma. Con schermi piccoli, non &egrave; possibile visualizzare tutte le
icone dei comandi. In quel caso, puoi visualizzare gli altri comandi toccando i tre quadratini verticali (overflow).</p>
<ol>

<li><b>Visualizzare un brano:</b> Tocca il libro con tre quadratini a destra. Puoi scegliere il libro/capitolo/versetto 
da visualizzare, oppure digitare il riferimento di qualsiasi brano da visualizzare (sul tablet, dopo aver toccato la matita), anche con 
versetti non consecutivi.<br />
Durante la lettura di commentari, &egrave; possibile trovare dei collegamenti ipertestuali a brani biblici oppure ad altre
voci nel commentario.
Se &egrave; un collegamento ad un'altra voce, tocca il collegamento per aprire il testo, oppure tieni premuto il dito sul collegamento
per ulteriori opzioni.
Se &egrave; un collegamento ad un brano della Bibbia, tocca il collegamento per vedere il testo con ulteriori opzioni.</li>

<li><b>Ricerche:</b> Tocca la lente di ingrandimento, e nella casella che appare digita l'espressione di ricercare. 
Pu&ograve; essere semplicemente una parola, ma sono ammesse anche espressione pi&ugrave; complicate. Per effettuare una 
ricerca avanzata tocca il pulsante (cellulare) o la lente di ingrandimento con il "+" accanto alla casella (tablet); nella schermata troverai anche l'aiuto per 
le espressioni di ricerca.</li>

<li><b>Libreria:</b> Tocca l'icona con tre libri. Se tocchi il nome della versione della Bibbia, puoi scegliere di 
usare un'altra delle versioni installate per visualizzare il testo. Puoi anche aprire la scheda dei commentari e aprirne uno.
Se tocchi &quot;Gestione libreria&quot;, 
c'&egrave; una lista delle versioni della Bibbia e dei commentari attualmente installati e quelli che possono essere
scaricati e installati da Internet. 
Puoi anche toccare sul nome di una versione per ulteriori informazioni.<br />
I libri sono installati nella cartella che il sistema segnala per il salvataggio dei dati:
su alcuni dispositivi, questa pu&ograve; non essere la scheda di memoria esterna.
Tuttavia, il programma cerca i testi anche nella cartella "laparola" delle schede di memoria,
quindi &egrave; sufficiente spostarli manualmente. 
Le preferenze, invece, vengono lette solo dalla cartella principale e pertanto bisogna lasciarle l&igrave;.</li>

<li><b>Preferiti:</b> Puoi toccare la stella per aggiungere la pagina attualmente visualizzata ai preferiti. Per visualizzare
una pagina salvata nei preferiti, tocca la voce <i>Preferiti</i> del menu a sinistra. Per togliere una pagina dai preferiti, prima devi
aprire la pagina, toccare la stella, e poi scegliere <i>Rimuovi</i>.</li>

<li><b>Avanti/indietro:</b> Per vedere il brano o la ricerca precedenti, tocca il pulsante <i>indietro</i> dell'Android. 
Dopo sar&agrave; possibile toccare la freccia verso destra o la voce <i>Avanti</i> per ritornare al brano o alla ricerca.</li>

<li><b>Dimensione del testo:</b> Ci sono tre modi per impostare la dimensione del testo. Si possono usare i comandi
<i>Ingrandisci</i> e <i>Riduci</i> del menu; oppure si possono usare due dita sullo schermo, avvicinandole ed allontanandole;
infine si pu&ograve; toccare lo schermo due volte rapidamente, tenendo premuto la seconda volta e muovendo il dito in alto
ed in basso. Nelle <i>Impostazioni</i> del programma &egrave; possibile rimuovere alcune di queste possibilit&agrave;.</li>

<li><b>Evidenziatore:</b> Per evidenziare dei versetti, scegli la voce <i>Evidenziatore</i> dal menu.
Poi scegli uno dei quattro colori disponibili toccando l'icona della mattita. Tocca un versetto per evidenziarlo, o per rimuovere l'evidenziazione.
Infine, tocca il punto di spunta per chiedere la finestra.
In quella finestra &egrave; anche possibile visualizzare tutti i versetti evidenziati.</li>

<li><b>Sintesi vocale:</b> fa leggere il testo, usando la sintesi vocale di Android. L'impostazione predefinita &egrave; di continuare la lettura,
anche dopo la fine del capitolo. Per interrompere alla fine del capitolo, clicca il pulsante delle impostazioni
accanto al pulsante <i>Leggi</i> dopo aver aperto la sintesi vocale.</li>

<li><b>Modo notte, Ingrandisci, Riduci:</b> cambiano il colore e la dimensione del testo.</li>

<li><b>Gestione pannelli:</b> In questa finestra puoi decidere quanti pannelli di testi da visualizzare,
e se i pannelli devono essere sincronizzati fra loro.
Un altro modo per gestire i pannelli &egrave; di tenere premuto il dito su uno spazio di un testo, dove non c'&egrave; una parola.</li>

<li><b>Impostazioni:</b> cambia alcune impostazioni del programma.</li>

<li><b>Cronologia:</b> elenca le pagine aperte recentemente. Toccando il nome di una pagina, &egrave; possibile riaprirla.</li>

<li><b>Condividi:</b> Tieni premuto il dito sul testo.
Poi trascina le freccette per seleziona tutto il testo desiderato. Nel menu del programma seleziona <i>Condividi</i>, e ti sar&agrave; chiesto come vuoi condividere il testo selezionato.</li>

<li><b>Copia:</b> Tieni premuto il dito sul testo.
Poi trascina le freccette per seleziona tutto il testo desiderato. Nel menu del programma seleziona <i>Copia</i>.</li>

</ol>

