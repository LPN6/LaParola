<p>Hai solo 10 minuti? Prova in questo modo:</p>
<ol type="a">
<li>Apertura e confessione dei peccati - 1 minuto</li>
<li>Lettura della Bibbia e meditazione - 5 minuti</li>
<li>Preghiera - 3 minuti</li>
<li>Chiusura - 1 minuto</li>
</ol>
<p>Ricordati che 10 minuti sono molto migliori di niente!</p>

<p>Avrai un gran beneficio se trascorri 2-4 ore una volta al mese come un "giorno con Dio" - per esempio un sabato o una domenica. Incontra il Signore nella lettura della Bibbia, riflessione, programmazione personale, musica, meditazione, e molta preghiera.</p>

<h2>a) Apertura - 2 minuti</h2>
<p>&laquo;Sta' in silenzio davanti al Signore, e aspettalo&raquo; 
(Salmo 37:7). Sii tranquillo. Rilassati nel corpo e nella mente. Da' tutte le tue preoccupazioni e tensioni a Dio. Sii consapevole della sua presenza. Riposati nel Signore.</p>
<p>Entra nella presenza del Signore con adorazione e lode. Rifletti sulla sua grandezza e potenza (1Cronache 29:11-12). Loda Dio con le proprie parole, oppure usando testi biblici, per esempio i (Salmi 145-150). Anche gli inni e cantici di adorazione sono utili.</p>

<h2>b) Confessione dei peccati - 2 minuti</h2>
&laquo;Esaminami, o Dio, e conosci il mio cuore. Mettimi alla prova e conosci i miei pensieri. Vedi se c'&egrave; in me qualche via iniqua e guidami per la via eterna.&raquo; (Salmo 139:23-24). Lascia che la luce di Dio risplenda negli angoli della tua vita, e confessa i tuoi peccati a lui: pensieri, parole, azioni e omissioni (Daniele 9:4-10, Salmo 19:13, Giacomo 4:17). Sii il pi&ugrave; specifico possibile. Ricevi il perdono di Dio, e la sua potenza per essere cambiato (Salmi 32; 51; Isaia 1:18; Romani 12:2; 1Giovanni 1:9).

<h2>c) Lettura della Bibbia - 7 minuti</h2>
<p>Chiedi al Signore di aprire il tuo cuore e la tua mente (Salmo 119:18,130).</p>
<p>Leggi un brano dalla Bibbia. Segui un piano di lettura biblica (per esempio le <a href="/letture.php">letture quotidiane</a> di questo sito), o creane uno per te stesso. Forse &egrave; meglio iniziare leggendo tutto il Nuovo Testamento. Alterna fra i Vangeli e il resto del NT.</p>

<h2>d) Meditazione e ascolto alla voce di Dio - 2 minuti</h2>
<p>Scegli un versetto o una frase dal testo che hai letto e medita su di esso. Forse potresti memorizzarlo. Lascia che Dio ti parli. Scrivi nel tuo quaderno quello che lui ti mostra.</p>

<h2>e) Preghiera - 5 minuti</h2>
<p>Prega per te stesso. Prega per altri: la famiglia, amici, colleghi, vicini. Prega per la tua chiesa, il risveglio, missioni, cristiani perseguitati. Prega per la tua citt&agrave;, la nazione, il mondo. A volte potresti usare il giornale per aiutarti a pregare.</p>

<h2>f) Chiusura - 2 minuti</h2>
<p>Canta una canzone, o ascolta una casetta o un CD. Ringrazia Dio per la comunione con lui oggi. Chiedi la sua potenza e la sua saggezza per vivere per lui. Ripeti la verit&agrave; su cui hai meditato.</p>
