<h2>Appendice 2. Libri apocrifi o deuterocanonici</h2>
<p>
In aggiunta ai libri riconosciuti dai Protestanti come canonici che compongono la Bibbia, ci sono altri libri che ebbero origine nel periodo che va dalla fine del tempo di Malachia fino all'era cristiana. Sono chiamati i libri apocrifi o deuterocanonici dell'Antico Testamento, e mentre la Chiesa cattolica romana li include nel canone, e molti Protestanti credono che siano utili da leggere, il loro valore &egrave; chiaramente minore rispetto a quello degli altri libri. Sono:</p>
<ul>
<li>Primo Maccabei</li>
<li>Secondo Maccabei</li>
<li>Giuditta</li>
<li>Tobia</li>
<li>La sapienza di Salomone</li>
<li>Siracide (o Sapienza di Ges&ugrave; Ben-Sirac o Ecclesiastico)</li>
<li>Baruc</li>
<li>L'epistola di Geremia</li>
<li>Il cantico dei tre giovani, Susanna, Bel e il drago (aggiunte al libro di Daniele)</li>
<li>Aggiunte al libro di Ester</li>
</ul>
<p>Una simile classe di letteratura &egrave; apparsa dopo la scrittura del Nuovo Testamento. Fra i libri di questa classe possiamo nominare:</p>
<ul>
<li>I Vangeli apocrifi</li>
<li>Il pastore di Erme</li>
<li>Le epistole di Clemente ai Corinzi</li>
<li>L'epistola di Barnaba</li>
<li>Paolo e Tecala</li>
</ul>
