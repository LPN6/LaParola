<h2>Un messaggio personale</h2>
<p>
Se non sei un Cristiano, per favore leggi questa pagina con attenzione.
</p><p>
Non basta che tu sia persuaso che la Bibbia &egrave; la Parola di Dio. Non devi fermarti l&agrave;. Ricordati, &egrave; la Parola di Dio a te, individualmente, personalmente. Ha un messaggio al tuo cuore che &egrave; importantissimo.
</p><p>
Vedi, tutti gli uomini sono per natura peccatori (Romani 3:10-12). Sono persi e sotto la condanna del Dio giusto. Ci&ograve; significa anche tu. Inoltre, il salario del peccato &egrave; la morte, e questa morte &egrave; morte eterna (Romani 6:23).
</p><p>
Ma ci sono delle buone notizie per i peccatori: Ges&ugrave; Cristo &egrave; venuto nel mondo per salvare i peccatori (1Timoteo 1:15). Quando &egrave; stato appeso sulla croce di Calvario, ha pagato tutta la pena per la nostra redenzione. Nessun peccatore deve morire se accetta il Signore Ges&ugrave; Cristo come suo personale Salvatore (Romani 5:8).
</p><p>
Come puoi conoscere la gioia della salvezza? Questo &egrave; la notizia migliore di tutte. Non c'&egrave; niente da pagare, niente da fare. Puoi ricevere questa redenzione senza paragoni e senza prezzo come dono gratuito da Dio... proprio adesso (Efesini 2:8-9).
</p><p>
Fai questo: inginocchiati, rivolgiti a Dio e digli che sei un peccatore indegno e senza meriti sulla strada per la perdizione. Poi digli che proprio ora stai accettando il Signore Ges&ugrave; Cristo come tuo personale Salvatore. Digli che credi che Cristo &egrave; il Figlio di Dio, il Salvatore del mondo, e il tuo Salvatore.
</p><p>
Se fai questo sinceramente, sull'autorit&agrave; dell'immutabile Parola di Dio sarai salvato (Giovanni 1:12, 3:16, 5:24). Poi continua nelle cose di Dio. Battezzati (Atti 2:41), fai parte di una chiesa che onora Cristo (Atti 2:47), vivi quotidianamente per lui (Romani 12:1), e cerca di portare altri ai suoi piedi (Marco 16:15). Solo cos&igrave; la tua vita sar&agrave; piena di gioia inesprimibile e di gloria!
</p>
