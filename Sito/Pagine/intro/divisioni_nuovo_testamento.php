<h2>13. Le divisioni del Nuovo Testamento</h2>
<p>
Le sezioni del Nuovo Testamento sono ben conosciute. I quattro Vangeli sono biografici; gli Atti degli apostoli &egrave; un libro storico; le Epistole sono appunto epistolari; e l'Apocalisse &egrave; descrittiva e profetica.
</p><p>
I Vangeli non sono una completa biografia di Cristo; ma solo alcuni eventi della sua vita che servono per stabilire la sua affermazione di essere il Cristo e il Figlio di Dio. In essi sono contenuti anche alcuni esempi del suo insegnamento e delle sue prediche. Uno dei Vangeli dichiara che questo &egrave; il suo scopo (Giovanni 20:31), e il contenuto degli altri dimostra che hanno lo stesso scopo. Giovanni dimostra anche il carattere parziale del suo racconto e dice che se tutto quello che Ges&ugrave; fece fosse scritto, il mondo non potrebbe contenere tutti i libri che sarebbero stati scritti (Giovanni 21:25).
</p><p>
Il libro degli Atti &egrave; una storia generale della chiesa per circa 30 anni dal suo inizio; le epistole sono lettere scritte da certi apostoli, cio&egrave; Paolo, Giacomo, Pietro, Giuda e Giovanni, tutte indirizzate a chiese o a credenti singoli; e l'Apocalisse spiega principalmente il futuro della chiesa.
</p>
