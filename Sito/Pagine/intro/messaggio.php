<h1>Il messaggio della Bibbia</h1>
<p class="primalettera">Dio ci ha dato la Bibbia per un scopo ben preciso: vuole che noi lo conosciamo. Vuole darci la salvezza. Ma essendo giusto, non lo pu&ograve; fare cos&igrave;, perch&eacute; pecchiamo tutti. Nella Bibbia si scopre il piano di salvezza che Dio ha disegnato.</p>
<hr />
<h2>Quattro passi per ottenere pace con Dio</h2>

<h3>Il piano di Dio - Pace e vita</h3>
<p>Dio ti ama e vuole che esperimenti la Sua pace e la Sua vita.</p>
<p>La Bibbia dice:</p>
<blockquote><p>Perch&eacute; Dio ha tanto amato il mondo, che ha dato il suo unigenito Figlio, affinch&egrave; chiunque crede in lui non perisca, ma abbia vita eterna.<br />(Giovanni 3,16)</p></blockquote>

<h3>Il problema dell'uomo - Separazione</h3>
<p>Pace con Dio non &egrave; una cosa che otteniamo automaticamente, perch&eacute; la nostra natura ci separa da Dio.</p>
<p>La Bibbia dice:</p>
<blockquote><p>Tutti hanno peccato e sono privi della gloria di Dio.<br />(Romani 3,23)</p></blockquote>

<h3>La soluzione di Dio - La croce</h3>
<p>L'amore di Dio fa dal ponte tra Dio e te. Quando Ges&ugrave; Cristo mor&igrave; in croce e poi risuscit&ograve;, pag&ograve; anche per i tuoi peccati.</p>
<p>La Bibbia dice:</p>
<blockquote><p>Egli ha portato i nostri peccati nel suo corpo, sul legno della croce, affinch&eacute;, morti al peccato, vivessimo per la giustizia, e mediante le sue lividure siete stati guariti.<br />(1Pietro 2,24)</p></blockquote>

<h3>La risposta dell'uomo - Accettare Cristo</h3>
<p>Tu puoi oltrepassare la divisione tra Dio e l'uomo, diventando membro della famiglia di Dio se lo accetti personalmente.</p>
<p>La Bibbia dice:</p>
<blockquote><p>Ma a tutti che l'hanno ricevuto egli ha data il diritto di diventare figli di Dio: a quelli, cio&egrave;, che credono nel suo nome.<br />(Giovanni 1,12)</p></blockquote>

<p>Per accettare Cristo devi fare quattro passi:</p>
<ul>
<li>RICONOSCERE il tuo bisogno spirituale: Sono un peccatore</li>
<li>CONVERTIRTI, cio&egrave; essere pronto a rinunciare al peccato</li>
<li>CREDERE che Ges&ugrave; Cristo &egrave; morto alla croce per te</li>
<li>RICEVERE, in preghiera, Ges&ugrave; Cristo nel tuo cuore e nella tua vita</li>
</ul>
<p>Cristo stesso dice nella Bibbia:</p>
<blockquote><p>Ecco, io sto alla porta e busso: se qualcuno ascolta la mia voce e apre la porta, io entrer&ograve; da lui e cener&ograve; con lui ed egli con me.<br />(Apocalisse 3,20)</p></blockquote>
<p>Potresti pregare cos&igrave; (ma ricordati che non sono le parole che ti salvano: Dio guarda il tuo cuore e le parole non importano):</p>
<p><em>Signor Ges&ugrave;,<br />
So che sono un peccatore. Credo che tu sei morto per i miei peccati. Mi converto da questi e apro la porta del mio cuore e della mia vita a te. Ti accetto come mio Salvatore e Signore. Grazie che mi vuoi salvare. Amen.</em></p>
