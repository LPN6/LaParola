<h1>Suggerimenti e idee per la preghiera</h1>

<p class="primalettera">Usa queste <strong>cinque forme principali di preghiera</strong>:</p>
<ol type="a">
<li><strong>Lode e adorazione</strong>. Vedi i Salmi 145-150. Concentrati su Dio, la sua persona e le sue qualit&agrave;.</li>
<li><strong>Confessione</strong> di peccati. Vedi i Salmi 32; 51; 130. Sii completamente onesto. Esaminati con Romani 12:9-21; 1Corinzi 13:4-7; Galati 5:22.</li>
<li><strong>Ringraziamento</strong> per la bont&agrave; e le benedizioni di Dio: il cibo, vestiti, la salute, amicizie, la salvezza, il perdono, la pace, benedizioni spirituali, eccetera. Potresti usare per esempio il Salmo 103 oppure inni e canti di ringraziamento.</li>
<li><strong>Preghiera</strong> per te stesso. Porta i propri bisogni al tuo Padre celeste: decisioni, rapporti, preoccupazioni, crescita spirituale, eccetera. Chiedi il frutto dello Spirito (Galati 5:22).</li>
<li><strong>Intercessione</strong> per altri: famiglia, amici, vicini, colleghi, la tua chiesa, la tua citt&agrave;, il paese, i leader politici, missioni, cristiani perseguitati, eccetera.</li>
</ol>

<p>Se hai <strong>problemi nel concentrarti</strong>, spesso aiuta pregare ad alta voce. Anche pregare in posizioni diverse pu&ograve; aiutare: inginocchiato, seduto, sdraiato, con mani alzate, camminando, eccetera.</p>

<p>Molti di noi hanno cos&igrave; tanti motivi di preghiera che di solito non riusciamo a pregare per tutto. Se questo &egrave; vero per te, &egrave; una buon'idea <strong>distribuire i motivi di preghiera</strong> fra i diversi giorni. Potresti adattare questo semplice schema:</p>
<ul>
<li><em>Domenica:</em> Chiesa locale e nazionale, missioni</li>
<li><em>Luned&igrave;:</em> Famiglia e amici</li>
<li><em>Marted&igrave;:</em> Altre organizzazioni cristiane</li>
<li><em>Mercoled&igrave;:</em> la nazione, il mondo, la giustizia</li>
<li><em>Gioved&igrave;:</em> Te stesso e i propri bisogni</li>
<li><em>Venerd&igrave;:</em> Colleghi e vicini</li>
<li><em>Sabato:</em> Vari</li>
</ul>

<p><strong>Pregare testi biblici:</strong> Scegli 3-4 versetti biblici (per esempio dai Salmi o da Efesini) e prega una frase del brano dopo un'altra. Loda, confessa peccati, ringrazia, prega per te stesso ed altri in base alle parole e espressioni del versetto.</p>

<p>Quando <strong>mediti</strong> su un versetto biblico, potresti usare questo metodo semplice ed efficace: Sottolinea una parola alla volta e rifletti sul significato che scopri. Per esempio:</p>
<ul>
<li><em>Cercate</em> prima il suo regno.</li>
<li>Cercate <em>prima</em> il suo regno.</li>
<li>Cercate prima il <em>suo</em> regno.</li>
<li>Cercate prima il suo <em>regno</em>.</li>
</ul>

<p>Compri un <strong>quaderno</strong> e usalo come un diario spirituale. Scrivi i motivi di preghiera e ringraziamento, versetti importanti e le cose che Dio ti mostra.</p>

<p><strong>Risposte alla preghiera sono sperimentate da quelli che:</strong></p>
<ul>
<li>cercano Dio 
Geremia 29:12-14;</li><li>aspettano Dio 
Salmo 40:2;
</li><li>pregano con fede 
Matteo 21:22;
</li><li>pregano nel nome di Ges&ugrave; 
Giovanni 14:13-14;
</li><li>pregano secondo la volont&agrave; di Dio 
1Giovanni 5:14;
</li><li>osservano i comandamenti di Dio 
1Giovanni 3:22;
</li><li>hanno il cuore afflitto 
Salmo 34:18;
</li><li>restano in Cristo 
Giovanni 15:7;
</li><li>si umiliano 
2Cronache 7:14.
</li>
</ul>

<p><strong>Risposte alla preghiera sono negate a quelli che:</strong></p>
<ul>
<li>pregano con motivi sbagliati
Giacomo 4:3;
</li><li>tramano il peccato nel cuore 
Salmi 66:18;
</li><li>vivono con il peccato non perdonato 
Isaia 59:2;
</li><li>non si occupano dei poveri 
Proverbi 21:13;
</li><li>si ritengono giusti 
Luca 18:11-14.
</li>
</ul>

<p><strong>Per riflettere:</strong> 15 minuti &egrave; l'1% di 24 ore. Non &egrave; il tempo minimo che vorresti trascorrere con il Signore?</p>

<p><strong>Le cinque direzioni della preghiera:</strong></p>
<ul>
<li><em>In su:</em> loda e adora Dio.</li>
<li><em>In dietro:</em> ringrazia Dio per quello che ha fatto.</li>
<li><em>Dentro:</em> prega per te stesso e i tuoi bisogni.</li>
<li><em>Attorno:</em> prega per la famiglia e amici.</li>
<li><em>Fuori:</em> prega per la citt&agrave;, la nazione e il mondo.</li>
</ul>
