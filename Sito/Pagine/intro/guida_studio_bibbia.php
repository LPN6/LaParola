<h2>1. Definizioni</h2>
<p>
La parola <i>Bibbia</i> viene dalla parola greca <i>biblos</i>, che vuol dire <i>libro</i>. Usata come titolo, significa <i>Il Libro</i>, cos&igrave; chiamata per il modo in cui era usata dai credenti quando la Bibbia fu completata. Anche i titoli <i>Antico Testamento</i> (detto anche Vecchio Testamento) e <i>Nuovo Testamento</i> sono stati introdotti dopo che la Bibbia fu completata. I libri contenuti nella seconda sezione contengono un nuovo patto che Dio ha fatto con gli uomini, mentre quelli nella prima contengono il primo patto che fece. Infatti la parola per <i>patto</i> era tradotta <i>testamentum</i>, e a causa di questa parola, in un periodo in cui la Bibbia in latino era la pi&ugrave; letta in Europa, il titolo <i>Testamento</i> &egrave; stato usato per le due sezioni.
</p><p>
Il titolo <i>Scritture</i>, a volte con il prefisso <i>Sante</i>, &egrave; un titolo che il Nuovo Testamento usa per i libri dell'Antico Testamento. In 2Pietro 3:16 &egrave; anche usato implicitamente per le epistole di Paolo, e cos&igrave; era usato come titolo per tutta la Bibbia. La parola significa <i>scritti</i>, e in questo senso primario poteva essere usata per qualsiasi scritto; ma come l'espressione <i>Il libro</i> era usata per un libro particolare, cio&egrave; <i>la Bibbia</i>, cos&igrave; l'espressione <i>Le Scritture</i> era usata per gli scritti nella Bibbia. Quando il titolo <i>Sante</i> &egrave; aggiunto, la Bibbia &egrave; ulteriormente differenziata dagli altri scritti.
</p><p>
Gli apostoli Paolo e Pietro usano il titolo "oracoli di Dio" per i libri dell'Antico Testamento, e Stefano li chiama "oracoli di vita" (Romani 3:2; Ebrei 5:12; 1Pietro 4:11; Atti 7:38). <i>Oracoli</i> significa affermazioni di Dio; e questi libri erano cos&igrave; chiamati perch&eacute; contengono affermazioni di Dio tramite degli uomini ispirati. Sono chiamati <i>oracoli di vita</i> a causa della loro potenza, in confronto con l'impotenza degli oracoli pagani. Ma se i libri dell'Antico Testamento sono degni di questo titolo, quanto pi&ugrave; quelli del Nuovo Testamento; di conseguenza, Papia, uno scrittore cristiano del secondo secolo, usa il termine per il Vangelo secondo Matteo, dicendo, "Matteo scrisse gli oracoli". Ci&ograve; &egrave; vero soprattutto di Matteo, perch&eacute; pi&ugrave; della met&agrave; del suo libro &egrave; composto da discorsi di Ges&ugrave;. &Egrave; giusto quindi parlare dell'intera Bibbia come "gli oracoli di Dio" o "gli oracoli di vita".
</p>
